-- broadcasts에 "발사에서 소리 지시까지 얼마나 걸렸나"를 남기는 컬럼 (2026-09-03)
--
-- 왜 필요한가(사용자 신고): "시계가 12:00인데 12:01쯤에 방송한다".
-- 발사는 정시였고 이력에도 12:00으로 찍혀 있었다 — **이력의 time은 발사 시각이지 소리 시각이
-- 아니기 때문이다.** 그 사이에는 TTS 합성이 있고(실측 2.25초, 현장은 더 길고 실패하면
-- 재시도·타임아웃 60초까지), 그 지연은 이력 어디에도 남지 않아 **귀로만 알 수 있었다.**
--
-- prep_ms : 발사 시각 → 화면에 재생 지시를 보낸 시각까지의 밀리초.
--           NULL은 "안 쟀음"이다(옛 행, 그리고 TTS를 안 쓰는 유형).
--           소리가 실제로 난 시각은 브라우저만 아는데, 여기서 재는 구간이 지연의 거의 전부다
--           (SSE 전달과 브라우저 재생 시작은 밀리초 단위다).
--
-- 이 값이 남으면 "정시에 나갔나"를 사람 귀가 아니라 이력으로 물을 수 있다.
-- 캐시 우선(9438777)·미리 만들기(aeb3dd0)가 실제로 듣는지도 이 숫자로 확인한다.
--
-- 실제 반영은 server/db/schema.js initDB()의 try { ALTER TABLE ... } catch {} 블록이 한다.

ALTER TABLE broadcasts ADD COLUMN prep_ms INTEGER DEFAULT NULL;
