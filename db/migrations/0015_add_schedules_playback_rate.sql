-- schedules.playback_rate — 이 예약이 트는 음원·영상의 재생 배속. NULL이면 1.0배(원래 속도).
--
-- 왜 필요한가: 노래방 방송처럼 어르신들이 따라 부르는 방송은 원래 속도가 빠르다. 방송 때마다
-- 사람이 손으로 맞출 수는 없어서 예약에 걸어둔다. 느리게(0.5배)부터 빠르게(1.5배)까지.
-- 그 밖의 값은 말이 뭉개지거나 알아듣기 어려워서 받지 않는다.
--
-- bgm_volume(0012)·main_volume(0013)과 같은 원칙:
-- 전역 설정을 바꿨다 되돌리지 않고, 이 예약의 방송 이벤트에만 실어 보낸다.
-- 되돌리기 전에 서버가 죽거나 다음 예약이 발동하면 값이 남기 때문이다.
--
-- 적용 대상은 브라우저가 재생하는 업로드 음원(prayer_play)과 업로드 영상(video_play)이다.
-- 예약이 흐름(broadcast_type='flow')이면 흐름 안의 음원·영상 단계까지 따라간다
-- (한 예약을 두 군데서 설정하게 만들지 않는다).
-- 유튜브 TV/BGM은 iframe 쪽 배속이라 이번 범위가 아니다(사용자 확정).
