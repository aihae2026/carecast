-- 방송이 왜 실패했나 — 사유를 **코드**로 남긴다 (P-95, 사용자 승인 2026-09-10 §4)
--
-- 왜 필요한가: `broadcasts.success = 0` 은 "안 나갔다"만 말하고 **왜**를 안 말한다.
-- 그래서 지금 두 자리가 **이력 문구를 정확일치로 짝맞춰** 뜻을 읽는다:
--   · `watchdog.wasPreempted()` — 밀림이면 경보 문구를 바꾼다(P-30)
--   · `routes/status.js`·`routes/broadcasts.js` — 밀림을 오류 집계에서 뺀다(P-31)
-- 문구를 바꾸는 날 두 곳이 조용히 어긋난다. 뜻을 **문자열이 아니라 값**으로 나른다.
--
-- **최소 한 칸만 더한다.** 표를 새로 만들지 않는다 — 사유는 방송 한 건에 하나이고,
-- 그 행에 붙어 있어야 조회 한 번으로 읽힌다.
--
-- 민감정보를 안 담는다(사용자 지시): **정해진 코드만** 들어간다. 원본 오류 메시지·토큰·
-- 방송 문안을 그대로 넣지 않는다. 코드 목록은 `server/domain/broadcastRecord.js` 가 정본이다.
--
-- 기존 행은 **NULL 그대로** 둔다 — `DEFAULT NULL` 이라 ALTER 가 값을 안 채운다.
-- NULL = **"사유를 안 남기던 때의 기록"** 이고, 이것이 '기록 없음'과 '사유 있음'을 가른다.
-- **백필하지 않는다.** 과거 행의 사유는 문구로 추정할 수는 있어도 그것은 추측이다
-- (CLAUDE.md DB 규칙: DEFAULT 를 주면 기존 행이 그 값으로 채워져 IS NULL 후속 분류가 죽는다).
--
-- 이전 앱과의 호환: 옛 코드는 이 칸을 **안 읽고 안 쓴다.** SELECT * 로 읽어도 여분 필드일 뿐이고
-- INSERT 는 칸 이름을 명시하므로 그대로 돈다. 되돌리기는 `.down.sql`.

