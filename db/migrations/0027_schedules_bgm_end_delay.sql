-- TTS 가 끝난 뒤 BGM 을 몇 초 더 흘릴까 (UX-17, 2026-09-11)
--
-- ── 왜 필요한가: 읽는 코드는 있는데 **쓰는 코드가 없었다** ───────────────────
-- `server/services/broadcastConfig.js:37` 이 `schedule.bgm_end_delay` 를 읽어 화면으로
-- 실어 보내고, `src/hooks/useScheduledBroadcast.js:391-396` 이 그 초만큼 기다렸다가
-- BGM 을 멈춘다. **그런데 그 칸이 `schedules` 에 아예 없었다** — 언제나 `undefined ?? 0`,
-- 즉 TTS 가 끝나는 순간 BGM 도 뚝 끊겼다.
--
-- 대시보드의 옛 "즉시" 칸과 **같은 모양**이다: 세는 코드만 있고 쓰는 코드가 0건이라
-- 구조적으로 언제나 0. 이 저장소가 반복해서 밟는 자리다.
--
-- 사용자 요구(UX-17): *"TTS 끝나고나서 한 BGM 5초 나가고, 근데 이 5초는 부드럽게
-- 들어가고 부드럽게 꺼지는 시간 포함해서"*. 앞쪽 5초는 `bgm_delay` 로 이미 있었다
-- (`schema.js`, DEFAULT 5). 뒤쪽만 없었다.
--
-- ── 기존 행을 건드리지 않는다 ────────────────────────────────────────────
-- **DEFAULT 0 이다.** 5 로 주면 ALTER 가 기존 예약을 전부 5 로 채우고, 그 순간
-- **현장에서 이미 돌고 있는 방송의 소리 길이가 바뀐다.** 지금 동작(0 = 즉시 정지)이
-- 기존 행의 사실이므로 그대로 둔다.
-- 새로 만드는 예약만 5 초를 기본으로 받는다 — 그 값은 코드(`scheduleStore.js`·
-- `scheduleUtils.BGM_DEFAULTS`)가 정하고, 이 ALTER 는 관여하지 않는다.
-- (CLAUDE.md DB 규칙: DEFAULT 를 주면 기존 행이 그 값으로 채워진다. 0024 가 그 함정에 걸렸다.)
--
-- ── 페이드는 이미 있다 ───────────────────────────────────────────────────
-- 부드럽게 켜지고 꺼지는 것은 `src/components/broadcast/YouTubeBGMHosts.jsx` 가 한다
-- (페이드 인/아웃 + TTS 덕킹, td09 H7). 이 칸은 **언제 멈출지**만 정한다 —
-- 그래서 요구대로 "페이드 시간이 그 5초 안에" 들어간다.
--
-- 이전 앱과의 호환: 옛 코드는 이 칸을 안 읽고 안 쓴다. INSERT 는 칸 이름을 명시하고
-- SELECT * 는 여분 필드로 흘린다. 되돌리기는 `.down.sql`.

ALTER TABLE schedules ADD COLUMN bgm_end_delay INTEGER DEFAULT 0;
