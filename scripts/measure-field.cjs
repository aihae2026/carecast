#!/usr/bin/env node
/**
 * **현장 방송 이력에서 낼 수 있는 수치만 낸다** (제출 §3 성과 측정).
 *
 * 쓰는 법: `node scripts/measure-field.cjs <현장DB사본경로>`
 *
 * ── 이 스크립트가 **하지 않는** 것 (사용자 지시 2026-09-15) ───────────────────
 *  · **지금 예약 설정을 과거 전체에 적용해 「예정 건수」를 만들지 않는다.** 설정은 그동안
 *    바뀌었고(점심·저녁 시각이 실제로 바뀌었다), 그걸로 만든 분모는 지어낸 숫자다.
 *  · **시스템 성공 기록을 「실제로 들렸다」로 쓰지 않는다.** `success=1` 은 *"우리 쪽에서
 *    재생 절차가 끝났다"* 이지 어르신 귀에 닿았다는 뜻이 아니다. 2026-09-14 저녁 마무리 방송은
 *    **화면에 재생 표시가 뜨고도 소리가 안 났다** — 그날이 이 구분의 증거다.
 *  · **도입 전 자료가 없으므로 전후 개선율을 만들지 않는다.**
 *
 * ── 그래서 무엇을 내나 ──────────────────────────────────────────────────────
 * **이미 쌓인 것을 세기만 한다.** 새 로그도 개인정보도 더하지 않는다.
 * 방송 **문구는 읽지 않는다**(어르신 이야기가 섞일 수 있다) — 길이와 갈래만 센다.
 */
'use strict'

const { DatabaseSync } = require('node:sqlite')

const 경로 = process.argv[2]
if (!경로) {
  console.error('쓰는 법: node scripts/measure-field.cjs <현장DB사본경로>')
  process.exit(1)
}

// **읽기 전용으로 연다.** 운영 사본을 실수로도 바꾸지 않는다.
const db = new DatabaseSync(경로, { readOnly: true })
const 하나 = (sql, ...a) => db.prepare(sql).get(...a)
const 여럿 = (sql, ...a) => db.prepare(sql).all(...a)

const 줄 = (s) => console.log(s)
const 표 = (rows, 칸) => rows.forEach(r => 줄('    ' + 칸.map(k => String(r[k] ?? '')).join('\t')))

줄('# 현장 방송 이력 측정')
줄(`DB: ${경로}`)
줄(`뽑은 때: ${new Date().toISOString()}`)
줄('')

// ── 1. 범위 ────────────────────────────────────────────────────────────────
// **`date` 가 빈 행이 있다.** 초기 몇 건이 그렇다 — 날짜를 못 붙이므로 **날짜 기반 셈에서
// 뺀다.** 빼는 것을 숨기지 않고 개수를 적는다.
const 전체 = 하나('SELECT COUNT(*) c FROM broadcasts').c
// SQLite 는 큰따옴표를 **식별자**로 읽는다 — 빈 문자열은 반드시 홑따옴표다.
// 그래서 JS 쪽을 백틱으로 둔다(홑따옴표끼리 부딪히지 않게).
const 날짜없음 = 하나(`SELECT COUNT(*) c FROM broadcasts WHERE date IS NULL OR date = ''`).c
const 범위 = 하나(`SELECT MIN(date) a, MAX(date) b, COUNT(DISTINCT date) d
                   FROM broadcasts WHERE date IS NOT NULL AND date != ''`)

줄('## 1. 범위')
줄(`  전체 기록        ${전체} 건`)
줄(`  날짜 없는 행     ${날짜없음} 건 ← 아래 날짜 기반 셈에서 제외`)
줄(`  기간             ${범위.a} ~ ${범위.b}`)
줄(`  기록이 있는 날   ${범위.d} 일`)
줄('')

// ── 2. 갈래별 ──────────────────────────────────────────────────────────────
줄('## 2. 갈래별 건수 (날짜 있는 것만)')
줄('    유형\t건수\t기록상 실패')
표(여럿(`SELECT type, COUNT(*) 건수,
          SUM(CASE WHEN success = 0 THEN 1 ELSE 0 END) 실패
        FROM broadcasts WHERE date IS NOT NULL AND date != ''
        GROUP BY type ORDER BY 건수 DESC`), ['type', '건수', '실패'])
줄('')

// ── 3. 기록상 실패 — **경보와 방송을 갈라서 센다** ──────────────────────────
// 처음에는 통째로 세어 «5.5% 실패» 가 나왔다. **그 숫자는 거짓말이다** —
// 실패로 적힌 것이 **거의 전부 `경보` 행**이었다. 경보는 방송이 아니라 **시스템이
// 사람에게 건 말**인데, `success = 0` 으로 적힌다. 갈라서 세지 않으면
// "방송 스무 건에 한 번꼴로 실패한다"로 읽힌다.
const 방송실패 = 하나(`SELECT COUNT(*) c FROM broadcasts
                       WHERE success = 0 AND type != '경보' AND date IS NOT NULL AND date != ''`).c
const 방송전체 = 하나(`SELECT COUNT(*) c FROM broadcasts
                       WHERE type != '경보' AND date IS NOT NULL AND date != ''`).c
줄('## 3. 기록상 실패 (경보 제외)')
줄(`  ${방송실패} / ${방송전체} 건 (${(방송실패 / 방송전체 * 100).toFixed(1)}%)`)
줄('  ※ 이 숫자는 **시스템이 스스로 적은 것**이다. "들렸다/안 들렸다"가 아니다.')
if (방송실패 > 0) {
  줄('  실패가 난 날:')
  표(여럿(`SELECT date, COUNT(*) 건수 FROM broadcasts
          WHERE success = 0 AND type != '경보' AND date IS NOT NULL AND date != ''
          GROUP BY date ORDER BY 건수 DESC, date DESC LIMIT 8`), ['date', '건수'])
}
줄('')

// ── 4. 정시성 ──────────────────────────────────────────────────────────────
// `delay_ms` = 예정 시각 → 첫 소리(= TTS 재생 지시). 합격선 4.0초는 사용자 결정
// (`PROJECT_PROFILE` §6-2). **재는 자리를 바꾸면 과거와 비교가 끊기므로** 그대로 쓴다.
const 잰것 = 여럿('SELECT delay_ms FROM broadcasts WHERE delay_ms IS NOT NULL ORDER BY delay_ms')
  .map(r => Number(r.delay_ms))
줄('## 4. 정시성 (delay_ms 가 있는 회차만)')
if (잰것.length === 0) {
  줄('  잰 회차가 없다.')
} else {
  const 중앙 = 잰것[Math.floor(잰것.length / 2)]
  const 합격선 = 4000
  const 넘은것 = 잰것.filter(v => v > 합격선).length
  줄(`  잰 회차     ${잰것.length} 건 ← **전체가 아니다.** 이 칸이 생긴 뒤의 회차만이다`)
  줄(`  중앙값      ${(중앙 / 1000).toFixed(2)} 초`)
  줄(`  최소~최대   ${(잰것[0] / 1000).toFixed(2)} ~ ${(잰것[잰것.length - 1] / 1000).toFixed(2)} 초`)
  줄(`  4.0초 초과  ${넘은것} 건`)
  줄('  ※ 「첫 소리」는 **TTS 재생 지시가 나간 순간**이다. BGM 시작은 안 센다')
  줄('    (PROJECT_PROFILE §6-2 — 재는 자리를 바꾸면 과거 회차와 비교가 끊긴다).')
}
줄('')

// ── 5. 경보 — **그날 그 방송이 실제로 나갔나**를 같이 본다 ─────────────────────
// 경보만 세면 «누락 37건» 이 된다. **그건 틀렸다.** 경보가 난 날마다 그 방송이 **성공으로
// 기록돼 있는지**를 같이 봐야 한다. 실제로 보니 **같은 날 자동방송 5종이 전부 성공**이었다 —
// 경보는 **오경보**였다. 감시 장치가 「완료」만 보고 있어서, 5분을 넘기는 방송
// (저녁 마무리 5.6분 등)이 매일 누락으로 찍혔다(CLAUDE.md 「누락 감시」 절).
//
// **이것을 안 가르면 제출 문서에 「현장 방송 누락 37건」이라고 적게 된다.** 사실이 아니다.
// ── 짝을 **하나하나** 지어야 한다 (V③ UI-0915-R6 지적) ─────────────────────────
// 앞 판은 **날짜별 건수**를 견줬다 — «경보 5, 자동성공 5 이니 오경보» 식이다.
// **그건 근거가 안 된다.** 검수관이 짚었다: 09-01 은 경보 3·성공 4, 09-04 는 경보 5·성공 4 다.
// 수만 맞춰 보면 **어느 경보가 어느 방송과 짝인지** 모른다.
//
// 그래서 **경보가 이름을 댄 그 방송**이, **그 경보 뒤에** 성공으로 적혔는지를 본다.
// 그래도 남는 한계가 있다 — **성공 기록은 실제로 소리가 났다는 뜻이 아니다.**
// 그러므로 결론은 «오경보로 확정» 이 아니라 **«경보가 틀렸다고 볼 근거가 있다»** 까지다.
// ── 이름은 **정확히** 맞춘다 (V③ UI-0915-R7 지적) ──────────────────────────────
// 앞 판은 `LIKE '%저녁%'` 였다. 그런데 자동방송 이름에 **「저녁 방송」과 「저녁 마무리 방송」이
// 둘 다 있다** — 그래서 「저녁 식사 전 방송」 경보가 **18:00 방송의 성공 기록과 짝지어졌다.**
// 서로 다른 방송을 이어 붙여 **성공 대응을 하나 부풀린 것**이다(35 → 34).
// 이름이 서로 포함 관계인 곳에서 `LIKE` 를 쓰면 이렇게 된다.
const 별명 = {
  '아침 종합 방송':   '아침 방송',
  '국민체조':         '국민체조 방송',
  '점심 식사 전 방송': '점심 방송',
  '저녁 식사 전 방송': '저녁 방송',      // ← 「저녁 마무리 방송」과 다르다
  '저녁 마무리':      '저녁 마무리 방송',
}
const 경보들 = 여럿(`SELECT date, time, content FROM broadcasts
                     WHERE type = '경보' AND date IS NOT NULL AND date != '' ORDER BY date, time`)
const 뒤에성공 = [], 못지음 = [], 다른종류 = []
for (const a of 경보들) {
  const m = a.content.match(/\[방송누락\] (.+?)\(/)
  if (!m) { 다른종류.push(a); continue }          // [자동업데이트] 같은 다른 경보
  const 키 = 별명[m[1]]
  if (!키) { 못지음.push({ ...a, 왜: `「${m[1]}」 이름을 못 맞췄다` }); continue }
  const 뒤 = 여럿(`SELECT time FROM broadcasts
                   WHERE date = ? AND type = '자동' AND success = 1
                     AND content = ? AND time >= ?`, a.date, 키, a.time)
  if (뒤.length > 0) 뒤에성공.push(a)
  else 못지음.push({ ...a, 왜: `그 뒤 「${m[1]}」 성공 기록을 못 찾았다` })
}

줄('## 5. 경보 — **경보마다 그 방송과 짝을 지어 본다**')
줄(`  경보 전체                      ${경보들.length} 건`)
줄(`  그중 [방송누락] 이 아닌 것      ${다른종류.length} 건`)
다른종류.forEach(a => 줄(`      ${a.date} ${a.time} ${a.content.slice(0, 40)}`))
줄(`  **경보 뒤에 그 방송이 성공으로 적힌 것**  ${뒤에성공.length} 건`)
줄(`  **짝을 못 지은 것**                      ${못지음.length} 건`)
못지음.forEach(a => 줄(`      ${a.date} ${a.time} — ${a.왜}`))
줄('')
줄('  ※ **「오경보로 확정」이라고 쓰지 않는다.** 성공 기록은 「우리 쪽 절차가 끝났다」이지')
줄('    「소리가 났다」가 아니다. 여기서 말할 수 있는 것은')
줄('    **「그 경보가 틀렸다고 볼 근거가 있다」** 까지다.')

const 마지막경보 = 하나(`SELECT MAX(date) d FROM broadcasts WHERE type = '경보'`).d
const 그뒤 = 하나(`SELECT COUNT(*) c FROM broadcasts
                   WHERE type = '자동' AND success = 1 AND date > ?`, 마지막경보).c
줄(`  마지막 경보: ${마지막경보} · 그 뒤 자동방송 성공 ${그뒤} 건 · 그 뒤 경보 0 건`)
줄('')

줄('## 낼 수 없는 것 (지어내지 않는다)')
줄('  · 「예정 대비 실제」 비율 — 지금 예약 설정을 과거에 적용하면 지어낸 분모가 된다.')
줄('    설정은 실제로 바뀌었다(점심·저녁 시각).')
줄('  · 「실제로 들린 비율」 — 시스템 기록으로는 알 수 없다. 사람이 귀로 들어야 한다.')
줄('  · 「도입 전후 개선율」 — 도입 전 자료가 없다.')
