/**
 * 단추를 **「지금 나갈 것」과 「나중에 나갈 것」으로 묶는다** (사용자 지시 2026-09-15).
 *
 * *"내가 하다 보니 알게 됐는데 이게 예약이랑 즉시방송이랑 섞여 있어서 헷갈린 거 같아.
 *   순서를 [지금방송, 배경음악, 순서] 이렇게 어떻게 좀 묶어봐 디자인적으로 구분되게,
 *   그리고 예약방송 이렇게 하면 좀 덜 헷갈리지 않을까 싶어."*
 *
 * 맞다. 넷이 한 줄에 나란히 서 있는데 **셋은 누르면 곧 소리가 나고 하나는 안 난다.**
 * 그 차이가 이 줄에서 가장 중요한 사실인데, 생김새로는 아무 데도 안 적혀 있었다.
 *
 * **묶는 근거를 새로 만들지 않는다** — 각 단추가 이미 `즉시` 를 들고 있다(위 `초안정의`).
 * 화면이 제 목록을 따로 적으면 언젠가 갈리고, 갈린 쪽이 화면이다.
 *
 * @returns {{키:'now'|'later', 이름:string, 단추:object[]}[]} 빈 묶음은 안 돌려준다.
 */
export function 단추묶음(목록 = 빠른시작) {
  const 묶음 = [
    { 키: 'now',   이름: '지금 바로',  단추: 목록.filter(b => b.즉시) },
    { 키: 'later', 이름: '나중에',     단추: 목록.filter(b => !b.즉시) },
  ]
  return 묶음.filter(g => g.단추.length > 0)
}

/**
 * **즉시 방송의 실행값을 맞춘다** — 예약으로 남지 않게.
 *
 * 이 세 값이 즉시 방송의 생사를 가른다. `emptySchedule()` 의 기본값은 **새 예약을 만들 때의
 * 것**이라 즉시 방송에는 독이다:
 *   · `scheduled_time` = 다음 5분 자리 → 1~5분 뒤 스케줄러가 **한 번 더 쏜다**
 *   · `repeat_weekdays` = 매일        → **내일도 모레도** 같은 시각에 나간다
 *   · `active` = 1                    → 스케줄러 조회에 그대로 걸린다
 * 2026-09-14 현장 신고(*"한 번 내보냈는데 몇 분 뒤 다시 나왔다"*)가 이것이었다.
 *
 * **함수로 뺀 이유**(V③ R7 지적): 빠른 단추만 고쳤더니 **검색으로 초안을 다시 채우는 길**이
 * 남아 있었다 — `run()` 은 `emptySchedule()` 위에 서버 결과를 얹으므로 `active: 1` 이
 * 되살아난다. 즉시 카드에서 "지금 안내방송 해줘"를 검색하면 **활성 예약으로 저장**된다.
 * 같은 규칙을 두 곳이 각자 적으면 이렇게 한쪽만 고쳐진다. **한 곳에서 맞춘다.**
 */
export function 즉시실행값(밑바탕, 지금 = new Date()) {
  const p2 = (n) => String(n).padStart(2, '0')
  return {
    ...밑바탕,
    immediate: true,
    scheduled_time: `${p2(지금.getHours())}:${p2(지금.getMinutes())}`,  // 미래가 아니다
    repeat_weekdays: [],                                                // 1회성
    repeat_start_date: `${지금.getFullYear()}-${p2(지금.getMonth() + 1)}-${p2(지금.getDate())}`,
    active: 0,                                                          // 마지막 빗장
  }
}

const 두자리 = (n) => String(n).padStart(2, '0')
const 날짜글 = (d) => `${d.getFullYear()}-${두자리(d.getMonth() + 1)}-${두자리(d.getDate())}`
const 시각글 = (d) => `${두자리(d.getHours())}:${두자리(d.getMinutes())}`

/**
 * **1회성 예약의 날짜가 이미 지났으면 다음으로 옮긴다.** 안 옮기면 영영 안 울린다.
 *
 * ── 왜 필요한가 (V③ R19·R20 지적, 2026-09-14) ───────────────────────────────
 * 현장 PC 의 창은 하루 종일 열려 있다 — 그게 이 시스템의 전제다(CLAUDE.md). 그래서
 * **어제 만든 초안이 오늘까지 칸에 남아 있을 수 있다.** 1회성 예약은 `repeatSchedule.js`
 * 가 **시작일 당일에만** 발동시키고 `scheduler.js` 는 **현재 분과 같은 것**만 조회하므로,
 * 지나간 날짜·시각인 채로 확정하면 **등록은 되는데 영영 안 울린다** — 이 저장소에서 원인을
 * 찾기 가장 어려운 실패다.
 *
 * **날짜만 보면 모자란다**(R20 지적). 오늘 15:00 짜리를 16:00 에 되살리면 날짜는 오늘이라
 * 그냥 지나가는데, 그 예약도 이미 못 울린다. **날짜와 시각을 같이** 본다.
 *
 * ── 규칙은 파서와 같다 ──────────────────────────────────────────────────────
 * `schedulePhrase.js` 가 이미 같은 일을 한다 — 1회성이고 오늘인데 시각이 지났으면
 * **내일로 옮기고 사람에게 알린다**(`time_past_moved`). 여기서 새 규칙을 짓지 않고
 * 그것을 따른다. 규칙이 두 벌이면 언젠가 갈린다.
 *
 * @returns {string|null} 옮겨야 하면 새 날짜, 그대로 둬도 되면 `null`
 */
function 지나갔으면다음날(초안, 지금) {
  if (!초안?.scheduled_time) return null
  const 오늘 = 날짜글(지금)
  const 날 = 초안.repeat_start_date || 오늘
  if (날 > 오늘) return null                       // 앞날이다 — 건드리지 않는다
  // 오늘 그 시각이 아직 안 지났으면 오늘로 충분하다. 지났으면 내일이다.
  if (초안.scheduled_time > 시각글(지금)) return 날 === 오늘 ? null : 오늘
  const 내일 = new Date(지금)
  내일.setDate(내일.getDate() + 1)
  return 날짜글(내일)
}

/**
 * **이미 있는 초안을 그 카드의 실행 방식에 맞춘다** (V③ R15 지적, 2026-09-14).
 *
 * ── 왜 필요한가 ──────────────────────────────────────────────────────────────
 * 「고른 카드가 언제 나갈지를 정한다」는 규칙을 **검색 경로에만** 걸어 뒀다. 그런데 카드를
 * 고르는 길은 둘이다 — 검색하면서 세워지는 길과 **단추를 누르는 길**. 두 번째가 비어 있었다.
 *
 * 카드 없이 예약 문장을 치면 `schedule` 칸에 초안이 선다. 이어서 즉시 문장을 치면 — 아직
 * 아무 카드도 안 골랐으므로 파서 제안을 따라 — **그 `schedule` 칸에 `immediate: true` 가
 * 들어앉는다.** 그 뒤 사람이 「예약 방송」을 눌러도 `모드고르기` 는 **있던 초안을 그대로
 * 되살린다**(작성 내용 보존). 그래서 「예약 방송」 카드를 보면서 확정을 누르면
 * **전관 스피커로 방송이 나간다.** 고른 카드와 정반대다.
 *
 * ── 규칙 ─────────────────────────────────────────────────────────────────────
 * **단추를 누르는 것이 명시적 선택이다.** 그러니 그 순간 실행 방식을 카드에 맞춘다.
 * **문안·제목·유형은 안 건드린다** — 보존해야 하는 것은 사람이 적은 내용이지 실행 방식이 아니다.
 *
 * 예약으로 되돌릴 때는 밑바탕의 시각·반복·활성을 **되살린다.** 안 되살리면
 * `즉시실행값` 이 남겨 둔 「지금 시각 · 반복 없음 · 꺼짐」 그대로 저장돼 **영영 안 울린다.**
 *
 * @returns {{초안: object, 바뀜: boolean}} `바뀜` 이면 화면이 사람에게 말한다(조용히 안 바꾼다).
 */
export function 실행방식맞추기(id, 초안, 밑바탕 = {}, 지금 = new Date()) {
  const 정의 = 초안정의[id]
  if (!정의 || !초안) return { 초안, 바뀜: false }
  const 즉시여야 = !!정의.즉시
  const 바뀜 = !!초안.immediate !== 즉시여야
  // ── 즉시는 **언제나** 실행값을 맞춘다 ────────────────────────────────────────
  // 이미 `immediate` 가 서 있어도 `active` 는 밑바탕의 `1` 인 채로 올 수 있다(검색 경로가
  // 그렇다). 그대로 두면 **활성 예약으로 저장돼 몇 분 뒤 한 번 더, 내일도 나간다** —
  // 2026-09-14 현장 신고가 그것이었다(V③ R7). 같은 값을 다시 써도 해가 없으니 늘 맞춘다.
  if (즉시여야) return { 초안: 즉시실행값(초안, 지금), 바뀜 }
  // ── 예약은 **어긋날 때만** 손댄다 ───────────────────────────────────────────
  // 맞는 초안까지 밑바탕으로 되돌리면 사람이 고쳐 둔 시각·반복이 조용히 날아간다.
  if (!바뀜) {
    // ── 다만 **지나간 1회성**은 되살린다 (V③ R19 지적, 2026-09-14) ──────────────
    // 현장 PC 의 창은 하루 종일 열려 있다 — 그게 이 시스템의 전제다(CLAUDE.md).
    // 그래서 **어제 만든 초안이 오늘까지 칸에 남아 있을 수 있다.** 1회성 예약은
    // `repeatSchedule.js` 가 **시작일 당일에만** 발동시키므로, 지난 날짜인 채로 확정하면
    // **등록은 되는데 영영 안 울린다** — 원인을 찾기 가장 어려운 실패다.
    //
    // **시각은 안 건드린다.** 그건 사람이 정한 뜻이다. 날짜만 오늘로 되살린다.
    // **반복 예약도 안 건드린다** — 시작일이 지났어도 내일 그 시각에 정상 발동한다.
    const 한번만 = !(초안.repeat_weekdays?.length)
    const 옮긴날 = 한번만 ? 지나갔으면다음날(초안, 지금) : null
    if (옮긴날) return { 초안: { ...초안, repeat_start_date: 옮긴날 }, 바뀜: true }
    return { 초안, 바뀜: false }
  }
  // 즉시였던 것을 예약으로 되돌린다. **시각·반복·활성을 반드시 되살린다**(V③ R17) —
  // 즉시 요청의 파싱 결과는 「오늘 지금 분 · 반복 없음」이라, `immediate` 만 내리면
  // **그 분이 지나는 순간 영영 안 울리는 예약**이 된다. 확인하는 동안에도 지나간다.
  return {
    초안: {
      ...초안,
      immediate: false,
      scheduled_time:    밑바탕.scheduled_time,
      repeat_weekdays:   밑바탕.repeat_weekdays,
      repeat_start_date: 밑바탕.repeat_start_date,
      active:            밑바탕.active,
    },
    바뀜: true,
  }
}

/**
 * 그 단추를 눌렀을 때 열릴 **초안**.
 *
 * @param {string} id      `빠른시작` 의 id
 * @param {object} 밑바탕  `scheduleUtils.emptySchedule()` 의 결과.
 *   **여기서 기본값을 다시 적지 않는다** — 시각·볼륨·반복 기본값은 그쪽이 단일 출처다.
 *   (그 모듈은 아이콘을 들고 있어 노드에서 못 불러온다. 그래서 **받아서** 쓴다.)
 * @returns {object|null} 모르는 id 면 `null`
 */
export function 빠른초안(id, 밑바탕 = {}, 지금 = new Date()) {
  // **단추 목록이 아니라 정의를 본다** — 차임벨처럼 단추에서 빠졌어도 여는 법은 살아 있다.
  const 단추 = 초안정의[id] || null
  if (!단추) return null
  // ── 예약 초안은 **밑바탕 그대로** ────────────────────────────────────────────
  // 아래 즉시 방송용 맞춤(시각·반복·활성)은 *"지금 나가고 예약으로 남지 않게"* 하려는
  // 것이다. 예약은 정반대로 **남아야** 하므로 그 맞춤을 지나면 안 된다 —
  // 지나면 새 예약이 「오늘 지금 시각 · 반복 없음 · 꺼짐」으로 만들어져 영영 안 울린다.
  if (!단추.즉시) {
    return { ...밑바탕, broadcast_type: 단추.유형, immediate: false, title: 단추.방송이름, content: '' }
  }
  return {
    // **실행값은 `즉시실행값` 한 곳이 정한다**(V③ R7). 여기서 따로 적으면 검색 경로와
    // 갈려서, 한쪽만 고친 채 현장 결함이 다른 문으로 되살아난다.
    ...즉시실행값(밑바탕, 지금),
    broadcast_type: 단추.유형,
    // 제목은 이력에 남는 이름이다. 비워 두면 확정이 "제목을 확인해 주세요"로 막혀
    // 또 막다른 길이 된다 — 그래서 읽히는 이름을 미리 넣고, 사람이 고칠 수 있게 둔다.
    title: 단추.방송이름,
    // 내용은 비운다. TTS 는 사람이 적을 자리이고, 나머지 유형은 읽을 문구가 없다.
    content: '',
  }
}
