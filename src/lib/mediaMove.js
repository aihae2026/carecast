// 음원·영상을 **다른 폴더로 옮기는 판정과 실행** — 화면 밖 한 곳.
//
// 왜 화면 밖인가(V③ R15 지적 3·6 → R16 지적 1, 2026-09-13~14):
//   ① 「일괄 옮기기」 버튼은 `{ 여럿: [...] }` 를 넣는데 옮기는 쪽은 `moveTarget.id` 하나만
//      읽었다 — 여러 개를 고르면 **`undefined` 를 서버로 보냈다.**
//   ② 그것을 지키던 시험은 `setMoveTarget({ 여럿: 고른파일 })` 이라는 **글자가 있는지만**
//      봤고, 결함이 있는 채로 관련 41건이 전부 초록이었다.
//   ③ 1차 수정에서 **목록 변환만** 꺼냈더니 독립 검수가 다시 물었다 — *"API 호출을
//      제거하거나 잘못된 ID 를 전달해도 이 시험은 통과할 수 있다."* 맞는 말이었다.
//      그래서 **도는 자리까지** 여기로 내린다.
//
// 판정이 화면 안에 있으면 소스 글자로만 검사하게 되고, 그런 검사가 실제로 결함을 놓쳤다.
// 여기 두면 시험이 **진짜 함수를 부르고**, 옮기는 창구를 **대역으로 갈아 끼워**
// 몇 번 불렀는지·어떤 id 로 불렀는지·중간에 실패하면 이어 가는지까지 잴 수 있다.

/**
 * 「옮기기」가 **무엇을 옮기려는 것인지** 푼다 — 한 개든 여러 개든 **파일 목록 하나**로.
 *
 * @param {null|{id?:number, 여럿?:Array}} 옮길것 화면이 쥐고 있는 `moveTarget`
 * @returns {Array} 실제로 옮길 파일들. `id` 가 없는 것은 빼고 준다 — 그게 그대로 서버에 가면 400 이다.
 */
export function 옮길파일들(옮길것) {
  if (!옮길것) return []
  const 후보 = Array.isArray(옮길것.여럿) ? 옮길것.여럿 : [옮길것]
  return 후보.filter(f => f && f.id != null)
}

/**
 * 실제로 옮긴다. **한 건이 실패해도 나머지는 계속 옮긴다.**
 *
 * 폴더는 자기 카테고리 파일만 받으므로(서버 400) 여러 종류를 함께 고르면 **일부만 들어가는
 * 것이 정상**이다. 그때 조용히 넘기지 않고 무엇이 안 갔는지 이름을 대고 돌려준다 —
 * 이 화면의 다른 실패(폴더 삭제·이름 변경)와 같은 방식이다.
 *
 * @param {object} 인자
 * @param {null|{id?:number, 여럿?:Array}} 인자.옮길것 화면의 `moveTarget`
 * @param {number|null} 인자.목적지 폴더 id (`null` 이면 맨 위)
 * @param {(id:number, 목적지:number|null)=>Promise} 인자.옮기기 옮기는 창구. 시험은 대역을 넣는다
 * @returns {Promise<{시도:number, 옮김:number, 실패:string[]}>}
 */
export async function 옮기기실행({ 옮길것, 목적지, 옮기기 }) {
  const 파일들 = 옮길파일들(옮길것)
  const 실패 = []
  let 옮김 = 0
  for (const 것 of 파일들) {
    try {
      await 옮기기(것.id, 목적지)
      옮김 += 1
    } catch (err) {
      실패.push(`${것.original_name || 것.id}: ${err?.message || '옮기지 못했습니다'}`)
    }
  }
  return { 시도: 파일들.length, 옮김, 실패 }
}

/** 옮기기 결과를 사람에게 보여 줄 한 덩어리로. 다 잘 갔으면 `null` — 굳이 알릴 것이 없다. */
export function 옮기기안내(결과) {
  if (!결과 || !결과.실패.length) return null
  return `${결과.시도}개 중 ${결과.실패.length}개를 옮기지 못했습니다.\n\n${결과.실패.join('\n')}`
}
