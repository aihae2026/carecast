// 화면이 쓰는 **볼륨 기본값 한 벌** (UX-39, 2026-09-11).
//
// 서버가 아무 값도 못 줄 때 화면이 자리를 채우는 숫자다. 정본은 서버의
// `server/domain/volume.js` 의 `CHANNELS[*].fallback` 이고, **여기는 그 사본이다.**
//
// 왜 사본이 필요한가: 화면은 서버 모듈을 못 읽는다(브라우저). 그렇다고 화면마다 숫자를
// 박으면 **2026-08-28 볼륨 사고**가 그대로 돌아온다 — 그때 기본값이 8곳에 흩어져 있어
// 한 곳을 고쳐도 나머지가 안 따라왔고, 화면에 보이는 값과 실제로 나가는 소리가 달랐다.
//
// **사본이 갈리는 것을 사람 규율로 막지 않는다.** `server/test/volume-defaults-single-source.test.js`
// 가 이 파일과 서버 `CHANNELS` 를 **줄 단위로 대조**한다. 서버 기본값을 고치면 그 검사가
// 빨간불이 되어 여기도 같이 보게 만든다.
//
// 값을 바꿀 일이 생기면 **서버를 먼저 고친다.** 여기는 따라오는 쪽이다.
export const 볼륨기본값 = {
  master: 70,
  tts:    80,
  audio:  100,
  media:  70,
  bgm:    70,
}

