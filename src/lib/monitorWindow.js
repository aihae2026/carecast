// 모니터링 창을 여는 **한 곳** (2026-09-14).
//
// `/monitor` 는 읽기 전용 요약 화면이다 — 방송을 내지 않고, 소리 담당 선출에서도 빠진다
// (`App.jsx` 의 `_IS_MONITOR`). 현장 PC 옆에 작게 띄워 두거나, 다른 자리에서 상태만
// 보려고 쓴다.
//
// **왜 함수로 뺐나**: 여는 줄이 옛 쉬운 화면 머리줄에만 박혀 있었고, 통합 홈으로 오면서
// 진입점이 통째로 빠졌다(사용자 지적 — *"원격에서 볼 수 있도록 모니터링 화면도 빠졌어"*).
// 되살리면서 두 화면에 같은 줄을 복사하면 주소·크기·창 이름이 두 벌이 된다.
// 이 저장소가 볼륨 기본값·음원 경로·식사 안내 문구에서 이미 겪은 실패다.
//
// **창 이름을 고정하는 것이 핵심이다.** 이름이 같아야 어디서 눌러도 **창이 하나**다.
// 빈 이름(`''`)이나 `_blank` 를 주면 누를 때마다 새 창이 뜬다.

/** 모니터링 창의 이름. 어디서 눌러도 이 이름이라 창이 하나로 모인다. */
export const 모니터창이름 = 'carecast_monitor'

/** 창 크기 — 폴더폰 커버스크린만 한 요약 화면이다(`pages/MonitorPage.jsx`). */
export const 모니터창옵션 = 'width=360,height=560,resizable=yes'

/**
 * 모니터링 창을 연다. 이미 열려 있으면 **그 창을 앞으로 가져온다**(같은 이름이라 새로 안 뜬다).
 *
 * @param {{open?: Function}} [창구] 시험이 대역을 넣는 자리. 기본은 브라우저의 `window.open`
 * @returns {Window|null} 팝업이 막히면 `null` — **조용히 지나가지 않는다.**
 *   부르는 쪽이 "안 열렸다"를 사람에게 말할 수 있어야 한다.
 */
export function 모니터창열기(창구 = {}) {
  const open = 창구.open || (typeof window !== 'undefined' ? window.open.bind(window) : null)
  if (!open) return null
  const 창 = open('/monitor', 모니터창이름, 모니터창옵션)
  // 이미 있던 창이면 뒤에 가려 있을 수 있다. 앞으로 꺼내 준다.
  try { 창 && 창.focus && 창.focus() } catch { /* 다른 출처면 focus 가 막힌다 — 여는 것까지는 됐다 */ }
  return 창 || null
}
