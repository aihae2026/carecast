/** 기관 이름·표어 글자수 상한. 정본: `server/routes/settings.js` 의 `ORG_TEXT_MAX` */
export const 기관글자수상한 = 40

/** HH:MM 형식. 정본: `server/domain/autoBroadcasts.js` 의 `HHMM` */
export const 시각형식 = /^([01]\d|2[0-3]):[0-5]\d$/

/**
 * **저장해도 되는 시각인가.** 서버 `유효시각()` 과 같은 뜻이다 —
 * **빈 값은 유효하다**(= "이 기능을 쓰지 않는다", AP-0012).
 * 자동종료 시각을 비우는 것은 "PC 를 끄지 않는다"는 정상적인 선택이다.
 */
export function 시각이맞나(v) {
  if (v === '' || v === null || v === undefined) return true
  return typeof v === 'string' && 시각형식.test(v)
}

/**
 * 기관 이름·표어가 저장 가능한가.
 *
 * **서버의 처리가 둘로 갈린다**([FACT] `server/routes/settings.js:1060-1066` 직독) —
 *   · 길이: 400 이 아니라 **조용히 `trim().slice(0, 40)` 으로 자른다.**
 *     그러니 이 검사는 "막힌다"가 아니라 **"잘리는 걸 미리 알려준다"** 가 목적이다.
 *   · 깨진 글자(U+FFFD): 여기만 400 이다. CP949 로 깨진 이름이 DB 에 들어앉아
 *     홀 TV 가 통째로 네모가 된 적이 있어서 서버가 막는다.
 * 양쪽 다 `trim()` 을 먼저 하므로 경계는 어긋나지 않는다("앞뒤 공백 + 45자"는 둘 다 초과).
 *
 * @returns {string} 문제가 있으면 사람에게 보여줄 문장, 없으면 빈 문자열
 */
export function 기관글자검사(값) {
  const s = String(값 ?? '')
  if (s.includes('�')) return '글자가 깨져 있습니다. 다시 입력해 주세요.'
  // 「다음」이 잠기므로 **「잘립니다」가 아니라 「줄여 주세요」다**(2026-09-17 브라우저 전수 시험 — 잘린다고 해 놓고
  // 단추가 안 눌려 사람이 멈췄다). 몇 자를 줄이면 되는지까지 말한다.
  if (s.trim().length > 기관글자수상한) return `${기관글자수상한}자까지만 넣을 수 있습니다 — ${s.trim().length - 기관글자수상한}자를 줄여 주세요.`
  return ''
}

