// 그래서 이 함수는 마법사가 실제로 받아 온 값만 보고 판정한다. **모르면 '확인 불가'다.**
// 판정 낱말은 `docs/ui-ux-layout.md` 의 상태 어휘와 같은 것을 쓴다.

/**
 * @param {object} 결과 마법사가 각 장에서 실제로 받은 것
 *   `{ org:{name,slogan}|null, device:string|null, sound:'들림'|'안 들림'|null,
 *      keys:{gemini,kma 각 boolean}|null, address:string|null }`
 *   **각 칸은 "안 해 봤으면 null"** 이다 — 빈 값과 구별해야 '확인 불가'를 낼 수 있다.
 * @returns {Array<{id,이름,상태,문구}>} 상태는 정상 · 미설정 · 실패 · 확인 불가
 */
export function 준비상태(결과 = {}) {
  const 줄 = []

  // 기관 정보 — 비어 있어도 방송은 나간다. 홀 TV 큰 글씨만 안 나온다.
  if (결과.org == null) 줄.push({ id: 'org', 이름: '기관 이름', 상태: '확인 불가', 문구: '아직 불러오지 못했습니다.' })
  else if (String(결과.org.name ?? '').trim()) 줄.push({ id: 'org', 이름: '기관 이름', 상태: '정상', 문구: 결과.org.name })
  else 줄.push({ id: 'org', 이름: '기관 이름', 상태: '미설정', 문구: '비어 있어 홀 TV 에 이름이 안 나옵니다.' })

  // 스피커 — 비어 있으면 **Windows 기본 장치**로 나간다. 고장은 아니다.
  if (결과.device == null) 줄.push({ id: 'speaker', 이름: '스피커', 상태: '확인 불가', 문구: '아직 불러오지 못했습니다.' })
  else if (String(결과.device).trim()) 줄.push({ id: 'speaker', 이름: '스피커', 상태: '정상', 문구: 결과.device })
  else 줄.push({ id: 'speaker', 이름: '스피커', 상태: '미설정', 문구: 'Windows 기본 장치로 나갑니다.' })

  // 소리 시험 — **사람의 귀가 판정한다.** 안 들렸다는 것은 실패다(방송이 안 들린다).
  if (결과.sound == null) 줄.push({ id: 'sound', 이름: '소리 확인', 상태: '확인 불가', 문구: '소리 시험을 안 했습니다.' })
  else if (결과.sound === '들림') 줄.push({ id: 'sound', 이름: '소리 확인', 상태: '정상', 문구: '들림' })
  else 줄.push({ id: 'sound', 이름: '소리 확인', 상태: '실패', 문구: '안 들렸습니다 — 스피커를 다시 골라 보세요.' })

  // 키 — 저장했는지만 본다. **연결이 되는지는 검사하지 않았으므로 「연결됨」이라 적지 않는다.**
  if (결과.keys == null) 줄.push({ id: 'api', 이름: 'AI·날씨', 상태: '확인 불가', 문구: '저장 현황을 못 읽었습니다.' })
  else {
    const 이름표 = { gemini: 'AI', kma: '날씨' }
    const 있음 = Object.keys(이름표).filter((k) => 결과.keys[k])
    줄.push(있음.length
      ? { id: 'api', 이름: 'AI·날씨', 상태: '정상', 문구: `${있음.map((k) => 이름표[k]).join(' · ')} 키 저장됨` }
      : { id: 'api', 이름: 'AI·날씨', 상태: '미설정', 문구: '건너뜀' })
  }

  // 접속 주소 — 못 찾았으면 휴대폰으로 못 들어온다. 방송은 나간다.
  if (결과.address == null) 줄.push({ id: 'address', 이름: '접속 주소', 상태: '확인 불가', 문구: '주소를 못 읽었습니다.' })
  else if (String(결과.address).trim()) 줄.push({ id: 'address', 이름: '접속 주소', 상태: '정상', 문구: 결과.address })
  else 줄.push({ id: 'address', 이름: '접속 주소', 상태: '미설정', 문구: '다른 기기에서 들어올 주소를 찾지 못했습니다.' })

  return 줄
}

// ── 저장해도 되는가 — 2026-09-11 독립 검수 지적 ──────────────────────────────
//
// **지금 값을 못 읽었으면 저장하면 안 된다.** 이것이 빠져 있었다.
//
// 마법사는 화면을 열 때 현재 값을 읽어 초안에 채운다. 그런데 그 조회가 실패하면
// 초안은 **빈 문자열로 남는다.** 그 상태에서 "저장"이 눌리면 —
//   · `tts_voice_normal = ''` → `getSetting` 은 `rawSetting ?? 기본값` 이라
//     **빈 문자열이 `??` 를 통과하지 못한다.** 기본 목소리로 안 돌아가고,
//     그 뒤 모든 안내 방송의 합성이 무너진다.
//   · `auto_shutdown_time = ''` → 현장의 18:21 이 조용히 지워진다.
//   · `org_name = ''` → 홀 TV 의 기관 이름이 사라진다.
// 그리고 화면에는 "저장했습니다"가 뜬다. **오류도 경고도 없다.**
//
// 마법사 머리말이 *"안 그러면 '다음'을 누르는 것만으로 멀쩡한 설정이 빈 값으로 덮인다"* 고
// 적어 둔 바로 그 사고가, 정상 경로는 막혔는데 **실패 경로에 남아 있었다.**
//
// 판정을 화면이 아니라 여기 두는 이유: 화면의 `저장가능` 은 삼항 연산자 한 줄이라
// "조회에 성공했는가"가 들어갈 자리가 없었고, 그래서 이 조합이 눈에 안 띄었다.
// 순수 함수로 내리면 `node --test` 가 직접 돌려 고정할 수 있다.

/**
 * @param {string} 단계   단계 id
 * @param {object} 초안   `{ 이름, 표어, 키들:{gemini,kma}, 장치 }` — 지금 입력칸에 있는 값
 * @param {object} 읽음   `{ org, tts }` — 조회 결과. **실패했으면 null 이다**
 * @returns {{ok:boolean, 이유:string}} `ok` 가 false 면 「다음」이 저장하지 않는다
 */
export function 저장해도되나(단계, 초안 = {}, 읽음 = {}) {
  const 막기 = (이유) => ({ ok: false, 이유 })

  if (단계 === 'org') {
    // **조회 실패가 먼저다.** 입력이 멀쩡해도 지금 값을 모르면 덮으면 안 된다.
    if (읽음.org == null) return 막기('지금 저장된 기관 정보를 못 읽었습니다. 저장하면 기존 값을 덮어씁니다 — 새로고침해 주세요.')
    const e = 기관글자검사(초안.이름) || 기관글자검사(초안.표어)
    return e ? 막기(e) : { ok: true, 이유: '' }
  }

  if (단계 === 'speaker') {
    // 장치만 보낸다(서버가 보낸 칸만 바꾼다). 그래도 **지금 장치를 못 읽었으면** 빈 초안이
    // 현장 스피커 이름을 지워 Windows 기본 장치로 떨어뜨린다 — 엉뚱한 데서 소리가 난다.
    if (읽음.tts == null) return 막기('지금 설정된 스피커를 못 읽었습니다. 저장하면 기존 값을 덮어씁니다 — 새로고침해 주세요.')
    return { ok: true, 이유: '' }
  }

  if (단계 === 'api') {
    // 키 저장은 **더하기만** 한다 — 조회 실패와 무관하고, 빈 키를 보낼 일도 없다.
    //
    // ── **이 장은 좌표도 받는다** (독립 검수 2026-09-18) ────────────────────────────
    // 앞 판은 키가 하나도 없으면 무조건 막았다. 그래서 **키를 이미 넣어 둔 기관이 위치만
    // 고치려고 들어오면**(키 칸은 늘 빈 채로 시작한다) 좌표를 넣는 순간 「다음」이 잠기고,
    // 화면에는 좌표와 상관없는 「넣을 키가 없습니다」만 떴다. 빠져나갈 길은 넣은 좌표를
    // 지우는 것뿐이었고 그 말은 어디에도 없었다 — 이번 수정의 주 목적이 가장 흔한
    // 경로에서 아예 동작하지 않았다.
    const 키들 = 초안.키들 ?? {}
    const 키있나 = Object.values(키들).some((v) => String(v ?? '').trim())
    const 위 = String(초안.위도 ?? '').trim()
    const 경 = String(초안.경도 ?? '').trim()
    // **한쪽만 넣은 것은 막는다.** 위도만으로는 조회가 안 되고, 조용히 한쪽만 저장하면
    // 두 값이 다른 동네를 가리킨다.
    if ((위 && !경) || (!위 && 경)) return 막기('위도와 경도를 둘 다 넣어 주세요.')
    if (키있나 || (위 && 경)) return { ok: true, 이유: '' }
    return 막기('넣을 키가 없습니다.')
  }

  if (단계 === 'terms') {
    // 동의는 **더하기만** 한다(덮을 기존 값이 없다) — 조회 실패와 무관하다.
    // 이름 상한 40 은 서버(`domain/licenseConsent.js` 의 이름상한)와 같다.
    const 이름 = String(초안.동의자 ?? '').trim()
    if (!초안.동의함) return 막기('「위 내용을 읽었고 동의합니다」에 표시해 주세요. 동의하지 않으려면 「건너뛰고 다음」을 누르세요.')
    if (!이름) return 막기('동의하는 분의 이름(또는 직책)을 적어 주세요.')
    if (이름.length > 40) return 막기('이름은 40자까지 적을 수 있습니다.')
    return { ok: true, 이유: '' }
  }

  return 막기('')   // 저장할 것이 없는 장 — 「다음」은 그냥 넘어간다
}

/**
 * 마무리 화면의 한 줄 요약. **하나라도 실패면 성공 문구를 쓰지 않는다**(UX-12).
 */
export function 마무리문구(줄들 = []) {
  if (줄들.some((r) => r.상태 === '실패')) return '연결하지 못한 항목이 있습니다. 아래를 확인해 주세요.'
  if (줄들.some((r) => r.상태 === '확인 불가')) return '확인하지 못한 항목이 있습니다.'
  if (줄들.some((r) => r.상태 === '미설정')) return '거의 다 됐습니다. 비워 둔 항목은 나중에 시스템 설정에서 채울 수 있습니다.'
  return '방송 준비가 끝났습니다.'
}

// ── 손으로 안 넣어도 되는 값은 **계산해서 채운다** (UX-08) ──────────────────
//
// Redirect URI 는 구글이 **이 화면으로 되돌아올 주소**다. 그러니 지금 보고 있는 주소에서
// 그대로 나온다 — 사람이 타이핑할 이유가 없다. 예전에는 `localhost:3001` 로 박혀 있어서
// **다른 PC 브라우저에서 설정을 열면 그 PC 의 localhost 를 가리키는 주소가 저장됐다.**
//
// 근거 없이 지어내지 않는다 — 주소창에 있는 것을 쓰고, 못 읽으면 옛 기본값으로 떨어진다.
// (기상청 격자에서 한 시설의 기본값을 지운 것과 같은 규칙이다: 남의 값을 심지 않는다.)
export const 기본CalendarId = 'primary'
export const 기본콜백경로 = '/api/calendar/callback'
export const 옛기본RedirectUri = 'http://localhost:3001' + 기본콜백경로

export function 기본RedirectUri(origin) {
  let o = origin
  if (o == null) { try { o = window.location.origin } catch { o = null } }
  if (!o) return 옛기본RedirectUri
  // 개발 중에는 화면(5173)과 서버(3001)가 다른 포트다. 구글은 **서버** 로 되돌려야 한다.
  if (/:5173$/.test(o)) return o.replace(/:5173$/, ':3001') + 기본콜백경로
  return o + 기본콜백경로
}
