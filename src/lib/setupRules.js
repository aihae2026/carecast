/** 마법사를 끝낼 수 있는 마지막 단계인가. 그 전에는 "완료"가 눌리지 않는다(UX-01). */
export function 마지막단계인가(단계id) {
  return 단계목록[단계목록.length - 1].id === 단계id
}

/** 진행 표시(UX-01 ①). 0~1 사이 값. */
export function 진행률(단계id) {
  const i = 단계목록.findIndex((s) => s.id === 단계id)
  if (i < 0) return 0
  return (i + 1) / 단계목록.length
}

