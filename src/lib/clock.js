// 날짜·시각을 사람이 읽는 글자로 — **한 곳에서만 짓는다** (2026-09-13).
//
// 통합 홈 머리줄에 실시간 시계를 넣으면서 뺐다. 그전에는 `easy/TopBar.jsx` 안에만 있었고,
// 홈에 시계를 붙이려면 같은 함수를 **한 벌 더** 쓰게 되는 자리였다. 그러면 두 화면의
// 시계가 서로 다른 모양이 될 수 있다 — 같은 PC 화면에서 위아래로 보이는데 하나는
// `09:07`, 하나는 `9:07` 이면 사람이 둘 중 뭘 믿을지 고민한다.
//
// **React 도 DOM 도 모르는 순수 함수다.** 그래서 `node --test` 가 그대로 돌린다 —
// 자정·한 자리 수 같은 경계는 눈으로 보기 어렵고 하루에 한 번만 재현된다.

const 요일 = ['일', '월', '화', '수', '목', '금', '토']

const 두자리 = (n) => String(n).padStart(2, '0')

/**
 * `2026년 09월 13일 (일)`
 * 월·일을 **두 자리로 맞춘다** — 목록에서 세로로 읽을 때 자리가 안 흔들린다.
 * @param {Date} date
 */
export function formatDate(date) {
  return `${date.getFullYear()}년 ${두자리(date.getMonth() + 1)}월 ${두자리(date.getDate())}일`
       + ` (${요일[date.getDay()]})`
}

/**
 * `09:07:42` — 24시간제. **오전/오후를 쓰지 않는다.**
 * 방송 시각이 전부 24시간제로 저장·표시되므로(`07:50`·`16:14`), 시계만 12시간제면
 * 사람이 머릿속에서 변환해야 한다. 화면 안에서 시각 표기는 한 가지여야 한다.
 * @param {Date} date
 */
export function formatTime(date) {
  return [date.getHours(), date.getMinutes(), date.getSeconds()].map(두자리).join(':')
}

