// **방송 화면 글자 크기 — 각 이름이 몇 배인지** (사용자 지시 2026-09-16).
//
// *"그 방송화면에 자막 크기 설정할 수 있게 끔 하게 해줘, 설정에서 크게, 중간, 작게"*
//
// 고를 수 있는 **이름**의 단일 출처는 서버(`server/domain/broadcastTextSize.js`)이고,
// 여기는 그 이름을 **배율**로 바꾼다. 두 목록은 `broadcast-text-size.test.js` 가 대조한다.
//
// ── 왜 「크게」가 1 인가 ────────────────────────────────────────────────────
// 2026-09-15 에 사용자가 방송 글자를 1.5 배로 키웠고 지금 화면이 그 크기다. 그래서
// **지금 크기 = 크게**로 두고 아래로만 줄인다. 위로 더 키우지 않는 이유가 있다 — 자막은
// 한 줄 글자 수(`captions.js` 의 MAX_CHARS)와 짝이라, 글씨만 키우면 줄이 넘쳐 도로
// 줄어든다(`BroadcastCaption` 머리말). 줄이는 쪽은 그 짝을 안 건드린다.
//
// 간격은 대략 한 단계에 18% 다 — 홀 TV 를 멀리서 볼 때 「달라졌다」가 보이는 최소 차이다.
// 이보다 촘촘하면 세 단추가 같은 결과처럼 보인다.
export const 글자크기들 = [
  { id: 'large',  이름: '크게', 배율: 1 },
  { id: 'medium', 이름: '중간', 배율: 0.82 },
  { id: 'small',  이름: '작게', 배율: 0.66 },
]

export const 기본글자크기 = 'large'

/** 이름 → 배율. 모르는 값은 「크게」(= 지금 화면)로 읽는다. */
export function 글자배율(id) {
  return (글자크기들.find(x => x.id === id) || 글자크기들[0]).배율
}

/**
 * CSS 크기 식에 배율을 곱한다. 배율이 1 이면 **원래 글자를 그대로** 돌려준다 —
 * `calc(… * 1)` 로 감싸면 값은 같아도 소스를 글자로 대조하는 시험이 옛 값을 못 찾는다.
 */
export function 크기곱(크기, 배율) {
  return 배율 === 1 ? 크기 : `calc(${크기} * ${배율})`
}

// ── 방송 화면 큰 글씨의 줄바꿈 (사용자 지적 2026-09-16) ─────────────────────────
// *"저렇게 화면에 따라 줄틀어지는거 안예쁘잖아"* — 표어의 한 낱말이 두 줄로 쪼개졌다.
// 한국어는 기본 줄바꿈이 **글자 단위**라 낱말 한가운데서 끊긴다.
//   keep-all   — 낱말째 다음 줄로 넘긴다
//   balance    — 두 줄 길이를 고르게 맞춘다(한 줄만 길고 다음 줄에 두 글자가 남지 않게)
//   break-word — 한 낱말이 화면보다 긴 드문 경우에만 끊는다(안 그러면 화면 밖으로 넘친다)
export const 방송글자줄바꿈 = { wordBreak: 'keep-all', textWrap: 'balance', overflowWrap: 'break-word' }
