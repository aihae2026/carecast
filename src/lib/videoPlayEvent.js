// 서버가 보낸 **영상 재생 신호**를 재생기가 읽는 모양으로 옮긴다 — 그 한 가지만 한다.
//
// 왜 화면 밖인가(V③ R18 지적 3 → R23 지적 1, 2026-09-14):
//   서버가 실어 보낸 칸 하나를 `useScheduledBroadcast` 의 변환이 **빼고 넘긴** 적이 있다.
//   그러면 재생기가 그 값을 못 보는데 **오류는 안 난다** — 소리와 자막만 조용히 어긋난다.
//
//   고친 뒤 붙인 가드가 **글자만 봤다.** 독립 검수가 그것을 깨뜨려 증명했다 —
//   *"메모리에서 실제 전달 코드를 `undefined` 로 바꿔도 단언이 통과했다."*
//   화면(.jsx) 안에 있으면 시험이 소스를 읽는 수밖에 없다. 여기로 내리면 **진짜로 부른다.**
//
// 그래서 이 파일에는 **그 사슬의 양 끝**이 함께 있다 — 옮기는 쪽과 읽는 쪽.
// 둘이 갈리면 가운데가 끊기고, 그 끊김이 그때 고친 바로 그 결함이다.
//
// ── 그 사고의 주인공(`delayProfile`)은 2026-09-16 에 없앴다 ──────────────────
// TV 싱크 보정값이 **하나로 합쳐져** 단계마다 갈래를 고를 일이 없어졌다
// (사용자 지시, `server/domain/videoSync.js` 머리말). **고를 것이 없으면 틀리게 고를
// 수도 없다** — 이 파일이 지키던 사고 유형 하나가 통째로 사라진 셈이다.
// 그래도 이 파일은 남는다: 칸을 빠뜨리는 실수는 **어느 칸에서든** 일어난다.

/**
 * 서버의 `video_play` payload → 재생기에 넘길 detail.
 *
 * **여기 없는 칸은 재생기에 안 간다.** 칸을 늘릴 때는 이 함수만 고친다 —
 * 화면이 제 안에서 따로 조립하면 또 한 칸이 조용히 빠진다.
 */
export function 영상재생상세(data = {}) {
  return {
    url:          data.url,
    name:         data.name,
    token:        data.token,
    category:     data.category,
    source:       data.source,
    videoId:      data.videoId,
    volume:       data.volume,
    rate:         data.rate,
    audioFileId:  data.audioFileId,
  }
}
