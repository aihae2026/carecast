// **단축키가 무엇을 뜻하는지 정하는 한 곳** (사용자 지시 2026-09-15).
//
// *"카드 나올 때, 취소버튼 누르는거 단축키 ESC로 해줘, 그리고 방송나갈때도 중간에
//   정지하려면 ESC 넣어주면서 정말 정지하시겠습니까? 이거 지금처럼 띄워주고"*
// *"일시정지 버튼도 만들어주고 이건 스페이스바로 단축키할까?"*
//
// ── 왜 규칙을 한 곳에 두나 ─────────────────────────────────────────────────
// 같은 키를 여러 화면이 각자 듣게 두면, 카드도 열려 있고 방송도 나가는 중일 때
// **둘 다 반응한다.** 카드가 닫히면서 방송도 멎거나, 반대로 아무 일도 안 일어난다.
// 어느 쪽이든 사람은 「단축키가 안 먹는다」로 겪는다.
//
// 그래서 **뜻을 정하는 일**은 여기서 하고, 화면은 그 답대로 움직이기만 한다.
// 순수 함수라 노드에서 그대로 돌려 본다.
//
// ── 우선순위: 방송이 제일 위다 ─────────────────────────────────────────────
// 소리가 나가는 중에는 그것을 멈추는 일이 급하다. 카드는 마우스로도 닫을 수 있지만,
// 전관 스피커로 나가는 소리는 **지금** 멈춰야 한다.
'use strict'

/**
 * 지금 글자를 적고 있는가.
 *
 * **이 검사가 없으면 방송 문안을 적다가 띄어쓰기를 누를 때마다 음악이 멎는다.**
 * 스페이스바를 전역 단축키로 쓰는 모든 화면이 겪는 함정이다.
 */
export function 글자입력중(대상) {
  if (!대상) return false
  const 태그 = String(대상.tagName || '').toUpperCase()
  if (태그 === 'INPUT' || 태그 === 'TEXTAREA' || 태그 === 'SELECT') return true
  if (대상.isContentEditable) return true
  return false
}

/**
 * 이 키가 지금 무엇을 뜻하나.
 *
 * @param {object} 상황
 * @param {string} 상황.key        눌린 키 (`event.key`)
 * @param {boolean} [상황.방송중]   지금 소리가 나가는 중인가
 * @param {boolean} [상황.카드열림] 초안 카드가 떠 있는가
 * @param {boolean} [상황.글자입력] 글자를 적는 칸에 초점이 있는가
 * @param {boolean} [상황.확인창]   「정말 정지하시겠습니까?」가 떠 있는가
 * @param {boolean} [상황.일시정지됨] 이미 멈춰 둔 상태인가
 * @returns {'정지'|'일시정지'|'다시'|'카드닫기'|null}
 */
export function 단축키뜻({ key, 방송중 = false, 카드열림 = false, 글자입력 = false, 확인창 = false, 일시정지됨 = false } = {}) {
  // 확인창이 떠 있으면 **그것이 전부다.** 뒤에 있는 것은 아무것도 안 듣는다 —
  // 「정말 정지하시겠습니까?」에 ESC 를 눌렀는데 카드까지 닫히면 사람이 무엇을
  // 취소한 것인지 모른다. (확인창을 닫는 일은 확인창 자신이 한다.)
  if (확인창) return null

  if (key === 'Escape') {
    // **방송이 카드보다 위다.** 둘 다 열려 있으면 방송을 멈춘다.
    if (방송중) return '정지'
    if (카드열림) return '카드닫기'
    return null
  }

  if (key === ' ' || key === 'Spacebar') {
    // **글자를 적는 중이면 아무 일도 안 한다.** 띄어쓰기를 뺏으면 안 된다.
    if (글자입력) return null
    if (!방송중) return null
    return 일시정지됨 ? '다시' : '일시정지'
  }

  return null
}

/**
 * 이 갈래를 일시정지할 수 있나.
 *
 * **안내 방송(`broadcast`)은 못 한다.** 그것은 서버가 단계를 순서대로 밟는 **시퀀스**라
 * (합성 → 재생 → 대기 → 다음), 중간에 멈춰 두면 서버의 시각 계산과 화면이 어긋난다.
 * 멈추는 길은 **정지** 하나다. 할 수 없는 일에 단추를 그려 놓고 눌러도 아무 일이 안
 * 일어나게 두는 것이 더 나쁘다 — 사람은 그것을 고장으로 읽는다.
 *
 * BGM 과 영상은 **이 창이 내는 소리**라 곧바로 멈췄다 이을 수 있다.
 */
export function 일시정지할수있나(갈래, 서버소리 = false) {
  // **즉시 방송은 서버 스피커가 낸다.** 이 창이 가진 소리가 아니라서 멈출 방법이 없다
  // (`routes/tts.js` 가 `audioQueue` 로 서버에서 재생한다). 그래서 갈래가 방송이어도
  // 서버 소리면 못 한다 — 단추를 그려 놓고 눌러도 아무 일이 없으면 고장으로 읽힌다.
  if (서버소리) return false
  return 갈래 === 'bgm' || 갈래 === 'video' || 갈래 === 'broadcast'
}
