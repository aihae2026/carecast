/**
 * 동의 시각(서버가 UTC ISO 로 적는다) → **이 PC 의 날짜** `YYYY-MM-DD`. 못 읽으면 ''.
 * ISO 문자열 앞 10글자를 자르면 UTC 날짜라, 한국 새벽(00~09시)의 동의가 전날로 보인다(2026-10-07 MT).
 */
export function 동의날짜(at) {
  const d = new Date(at)
  if (Number.isNaN(d.getTime())) return ''
  const 두자리 = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${두자리(d.getMonth() + 1)}-${두자리(d.getDate())}`
}

/** 다시 동의를 받아야 하나. 기록이 없거나 옛 판이면 그렇다. */
export function 동의필요(consent) {
  return !consent || consent.version !== 약관판
}

