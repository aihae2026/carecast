/** 분 단위 경계. `[시작분, 키]` 를 시간순으로 — 마지막 구간이 자정을 넘어 이어진다. */
const 경계 = [
  [5 * 60,        'dawn'],    // 05:00
  [8 * 60 + 30,   'day'],     // 08:30
  [16 * 60 + 30,  'dusk'],    // 16:30
  [19 * 60 + 30,  'night'],   // 19:30
]

/**
 * 그 시각이 하루의 어느 마디인가. **순수 함수다** — Date 를 받아 키만 낸다.
 * @param {Date} [now]
 * @returns {'dawn'|'day'|'dusk'|'night'}
 */
export function skyKeyAt(now = new Date()) {
  const 분 = now.getHours() * 60 + now.getMinutes()
  // 05:00 보다 이르면 아직 전날 밤이다.
  if (분 < 경계[0][0]) return 'night'
  let 키 = 'night'
  for (const [시작, k] of 경계) { if (분 >= 시작) 키 = k }
  return 키
}

/** 그 시각의 하늘 한 벌. */
export function skyAt(now = new Date()) {
  return SKY[skyKeyAt(now)]
}

/**
 * 덩어리 하나를 CSS `background-image` 한 겹으로 옮긴다.
 * `closest-side` + 70% 에서 투명 — 가장자리가 딱 끊기지 않고 번진다(블러 대신).
 */
// ── **가장자리에 「투명한 벽」이 생기지 않게** (사용자 지적 2026-09-14) ────────────────
// *"방송화면에서 왜 투명한 벽 같은 게 보여, 그라디언트에 섞여서"*
//
// 원인은 **정지점이 둘뿐**이었다는 것이다. `색 0% → 투명 70%` 한 구간으로 떨어뜨리면
// 그 사이가 **직선으로** 보간된다. 사람 눈은 그 직선이 끝나는 70% 지점의 꺾임(밝기
// 기울기가 갑자기 0이 되는 자리)을 **또렷한 테두리**로 읽는다 — 물감이 아니라 유리벽이다.
// 넓은 화면일수록 그 원이 커져서 더 잘 보인다(홀 TV 가 가장 나쁜 조건이다).
//
// 그래서 가운데에 정지점을 둘 더 놓아 **바깥으로 갈수록 천천히** 사라지게 한다. 알파가
// 0 에 가까워지는 속도가 완만해져 꺾임이 눈에 안 띈다. 색도 반지름도 그대로다 —
// 사라지는 **결**만 바꿨다.
export function blobLayer({ c, x, y, r, o }) {
  return `radial-gradient(${r}% ${r}% at ${x}% ${y}%, `
    + `${c}${알파(o)} 0%, `
    + `${c}${알파(o * 0.62)} 32%, `
    + `${c}${알파(o * 0.26)} 54%, `
    + `${c}${알파(o * 0.07)} 72%, `
    + `${c}00 88%)`
}

/** 0~1 불투명도를 8자리 hex 의 알파 두 글자로. */
function 알파(o) {
  return Math.round(Math.max(0, Math.min(1, o)) * 255).toString(16).padStart(2, '0')
}

/**
 * 화면에 바로 얹을 수 있는 스타일 한 벌.
 * 겹 순서는 **앞이 위**다 — 배열 앞쪽 덩어리가 더 위에 온다.
 */
export function skyStyle(now = new Date()) {
  const 하늘 = skyAt(now)
  return {
    backgroundColor: 하늘.base,
    backgroundImage: 하늘.blobs.map(blobLayer).join(', '),
  }
}
