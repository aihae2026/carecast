// **무엇/다음을 지어내지 않는다** — 모르면서 아는 척하면 사람을 더 멀리 보낸다.
export function 연동오류읽기(오류) {
  const 원문 = 오류 == null ? ''
    : typeof 오류 === 'string' ? 오류
      : (오류.error || 오류.message || String(오류))
  const 글 = 원문가리기(원문)
  for (const r of 규칙) {
    if (r.걸림.test(글)) return { 종류: r.종류, 무엇: r.무엇, 다음: r.다음, 원문: 글 }
  }
  return {
    종류: 'unknown',
    무엇: '연결에 실패했습니다.',
    다음: '아래 원문이 무엇을 말하는지 확인해 주세요. 같은 말이 되풀이되면 그 문장을 그대로 알려 주시면 됩니다.',
    원문: 글,
  }
}

// 성공했을 때도 같은 모양으로 말한다 — 화면마다 "정상"·"OK"·"성공" 이 갈리지 않게.
export function 연동성공읽기(덧말) {
  return { 종류: 'ok', 무엇: '연결됐습니다.', 다음: 덧말 || '', 원문: '' }
}
