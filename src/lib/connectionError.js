// 연동 오류를 **사람이 다음에 뭘 하면 되는지**로 옮긴다 (UX-10, 2026-09-11).
//
// 지금까지 각 연동 카드는 받은 오류 문자열을 **그대로** 띄웠다 — `fetch failed`,
// `401 유효한 인증키가 아닙니다`, `UND_ERR_CONNECT_TIMEOUT`. 이 말들은 무엇이
// 잘못됐는지도, 무엇을 하면 되는지도 알려주지 않는다. 시설 실무자가 읽는 화면이다.
//
// **더 나쁜 것은 이 말들이 사람을 엉뚱한 데로 보낸다는 것이다.** 이 저장소가 그걸
// 두 번 겪었고 CLAUDE.md 에 적어 뒀다:
//
//   · `401 유효한 인증키가 아닙니다` — 키가 틀린 게 아니라 **다른 서비스의 키**였다.
//     data.go.kr 키 하나를 네 칸에 전부 붙여 넣어 날씨·자외선·미세먼지가 통째로 401.
//     길이부터 다르다(apihub 22자 · 자외선 88자).
//   · `UND_ERR_CONNECT_TIMEOUT` — 키 문제가 아니라 **그 호스트에 안 닿는 것**이었다.
//     같은 시각 apihub 는 136ms 로 멀쩡했다. 키를 의심하다 시간을 버린다.
//
// 그 지식을 문서에만 두면 다음 사람은 또 헤맨다. 화면이 말하게 한다.
//
// 원문은 **버리지 않는다** — 접어서 함께 둔다. 우리가 못 알아본 오류를 사람이
// 검색이라도 할 수 있어야 하고, 조용히 삼키면 그게 더 오래 걸린다.

// **원문에 키가 섞여 있을 수 있다.** 기상청·에어코리아는 키를 **URL 질의**로 보내서,
// 타임아웃 오류 문구에 `...?serviceKey=xxxx` 가 통째로 들어오는 일이 있다. 그걸 화면에
// 그대로 띄우면 어깨너머로 보이고 스크린샷에 남는다(Codex 지적, 2026-09-11 EV-004644).
//
// 그렇다고 원문을 **버리지는 않는다** — 우리가 못 알아본 오류를 사람이 검색이라도 해야
// 한다. 가릴 것만 가리고 나머지는 그대로 둔다.
// **이름을 하나씩 세지 않는다.** 처음엔 `serviceKey|authKey|key|token|secret` 만 적었다가
// `x-api-key:` · `Authorization: Basic …` · `?client_secret=` 을 통째로 놓쳤다
// (Codex 지적, 2026-09-11 EV-004651). 헤더 모양을 손으로 세다 세 판 진 것과 같은 실수다.
// 그래서 **비밀을 가리키는 낱말이 들어간 이름이면 무엇이든** 가린다.
const 비밀낱말 = 'key|secret|token|password|passwd|credential|auth'

const 비밀이름인가 = (이름) => {
  let 편 = String(이름)
  // `service%4Bey` 처럼 이름이 인코딩돼 올 수 있다. 풀어서 본다.
  try { 편 = decodeURIComponent(편) } catch { /* 잘못된 인코딩이면 원래 것으로 본다 */ }
  return new RegExp(비밀낱말, 'i').test(편)
}

export function 원문가리기(글) {
  return String(글 ?? '')
    // ⓪ 따옴표로 묶인 값은 **닫는 따옴표까지** 가린다 — 공백이 들어 있으면
    //     **질의 규칙보다 먼저 돈다**(Codex R12 지적 2026-09-12). 질의 규칙이 먼저 돌면
    //     `?token=abc\` 의 **escape 역슬래시까지 지워** 버리고, 그러면 이 규칙이 그 따옴표를
    //     값의 끝으로 읽는다 — `{"password":"dummy ?token=abc\"secret\" tail"}` 에서
    //     `secret`·`tail` 이 남았다. 따옴표로 묶인 값이 **더 넓은 덩이**라 먼저 가려야 한다.
    //     첫 낱말만 가리고 나머지가 남았다(`"dummy secret value"`, EV-004691).
    //     **진단 필드 이름은 여기서도 비켜 간다** — JSON 안의 `"keySource":"kma_…"` 까지
    //     가려서 진단을 못 하게 만들었다(Codex 지적, EV-004698). 아래 규칙에만 예외를
    //     두고 여기엔 안 둬서 났다 — 예외는 **두 곳 모두**에 있어야 한다.
    //     **값 안에 다른 종류의 따옴표가 섞여도 닫는 따옴표까지 간다**(Codex R10 지적
    //     2026-09-12). 예전엔 값을 `[^"']*` 로 읽어서 `password='dummy "secret" value'` 가
    //     `password=*** "secret" value'` 로 **뒷부분이 남았다.** 여는 것과 **같은** 따옴표를
    //     만날 때까지 읽는다(역참조로 가른다).
    //
    //     **역슬래시로 escape 된 따옴표는 값의 끝이 아니다**(Codex R11 지적, 같은 날).
    //     `JSON.stringify({password:'dummy "secret" value'})` 는
    //     `{"password":"dummy \"secret\" value"}` 가 되는데, escape 를 모르면 그 `\"` 에서
    //     멈춰 `secret`·`value` 가 남았다. 이 글은 화면에 그대로 뜬다
    //     (`ConnectionErrorNote.jsx`). `\\.` 를 **먼저** 먹어서 그 뒤를 닫는 따옴표로 안 본다.
    .replace(new RegExp(`(["']?[\\w.-]*(?:${비밀낱말})[\\w.-]*(?<!Source|Masked|Set|Name|Type|Id|IsEncoded)["']?\\s*[:=]\\s*)(["'])((?:\\\\.|(?!\\2)[\\s\\S])*)\\2`, 'gi'), '$1$2***$2')
    // ⓪-2 **질의는 이름으로 가른다.** 값의 생김새로 추측하던 규칙은 걷어냈다 —
    //    `filename=weather_diagnostic_report.json` 같은 멀쩡한 값까지 지웠다
    //    (Codex 지적, 2026-09-11 EV-004691). 이름을 풀어 보면 인코딩된 이름도 잡히고,
    //    값이 짧아도 잡힌다. **진단을 지우는 쪽보다 이름을 믿는 쪽이 낫다.**
    .replace(/([?&])([\w.%-]+)=([^&\s"']*)/g,
      (전체, 앞, 이름, 값) => (값 && 값 !== '***' && 비밀이름인가(이름)) ? `${앞}${이름}=***` : 전체)
    // ① **방식이 앞에 붙은 값부터.** `Authorization: Bearer ya29…` 를 ②가 먼저 만나면
    //    `Bearer` 만 가리고 **토큰은 그대로 남는다** — 실제로 그렇게 났다(EV-004663).
    //    **길이를 안 따진다** — `Bearer` 가 앞에 있으면 그 뒤는 자격증명이다.
    //    예전엔 6자 미만을 봐줘서 `Bearer abc12` 가 그대로 나갔다(EV-004679).
    .replace(/\b(Bearer|Basic|Token)\s+(?!\*\*\*)[A-Za-z0-9._~+/=-]+/gi, '$1 ***')
    // ② 질의 문자열 — `?serviceKey=…` · `&client_secret=…` · `&x_api_key=…`
    .replace(new RegExp(`([?&][\\w.-]*(?:${비밀낱말})[\\w.-]*=)[^&\\s"']+`, 'gi'), '$1***')
    // ③ 헤더·키=값·**JSON** 모양 — `x-api-key: …` · `apiKey="…"` · `{"apiKey":"…"}`
    //    JSON 은 이름 뒤에 **닫는 따옴표**가 붙어서(`"apiKey":`) 그것을 허용해야 한다 —
    //    안 그러면 통째로 빠져나간다(Codex 재현, 2026-09-11 EV-004669).
    //    이미 가린 것과 방식 낱말은 건드리지 않는다(그러면 `*** ***` 이 된다).
    //    **길이를 안 따진다.** 이름이 "비밀" 이라고 말하는데 값이 짧다고 봐주면
    //    `{"password":"abc12"}` 가 그대로 나간다(Codex 재현, 2026-09-11 EV-004679).
    //    다만 **우리 진단 필드 이름**(`keySource`·`keyMasked`·`keySet`…)은 값이 비밀이
    //    아니라 설명이다 — 그것까지 가리면 진단을 못 한다. 이름 끝으로 가른다.
    //    **이미 가린 것은 따옴표째로 건너뛴다**(2026-09-12). 앞 규칙이 `password='***'` 로
    //    바꿔 놓은 것을 이 규칙이 다시 만나면 `'` 를 값의 일부로 읽어 **여는 따옴표를
    //    삼켰다** — `password=***'` 처럼 짝이 안 맞는 글이 남는다. 비밀이 새는 것은
    //    아니지만, 읽는 사람이 "뭔가 잘렸다"로 보고 원문을 다시 찾게 만든다.
    .replace(
      new RegExp(`\\b([\\w.-]*(?:${비밀낱말})[\\w.-]*(?<!Source|Masked|Set|Name|Type|Id|IsEncoded)["']?\\s*[:=]\\s*)(?!["']?\\*\\*\\*|Bearer\\b|Basic\\b|Token\\b)["']?[^\\s"',;)}\\]]+`, 'gi'),
      '$1***')
    // ④ Google API 키는 생김새가 뚜렷하다 — 아래 규칙이 맡는다.
    //
    // **값의 생김새로 추측하는 규칙은 두지 않는다.** 한때 "20자 넘는 불투명 질의값"을
    // 전부 가렸는데, UUID·파일명까지 지워 **진단을 못 하게 만들었다**(EV-004679·EV-004691).
    // 가리기는 덜 가려도 새고, 너무 가려도 못 쓴다. 이름으로 가르는 쪽을 택했다.
    // 그래서 **이름을 전혀 알아볼 수 없는 키 질의는 여기서 못 잡는다** — 그 자리는
    // 서버가 자기 키 값을 직접 지워서 막는다(`routes/weather.js` 의 `키가리기`).
    // ④ Google API 키는 생김새가 뚜렷하다(AIza…). 이름 없이 적혀 있어도 가린다.
    .replace(/\bAIza[A-Za-z0-9_-]{10,}/g, 'AIza***')
}

