// 첫 화면의 **큰 제목** — 도는 한 줄.
//
// ── 무엇을 푸는가 (사용자 지시 2026-09-15) ─────────────────────────────────────
// *"기능 메뉴얼 논리 구조와 문구 규칙이 연결 파싱 되어서 **AI 개입 없어도** 자동으로
//   기능 안내 등등이 나갈 수 있도록."*
//
// 그전까지 첫 화면에는 「무엇을 방송할까요?」 **한 문장이 고정**으로 박혀 있었다.
// 그래서 이 시스템이 무엇을 할 수 있는지는 **매뉴얼을 열어야만** 알 수 있었고,
// 요양원 직원이 매뉴얼을 열 이유는 없다 — 쓸 줄 아는 기능만 쓰고 나머지는 없는 것이 된다.
//
// ── 작은 줄을 큰 제목에 합쳤다 (사용자 결정 2026-09-15) ─────────────────────────
// 처음엔 제목 아래 **13px 작은 줄**을 따로 뒀다(`HomeTip`). 그런데 그러면 따뜻한 말이
// 두 군데로 갈린다 — 제목은 고정이고 작은 줄만 도니까, 정작 사람이 보는 큰 글씨는
// 아무것도 안 알려 준다. 사용자 결정으로 **큰 제목 하나로 합쳤다.**
//
// **문장도 차례도 서버가 정한다**(`domain/guideTips.js`). 여기서는 받아서 그리고,
// 시간을 재서 넘길 뿐이다 — 규칙이 화면과 서버 두 벌이 되면 언젠가 갈린다.
//
// ── 조용히 실패한다 ─────────────────────────────────────────────────────────
// 못 받아도 **제목은 남는다.** 이 줄은 h1 이라, 안내 한 줄이 실패했다고 화면에서
// 제목이 통째로 사라지면 그게 더 큰 고장이다. 그래서 못 받으면 닻 문구로 돌아간다.
import { useEffect, useMemo, useState } from 'react'
import { getTodaySchedule, getHomeTip } from '../../lib/api'

// 차례표를 다시 묻는 간격. `HomeToday` 와 **같은 60초**다 — 다른 값을 쓰면 목록의
// 「안 나감」과 이 제목이 한동안 다른 말을 한다.
//
// **차례가 넘어가는 간격은 여기 없다.** 칸마다 `머무는초` 가 붙어서 온다(닻 12초 ·
// 곁말 9초, `guideTips.차례짜기`). 예전엔 이 폴링이 회전 상태에 걸려 있어서 **60초
// 타이머가 한 번도 안 울렸다** — 12초마다 서버를 두 번씩 불렀다. 둘은 남남이다.
const 물어보는간격 = 60_000

// 글자가 지워지는 데 걸리는 시간. 이만큼 뒤에 **글자를 바꾸고** 다시 또렷해진다.
// 들어오는 것도 같은 시간이라 한 번 바뀌는 데 1.4초다.
//
// **380ms 에서 늘렸다** (사용자 지적 2026-09-15: *"블러 처리속도가 너무 빠르다"*).
// 이 자리는 36px 짜리 큰 제목이라 **눈이 따라갈 거리가 길다** — 작은 줄이던 때의
// 값을 그대로 쓰니 글자가 깜빡 바뀌는 것처럼 보였다. 머무는 시간이 9~12초라
// 1.4초를 써도 읽을 시간은 그대로 넉넉하다.
const 지우는시간 = 700
// 물감이 훑고 지나가는 시간. **지우고 띄우는 동안을 다 덮어야** 중간에 끊기지 않는다
// (700 + 700 = 1400 보다 길다).
const 훑는시간 = 1600

// 못 받았을 때 돌아갈 자리. 서버의 `guideTips.닻문구` 와 **같은 문장이어야 한다** —
// `server/test/guide-tips.test.js` 가 두 파일을 대조해서 고정한다.
const 닻문구 = '무엇을 방송할까요?'
const 기본문구 = { text: 닻문구, kind: 'anchor' }

export default function HomeHeadline() {
  const [계획, set계획] = useState(null)      // { 붙잡는말, 차례 }
  const [칸, set칸] = useState(0)
  const [지워짐, set지워짐] = useState(false)
  const [물결, set물결] = useState(0)          // 물감을 한 번 더 훑게 하는 번호

  // ── 차례표 받기 ─────────────────────────────────────────────────────────
  // **회전과 아무 상관이 없다.** 의존성이 비어 있어야 60초 타이머가 산다.
  useEffect(() => {
    let 죽음 = false
    const 읽기 = async () => {
      try {
        // **오늘 목록을 같은 창구로 받는다**(`/api/schedules/today`). 서버가 따로 세면
        // 화면의 「안 나감」과 이 제목이 갈린다 — 판정이 두 벌이면 사람이 둘 다 안 믿는다.
        const r = await getTodaySchedule()
        const p = await getHomeTip(Array.isArray(r?.items) ? r.items : [])
        if (!죽음) set계획(p && typeof p === 'object' ? p : null)
      } catch { if (!죽음) set계획(null) }
    }
    읽기()
    const t = setInterval(읽기, 물어보는간격)
    return () => { 죽음 = true; clearInterval(t) }
  }, [])

  // **`useMemo` 를 쓰는 이유가 있다.** 이 둘을 그냥 계산하면 **매 렌더마다 새 값**이 되고,
  // 아래 두 효과의 의존성이 계속 바뀌어 **타이머가 매번 처음부터 다시 걸린다.**
  // 지워짐·물결이 바뀔 때마다 머무는 시간이 그만큼 뒤로 밀린다 — 방금 고친 것과 같은
  // 종류의 버그다(상수에 적힌 시간과 실제로 도는 시간이 갈린다).
  const { 붙잡는말, 차례 } = useMemo(() => ({
    붙잡는말: 계획?.붙잡는말?.text ? 계획.붙잡는말 : null,
    차례: Array.isArray(계획?.차례) ? 계획.차례.filter(x => x?.text) : [],
  }), [계획])
  const 보일것 = useMemo(
    () => 붙잡는말 || 차례[차례.length ? 칸 % 차례.length : 0] || 기본문구,
    [붙잡는말, 차례, 칸])

  // ── 차례 넘기기 = 지웠다가 띄우기 ───────────────────────────────────────
  // **칸마다 머무는 시간이 다르다.** 그래서 `setInterval` 이 아니라 한 칸씩 `setTimeout`
  // 이다 — 고정 간격으로 돌리면 닻이 더 오래 머물게 할 수가 없다.
  //
  // 글자를 **그 자리에서 바꾸지 않는다.** 머무는 시간이 끝나면 먼저 흐려지고(=지워짐),
  // 다 지워진 뒤에 칸을 넘기면서 동시에 또렷해진다. 그 사이를 물감이 한 번 훑는다.
  // 칸과 지워짐을 **같이 놓는 것이 핵심**이다 — React 가 한 번에 반영하므로 새 글자가
  // 흐린 상태에서 나타나 또렷해진다. 따로 놓으면 헌 글자가 한 번 또렷해졌다 사라진다.
  //
  // **둘을 한 효과에 둔 이유**: 나눠서 「글자가 바뀌면 지운다」로 쓰면 효과 본문에서
  // 곧바로 `setState` 를 부르게 되고(연쇄 렌더), `react-hooks/set-state-in-effect` 가
  // 막는다. 타이머 **콜백 안**에서 바꾸면 그 문제가 아예 없다.
  //
  // **붙잡는 말이 있으면 안 돈다.** 안 나간 방송은 12초 뒤에도 안 나간 채다.
  useEffect(() => {
    if (붙잡는말 || 차례.length < 2) return
    const 초 = Number(차례[칸 % 차례.length]?.머무는초) || 10
    let 띄우기
    const 지우기 = setTimeout(() => {
      set지워짐(true)
      set물결(n => n + 1)
      띄우기 = setTimeout(() => { set칸(n => n + 1); set지워짐(false) }, 지우는시간)
    }, 초 * 1000)
    return () => { clearTimeout(지우기); clearTimeout(띄우기) }
  }, [붙잡는말, 차례, 칸])

  // ── **이 자리는 나무라지 않는다** (사용자 결정 2026-09-15) ────────────────────
  // 한때 여기서 「○○이 안 나갔어요.」를 빨간 글씨로 띄웠다. 색을 먼저 걷었고
  // (*"안 나갔어요 하면 되지 왜 빨간색 입혀"*), 그다음 **문구 자체를 걷었다**
  // (*"오래 떠있으니까 부정적인 느낌이 들어… 어차피 상태로 확인 가능하니까"*).
  //
  // 그래서 여기엔 **급함이라는 갈래가 없다.** 안 나간 방송은 오늘 일과방송 목록의
  // 「안 나감」과 경보가 보여 준다 — 규칙은 `domain/guideTips.차례짜기` 한 곳이다.
  // 읽어 주기(`aria-live`)도 끈다: 9초마다 제목을 소리로 읽으면 그게 잔소리다.

  return (
    <span className="relative inline-block">
      {/* 물감이 훑고 지나간다 — 배경 물감과 **같은 토큰**이라 새 색이 아니다.
          장식이므로 `aria-hidden` 이고, 글자 뒤(`-z-10`)에서 아주 엷게만 지난다. */}
      {물결 > 0 && (
        <i key={물결} aria-hidden="true"
           className="pointer-events-none absolute -inset-x-[18%] -inset-y-[30%] -z-10 block
                      rounded-full mix-blend-multiply opacity-0
                      motion-safe:animate-[cc-headline-wash_1600ms_ease-out]"
           style={{
             animationDuration: `${훑는시간}ms`,
             filter: 'blur(26px)',
             background: 'linear-gradient(100deg,'
               + ' rgba(var(--ds-v3-drop-tts),0) 0%,'
               + ' rgba(var(--ds-v3-drop-tts),.9) 26%,'
               + ' rgba(var(--ds-v3-drop-bgm),.9) 62%,'
               + ' rgba(var(--ds-v3-drop-bgm),0) 100%)',
           }} />
      )}
      {/* 글자. 읽어 주기는 끈다 — 9초마다 제목을 소리로 읽으면 그건 잔소리다. */}
      <span aria-live="off"
            style={{ transitionDuration: `${지우는시간}ms` }}
            className={'block transition-[filter,opacity,transform] ease-out '
              + 'motion-reduce:transition-none '
              + (지워짐 ? 'opacity-0 blur-[10px] scale-[1.03]' : 'opacity-100 blur-0 scale-100')}>
        {보일것.text}
      </span>
    </span>
  )
}
