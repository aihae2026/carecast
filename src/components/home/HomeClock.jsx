// 머리줄의 **시계 한 덩어리** — 날짜 · 시각 · 날씨가 세로로 쌓인다.
//
// ── 왜 세로로 묶었나 (사용자 지시 2026-09-16) ────────────────────────────────
// *"윗줄 너무 지저분해 보이지 않아? 차라리 실시간 시간을 좀 더 크게 해서 가운데로 오고,
//   그다음 일자를 위에, 그 아래에 날씨정보 들어가서 콤팩트하게 놓으면 좀 덜 지저분해
//   보이지 않을까?"*
//
// 맞는 지적이다. 앞 판은 머리줄에 **가로로 다섯 덩어리**가 줄줄이 섰다 —
// 로고 · 메뉴 · 크게 보기 · 시각+날짜 · 날씨. 그 사이를 세로선이 갈라서 눈이 다섯 번
// 멈춘다. 그런데 **시각·날짜·날씨는 원래 한 가지 이야기다**(「지금 여기는 이렇다」).
// 한 이야기를 세 덩어리로 늘어놓은 것이 어수선함의 정체였다.
//
// 이제 **한 덩어리 세 줄**이다. 가로로 먹는 자리가 절반 아래로 줄고, 머리줄에 남는
// 덩어리는 셋뿐이다.
//
// ── 크기 — 자주 보는 것이 가장 크다 ────────────────────────────────────────
//   날짜 13px 잉크3 ·  **시각 22px 잉크** ·  날씨 13px 잉크2
// 이 화면에서 시각은 **방송 시각과 맞춰 보는 값**이라 셋 중 가장 크다(초까지 그린다).
// 날짜와 날씨는 곁눈으로 확인하는 것이라 조용히 둔다.
//
// **줄 높이를 꽉 조인다**(leading-none 계열). 세 줄이 64px 머리줄 안에 들어가야 한다 —
// 기본 행간으로 두면 75px 이 되어 머리줄이 늘어나고, 그러면 밑의 글과 겹친다
// (2026-09-16 에 실제로 그 사고가 났다).
//
// ── 숫자가 흔들리지 않게 ───────────────────────────────────────────────────
// `tabular-nums` 는 초를 그리는 지금 **필수**다. 없으면 `1` 과 `0` 의 폭이 2.5px 씩
// 달라(Pretendard 실측) 1초마다 위아래 줄이 좌우로 흔들린다.
import { useEffect, useState } from 'react'
import { formatDate, formatTime } from '../../lib/clock'

export default function HomeClock() {
  const [now, setNow] = useState(() => new Date())

  useEffect(() => {
    const t = setInterval(() => setNow(new Date()), 1000)
    return () => clearInterval(t)
  }, [])

  return (
    // **가운데 선다**(사용자 지시 2026-09-16: *"날짜랑 시간을 가운데 배치"*).
    // `HomeShell` 이 이 덩어리를 자리에서 빼내 화면 한가운데(`absolute left-1/2`)에 세운다.
    // **세로선을 걷었다** — 가운데에 있으면 무엇과 갈리는지가 이미 자리로 보인다.
    //
    // ── 왜 `tablet`(834px) 이 아니라 `laptop`(1024px) 부터인가 (2026-09-16 정정) ──
    // 자리에서 빠져 있다는 것은 **다른 것이 그 자리를 비켜 주지 않는다**는 뜻이다.
    // 834px 에서는 탭 다섯이 이미 한 줄을 거의 다 쓰고 있어서 시계가 그 위에 겹쳐
    // 올라앉았다 — 사용자가 창을 줄여 실제로 보았다(*"시간 쪽 겹쳐지는거 버그 보이지?"*).
    //
    // 겹침을 막는 장치는 **둘**이고 둘 다 필요하다:
    //   ① 여기 — 자리가 나는 폭(1024px)부터 그린다.
    //   ② `HomeShell` 의 탭 줄 `max-w` — 탭이 가운데로 넘어오지 못하게 막는다.
    // ① 만 두면 1024px 바로 위에서 탭이 늘어날 때 다시 겹치고, ② 만 두면 834~1024px
    // 에서 탭 다섯이 좁은 칸에 갇혀 가로로 밀린다.
    <div className="hidden laptop:flex min-w-0 flex-col items-center justify-center leading-none">
      {/* 날짜 — 하루에 한 번 보면 되는 값이라 가장 조용하다.
          `aria-hidden` 을 안 준다: 날짜는 정보다. 다만 `<time>` 은 아래 시각 쪽에 준다
          (같은 순간을 두 번 알릴 필요가 없다). */}
      <span className="whitespace-nowrap text-[13px] text-ds-v3-ink-3">
        {formatDate(now)}
      </span>

      {/* 시각 — 이 덩어리의 주인공. **낭독기가 1초마다 읽지 않게** `aria-live` 를 안 건다
          (기본값 off). 사람이 원할 때 읽으러 오는 값이다. */}
      <time dateTime={now.toISOString()}
        className="mt-0.5 whitespace-nowrap text-[22px] font-semibold tabular-nums
                   tracking-tight text-ds-v3-ink">
        {formatTime(now)}
      </time>

    </div>
  )
}
