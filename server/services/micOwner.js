// 마이크 생방송의 **주인이 누구인가** — 한 곳에서만 정한다 (P-63, 2026-09-11).
//
// ── 무엇이 문제였나 ────────────────────────────────────────────────────────
//
// [FACT] EV-004033 — 재현:
//   · `audioPlayer.playChunk(data)` 는 인자가 데이터 하나뿐이라 **누가 보냈는지 모른다**
//   · 단일 방송자 개념은 `server/index.js` 의 WS 업그레이드 **클로저 지역 변수**
//     `broadcaster` 에만 있고 모듈로 안 나간다
//   · 그래서 HTTP 폴백(`routes/mic.js` 의 `POST /stream`)은 그것을 **볼 수조차 없다**
//
// 두 기기가 동시에 HTTP 폴백으로 보내면 **청크가 섞여 한 스피커로 나간다.**
// 요양원에서는 "두 사람 목소리가 겹쳐 나간다" 가 된다 — 안내 방송에서 가장 나쁜 종류다.
//
// ── 왜 여기(services)인가 ──────────────────────────────────────────────────
//
// 옆에 `micLive.js` 가 이미 **"지금 생방송 중인가"** 를 안다. "누가" 를 같은 층에 두면
// WS 경로와 HTTP 폴백이 **같은 것**을 본다. `index.js` 안의 지역 변수로 두면 지금과
// 똑같이 한쪽만 알게 된다 — 그것이 이 결함의 뿌리였다.
//
// ── 조용히 굳지 않는다 ────────────────────────────────────────────────────
//
// 창을 그냥 닫으면 `놓기` 가 안 온다. 그때 주인이 **영영 남으면 아무도 마이크를 못 쓴다** —
// 겹쳐 나가는 것보다 나쁠 수 있다(급할 때 방송이 아예 안 된다). 그래서 마지막 청크로부터
// 일정 시간이 지나면 **저절로 풀린다.** `micLive.HOLD_MS`(신호등이 꺼지는 시간)보다
// 넉넉히 잡는다 — 표시가 꺼졌다고 곧바로 남이 끼어들면 말이 끊긴다.
'use strict'

// 마지막 청크 뒤 이만큼 조용하면 주인을 놓는다.
// `micLive.HOLD_MS`(신호등)보다 길다 — 잠깐 숨을 고르는 것과 방송이 끝난 것은 다르다.
const 만료MS = 15000

let _주인 = null          // 기기 이름표(탭 id 등). 없으면 아무도 안 잡고 있다.
let _마지막 = 0           // 그 주인이 마지막으로 무언가 보낸 시각
let _시계 = null          // 테스트용 가짜 시계. 평소엔 null 이라 Date.now() 를 쓴다.

const 지금 = () => (_시계 === null ? Date.now() : _시계)

/** 만료됐으면 조용히 놓는다. 읽는 쪽이 늘 최신 상태를 보게 한다. */
function _만료정리() {
  if (_주인 !== null && 지금() - _마지막 > 만료MS) { _주인 = null; _마지막 = 0 }
}

/** 지금 주인. 없으면 `null`. */
function 지금주인() { _만료정리(); return _주인 }

/**
 * 마이크를 잡는다.
 * @returns {boolean} 잡았으면 true. **남이 쓰고 있으면 false** — 그때는 보내면 안 된다.
 */
function 잡기(이름) {
  if (!이름) return false          // 이름 없이는 못 잡는다. 누구인지 모르면 놓을 수도 없다.
  _만료정리()
  if (_주인 !== null && _주인 !== 이름) return false
  _주인 = 이름
  _마지막 = 지금()
  return true
}

/**
 * 마이크를 놓는다. **남의 것은 못 놓는다** — 실수로 남의 방송을 끊지 않게.
 */
function 놓기(이름) {
  if (_주인 !== null && _주인 === 이름) { _주인 = null; _마지막 = 0 }
}

/**
 * 이 이름이 지금 보내도 되는가.
 *
 * **이름을 안 주면 통과시킨다(하위 호환).** 아직 이름을 안 실어 보내는 호출부가 있으면
 * 그것까지 막는 순간 **기존 방송이 죽는다** — 고치려던 것보다 나쁜 결과다.
 * 이름을 준 호출만 소유권을 본다.
 */
function 주인인가(이름) {
  if (이름 === null || 이름 === undefined) return true
  _만료정리()
  if (_주인 === null) { _주인 = 이름; _마지막 = 지금(); return true }  // 아무도 없으면 이 사람이 주인
  if (_주인 !== 이름) return false
  _마지막 = 지금()
  return true
}

module.exports = {
  잡기, 놓기, 주인인가, 지금주인,
  __test__: {
    만료MS,
    리셋() { _주인 = null; _마지막 = 0; _시계 = null },
    시계(t) { _시계 = t },
  },
}
