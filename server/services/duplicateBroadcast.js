/**
 * **같은 방송이 겹쳐 나가지 않게 막는다.**
 *
 * 전관 스피커로 나간 소리는 되돌릴 수 없다. 그런데 같은 방송이 두 번 나가는 길은
 * 화면 단추를 잠가도 남는다 —
 *   · 응답이 늦어 **브라우저가 재시도**한다(사람은 한 번 눌렀다).
 *   · **다른 PC·다른 창**에서 같은 방송을 누른다(현장에 원격 PC 가 있다).
 *   · 잠그기 전에 손가락이 두 번 닿는다(페르소나 P3 「두 번 누르는 시설장」).
 * 그래서 마지막 방어선은 서버다.
 *
 * ── 규칙: 시간 창이 아니라 「아직 나가고 있나」 ──────────────────────────────
 * "5초 안에 같은 요청이면 막는다" 같은 창은 **짧으면 못 막고 길면 재방송을 막는다.**
 * 재방송은 현장에서 자주 쓰는 기능이라(같은 안내를 한 번 더) 막으면 안 된다.
 * 그러므로 **그 방송이 끝나는 순간 잠금을 푼다.** 끝난 뒤에는 몇 번이든 다시 나간다.
 *
 * ── 고장 모드와 상한 ────────────────────────────────────────────────────────
 * 이 장치의 고장은 **열쇠가 끼는 것**이다 — 풀어 줄 자리가 예외로 건너뛰어지면 그 방송은
 * **영영 안 나간다.** 막으려던 것(두 번 나감)보다 나쁜 결과다(무음은 이 저장소에서 가장
 * 비싼 실패다). 그래서 `최대잠금ms` 상한을 둔다. 상한이 지나면 잠금은 없는 것으로 본다.
 */
'use strict'

/** 한 방송이 아무리 길어도 이보다 오래 잠가 두지 않는다. */
const 최대잠금ms = 60_000

/**
 * **예약 수동재생에서만 쓰는 「두 번 누름」 창** (V③ 지적, 2026-09-14).
 *
 * 즉시 TTS(`/api/tts/broadcast`)는 재생이 끝나는 순간을 **정말로 안다** — 대기열이 돌려주는
 * 약속이 그때 풀린다. 그래서 그쪽은 「아직 나가고 있나」를 그대로 쓴다.
 *
 * **예약 수동재생은 그것을 모른다.** `fireSchedule` 은 브라우저에 재생을 **지시하고 바로
 * 돌아온다**(`scheduler.js:538` 에서 쏘고 `:568` 에서 기록하고 끝) — 실제 소리는 그 뒤에
 * 브라우저에서 난다. 그래서 발사 약속이 풀리는 것으로 잠금을 풀면 **몇 밀리초 만에 풀려**
 * 사실상 아무것도 안 막는다. 검수관이 그것을 짚었고, 내 시험은 **기다리는 대역**을 써서
 * 그 차이를 못 봤다(가짜 오라클).
 *
 * 그래서 **거짓말을 걷는다.** 이 길은 「재생이 끝날 때까지」가 아니라 **「두 번 누름을 막는
 * 창」**이다. 이름과 주석이 그렇게 말한다 — 지킬 수 없는 약속을 이름에 넣지 않는다.
 * 8초: 사람이 "안 눌렸나?" 하고 다시 누르는 구간을 덮으면서, 일부러 다시 내보내려는 사람을
 * 오래 막지 않는 길이다.
 */
const 이중클릭창ms = 8_000

/** 열쇠 → 잠근 시각(ms). */
const 잠긴것 = new Map()

/**
 * 같은 방송이 이미 나가고 있는지 보고, 아니면 잠근다.
 *
 * @param {string} 열쇠  같은 방송인지 가르는 표식(`방송열쇠()` 로 짓는다)
 * @param {number} 지금  현재 시각(ms). 시험이 시계를 주입한다
 * @returns {{ok: true, 풀기: () => void} | {ok: false, 지난ms: number}}
 */
function 겹침잠금(열쇠, 지금 = Date.now()) {
  const 언제 = 잠긴것.get(열쇠)
  if (언제 !== undefined && 지금 - 언제 < 최대잠금ms) {
    return { ok: false, 지난ms: 지금 - 언제 }
  }
  잠긴것.set(열쇠, 지금)
  let 풀렸나 = false
  return {
    ok: true,
    // **두 번 풀어도 안전해야 한다** — 성공 경로와 오류 경로가 둘 다 부를 수 있고,
    // 그 사이에 다른 요청이 같은 열쇠를 새로 잠갔을 수 있다(그것까지 풀면 안 된다).
    풀기() {
      if (풀렸나) return
      풀렸나 = true
      if (잠긴것.get(열쇠) === 지금) 잠긴것.delete(열쇠)
    },
  }
}

/**
 * 즉시 TTS 방송의 열쇠.
 *
 * **무엇이 같은 방송인가**를 정하는 자리다. 문구만 보면 안 된다 — 같은 문구라도 음량이나
 * 대상이 다르면 사람이 **다른 방송을 의도한 것**이다. 반대로 여기에 시각이나 난수를 섞으면
 * 열쇠가 매번 달라져 **아무것도 못 막는다.**
 */
function 방송열쇠({ text, target, voice, priority, volume, repeat }) {
  return [
    'tts',
    String(target ?? ''),
    String(voice ?? ''),
    priority ? '1' : '0',
    volume === null || volume === undefined ? '' : String(volume),
    repeat ? '1' : '0',
    String(text ?? '').trim(),
  ].join('|')
}

/** 예약 수동 재생의 열쇠 — 같은 예약을 두 번 누른 경우. */
function 예약열쇠(id) { return `schedule|${id}` }

/** 시험이 쓰는 자리. 제품 경로에서는 부르지 않는다. */
function 전부풀기() { 잠긴것.clear() }

module.exports = { 겹침잠금, 방송열쇠, 예약열쇠, 전부풀기, 최대잠금ms, 이중클릭창ms }
