'use strict'
// **차임 뒤에 안내를 낼 때까지의 대기 규칙** — 순수 함수(프로세스·장치를 모른다).
// `chimePlayer.js` 와 따로 두는 이유: 여러 시험이 chimePlayer 모듈을 통째로 가짜로 바꿔 끼운다.
// 대기 규칙까지 그 안에 있으면 가짜 모듈에는 이 함수가 없어 호출자가 죽는다.

// ── **차임이 실제로 울린 뒤에 다음 소리를 낸다** (사용자 신고 2026-09-17) ─────────────────────
// *"차임벨 울리고 가는게 아니라, 차임벨이랑 거의 TTS 랑 같이 나오는 버그"*
// 예전엔 차임 프로세스를 **띄운 순간**부터 고정 시간(즉시 방송 2.6초·흐름 3초)만 기다렸다. 느린 노트북에서
// 파이썬이 늦게 뜨면 차임 시작이 그만큼 밀려 안내와 겹쳤다. 이제 **시작 신호 + 여유** 까지 기다린다.
//   · 기본 대기(예전 값)보다 짧아지지는 않는다 — 빠른 PC 의 박자는 그대로다.
//   · 시작 신호를 못 주는 경로(스텁·맥·하드웨어 꺼짐)는 예전과 똑같이 기본 대기만 한다.
//   · 신호가 끝내 안 오면 상한 뒤 진행한다 — 차임 때문에 안내가 영영 안 나가면 안 된다.
const 차임시작후여유ms = 1800
const 차임시작기다림상한ms = 5000
function 차임시작표지() {
  let 시각 = null, 알림 = () => {}, 끝알림 = () => {}
  const 약속 = new Promise((r) => { 알림 = () => { if (시각 == null) { 시각 = Date.now(); r(시각) } } })
  // **차임 프로세스가 끝난 순간** — 시작 신호 없이 끝났으면(장치 열기 실패·프로세스 죽음) 더 기다릴 것이 없다.
  // 이것이 없을 때 안내 음성이 상한 5초를 통째로 더 기다렸다(2026-09-17 느림 분석).
  const 끝약속 = new Promise((r) => { 끝알림 = r })
  return { onStart: () => 알림(), 약속, 시각: () => 시각, 끝남: () => 끝알림(), 끝약속 }
}
/**
 * 차임을 띄운 시각 `t0` 기준으로, 안내를 내도 되는 순간까지 기다린다. `잠자기(ms)` 로 마지막 대기를 한다.
 * `취소됨()` 이 참이 되면 시작 신호 대기도 곧바로 끝낸다(2026-09-26 Codex 검수 Medium — 정지해도 최대 8초를 기다렸다).
 * 안 주면 예전과 같다.
 */
async function 차임뒤대기({ 신호옴, 표지, t0, 기본ms, 잠자기 = (ms) => new Promise((r) => setTimeout(r, ms)), 취소됨 = null }) {
  const 기본끝 = t0 + 기본ms
  if (신호옴 && 표지.시각() == null) {
    // 취소를 200ms 마다 본다(flowRunner.cancellableSleep 과 같은 간격).
    const 쉬기 = (ms) => new Promise((r) => {
      const 끝시각 = Date.now() + Math.max(0, ms)
      const 한번 = () => {
        const 남음 = 끝시각 - Date.now()
        if (남음 <= 0 || (취소됨 && 취소됨())) return r()
        setTimeout(한번, 취소됨 ? Math.min(200, 남음) : 남음)
      }
      한번()
    })
    let 끝났다 = false
    const 끝 = (표지.끝약속 || new Promise(() => {})).then(() => { 끝났다 = true })
    await Promise.race([표지.약속, 쉬기(기본끝 - Date.now())])
    if (표지.시각() == null && !끝났다) await Promise.race([표지.약속, 끝, 쉬기(차임시작기다림상한ms)])
  }
  const 시작 = 표지.시각()
  const 끝 = Math.max(기본끝, 시작 != null ? 시작 + 차임시작후여유ms : 0)
  return 잠자기(Math.max(0, 끝 - Date.now()))
}

module.exports = { 차임시작표지, 차임뒤대기, 차임시작후여유ms, 차임시작기다림상한ms }
