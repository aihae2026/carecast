// **Gemini 로 나가는 글에서 어르신 실명·번호를 뺀다** (사용자 승인 2026-09-15).
//
// ── 왜 있나 ────────────────────────────────────────────────────────────────
// 방송 민감정보 검사(`sensitiveInfo.checkSensitive`)가 도는 자리는 셋이고 전부
// **「스피커로 나가기 전 · 예약으로 저장되기 전」** 이다. **「바깥 모델로 보내기 전」은
// 하나도 없었다.** 그래서 *"오늘은 김○○ 어르신 생신입니다"* 같은 문안이 그대로 구글로
// 갔다 — 현장은 무료 티어라 약관상 그 입력이 모델 개선에 쓰이고 사람이 읽을 수 있다
// (`docs/submission/SUBMISSION.md` §4.5). **그런 문안이 실제로 이력에 있다.**
//
// ── 무엇을 하나 ────────────────────────────────────────────────────────────
// **막지 않고 바꿔서 보낸다.** 「이름이 있으면 AI 를 안 쓴다」로 막으면 생신 안내처럼
// 이름이 꼭 들어가는 방송은 AI 를 영영 못 쓴다.
//
//   보낼 때  「김철수 어르신 생신입니다」 → 「사람1 어르신 생신입니다」
//   돌아올 때 「사람1 어르신의 생신입니다」 → 「김철수 어르신의 생신입니다」
//
// **직원·어르신이 보는 것은 하나도 안 바뀐다. 바깥으로 안 나갈 뿐이다.**
//
// ── 번호는 되돌리지 않는다 ─────────────────────────────────────────────────
// 주민등록번호·휴대폰번호는 이 저장소가 이미 **차단** 으로 정한 값이다(`sensitiveInfo.js`
// 머리말 — *"방송할 이유가 없는 정보"*). 자리표를 주지 않고 그 자리에서 뺀다.
// **생년월일은 안 뺀다** — 날짜는 프롬프트 어디에나 있어서(「오늘 날짜: …」) 빼면
// 자연어 예약 파싱이 통째로 깨진다. 그 차단은 방송 경계에 그대로 남아 있다.
//
// ── 알면서 남겨 둔 구멍 둘 ─────────────────────────────────────────────────
// ① **`이름찾기` 가 못 찾는 이름은 여기서도 못 막는다.** 그 규칙은 「흔한 성씨 + 호칭」
//    이나 「맥락어 + 이름」일 때만 문다(헛경고를 줄이려고 일부러 좁게 잡은 것이다).
//    호칭 없이 이름만 적으면 그대로 나간다. **줄이는 것이지 없애는 것이 아니다.**
// ② (2026-11-01 막음 — 전문가 1차 검토 4-2) 예전엔 **전각·띄어 쓴 번호**(`０１０`, `0 1 0 - 1 2 3 4`)가
//    여기서 안 걸려 Gemini 로 나갔다. (2026-11-10 2차 검토 4-1) 번호 옆에 호실·시각 숫자가 붙으면 또
//    빠져나갔다. 이제 방송 경계와 같은 `sensitiveInfo.번호찾기` 가 **숫자 칸의 경계를 지키며** 번호를 찾고,
//    **원문의 그 부분**을 `[전화번호]`·`[주민등록번호]` 로 바꾼다.
//    가린 뒤에도 번호 모양이 남으면 `가리기` 가 `보류` 를 돌려주고, 부르는 쪽은 **보내지 않는다.**
'use strict'

const { 이름찾기, 번호찾기 } = require('./sensitiveInfo')

// 자리표는 **한국어 낱말 꼴**로 둔다. 기호(`[NAME_1]`)는 모델이 곧잘 지워 버리고,
// 영문 토큰은 한국어 문장 안에서 조사가 안 붙어 결과가 어색해진다.
const 자리표머리 = '사람'
const 자리표 = (n) => `${자리표머리}${n}`

// **남아 있으면 안 되는 모양.** 되돌린 뒤에도 이것이 보이면 모델이 자리표를 망가뜨린
// 것이다(번호를 바꾸거나 띄어 쓰거나). 그 글은 버린다 — 「사람1 어르신 생신입니다」가
// 스피커로 나가느니 AI 를 안 쓴 원문이 낫다.
const 남은자리표 = /사람\s*\d+/

// ── 번호 찾기: 방송 경계와 **같은 함수**(`sensitiveInfo.번호찾기`)를 쓴다 ──────────────────
// 따로 두면 한쪽만 고쳐져 두 경계의 판정이 갈린다(실제로 그랬다 — 2026-11-01 검수). 그 함수는
// 숫자 칸의 경계를 지키며 찾아서 「010-1234-5678 201호」처럼 번호 옆에 다른 숫자가 있어도 번호 자리만
// 돌려준다(전문가 2차 검토 4-1). 표지 순서는 `[a, b, k]` 의 k 와 같다.
const 번호표지 = ['[주민등록번호]', '[전화번호]']
const 표지번호 = { rrn: 0, phone: 1 }

// ── 보류 그물: 가리기 규칙과 **다른, 더 느슨한** 판정 ────────────────────────────────
// 가리기와 같은 판정으로 「남았나」를 보면, 그 규칙이 못 본 표기(가운뎃점·밑줄·빗금 등)는 보류에서도
// 못 본다 — 안전망이 아니다(2026-11-01 검수). 그래서 두 가지를 더 넓게 본다.
//   ① 숫자 칸 사이의 **숫자 아닌 글자 1~3개를 무엇이든** 다리로 쳐서 이은 구간
//   ② 구분자 없이 길게(10자리 이상) 붙은 숫자 칸은 **그 안 어디에** 번호 모양이 있어도
// 예전엔 ①의 덩어리 **전체**만 번호와 비교해서, 번호 옆에 호실 숫자가 붙으면 빠져나갔다(2차 검토 4-1).
// 이제 칸 구간 단위로 본다 — 칸 안을 자르지 않으니 날짜·시각 같은 것과는 안 겹친다.
// 다리 글자에서 **글자(한글·영문 등)는 뺀다** — 「2층 201, 202, 203, 204호」의 「층 」이 호실 숫자를
// 이어 번호 꼴이 되는 헛보류가 있었다(2026-11-01 재검수).
const 느슨한다리 = (사이) => /^[^\p{L}\d]{1,3}$/u.test(사이)
const 긴칸속번호 = /01[016789]\d{7,8}|\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])[1-4]\d{6}/
function 번호같은덩어리가있나(글) {
  const s = String(글 ?? '')
  if (번호찾기(s, 느슨한다리).length) return true
  const 반각글 = s.replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
  for (const m of 반각글.matchAll(/\d{10,}/g)) if (긴칸속번호.test(m[0])) return true
  return false
}

/** 원문에서 번호가 있는 자리 `[시작, 끝, 표지번호]` 들(겹치지 않는다). */
function 번호자리(글) {
  return 번호찾기(String(글 ?? '')).map(b => [b.start, b.end, 표지번호[b.type]])
}

/** 원문에서 번호 자리를 표지로 바꾼다. 뒤에서부터 바꿔야 앞 구간의 위치가 안 밀린다. */
function 번호가리기(글) {
  let out = String(글 ?? '')
  const 구간 = 번호자리(out)
  for (let n = 구간.length - 1; n >= 0; n--) {
    const [a, b, k] = 구간[n]
    out = out.slice(0, a) + 번호표지[k] + out.slice(b)
  }
  return out
}

/**
 * 글 하나에서 이름을 자리표로 바꾸고 번호를 뺀다.
 * @param {string} 글
 * @param {Map<string,string>} 표  자리표 → 원래 이름 (여러 글에 걸쳐 같은 표를 쓴다)
 * @returns {{글: string, 바뀜: boolean}}
 */
function 글가리기(글, 표) {
  let out = String(글 ?? '')
  const 처음 = out

  // 번호 먼저 가린다. 이름보다 먼저 해야 「010-1234-5678 김철수 어르신」 같은 글에서
  // 번호 자리가 이름 찾기를 방해하지 않는다. 전각·띄어 쓴 번호도 찾는다(위 `번호자리`).
  out = 번호가리기(out)

  for (const 이름 of 이름찾기(out)) {
    // 같은 이름이 여러 글에 나오면 **같은 자리표**를 쓴다 — 갈라 주면 모델이 두 사람으로
    // 읽는다.
    let 표지 = null
    for (const [k, v] of 표) if (v === 이름) { 표지 = k; break }
    if (!표지) { 표지 = 자리표(표.size + 1); 표.set(표지, 이름) }
    out = out.split(이름).join(표지)
  }

  return { 글: out, 바뀜: out !== 처음 }
}

/**
 * 요청 본문(문자열 JSON)의 **글자값만** 가린다. 속성 이름과 구조는 안 건드린다.
 *
 * **가릴 것이 없으면 원본 문자열을 그대로 돌려준다.** 다시 `JSON.stringify` 하면 칸
 * 순서·공백이 달라져서, 멀쩡한 요청의 모양이 조용히 바뀐다.
 *
 * 문자열 JSON 이 아니면(없음·GET·Buffer·비 JSON) **손대지 않는다** —
 * `/api/ai/models` 는 GET 이고 본문이 없다. 여기서 죽으면 모델 목록이 안 뜬다.
 */
function 가리기(body) {
  const 표 = new Map()
  if (typeof body !== 'string' || !body) return { 본문: body, 표 }

  let 뿌리
  try { 뿌리 = JSON.parse(body) } catch { return { 본문: body, 표 } }

  let 바뀜 = false
  let 보류 = false
  const 훑기 = (v, 깊이) => {
    if (깊이 > 20) return v
    if (typeof v === 'string') {
      const r = 글가리기(v, 표)
      if (r.바뀜) 바뀜 = true
      // **가린 뒤에도 번호 모양이 남으면 보내지 않는다**(전문가 1차 검토 4-2) — 가리기 규칙이 못 다룬
      // 표기가 있다는 뜻이다. 판정은 가리기와 **다른 느슨한 그물**(번호같은덩어리가있나)로 한다.
      // 칸마다 본다(JSON 전체로 보면 다른 칸의 숫자끼리 붙어 헛경보가 난다).
      if (번호같은덩어리가있나(r.글)) 보류 = true
      return r.글
    }
    if (Array.isArray(v)) return v.map(x => 훑기(x, 깊이 + 1))
    if (v && typeof v === 'object') {
      const out = {}
      // 속성 **이름은 그대로 둔다.** 이름을 바꾸면 받는 쪽이 못 읽는다.
      for (const [이름, x] of Object.entries(v)) out[이름] = 훑기(x, 깊이 + 1)
      return out
    }
    return v
  }
  const 가린것 = 훑기(뿌리, 0)

  if (!바뀜) return { 본문: body, 표, 보류 }
  // 부르는 쪽(geminiClient)이 `보류` 를 보고 요청 자체를 멈춘다.
  return { 본문: JSON.stringify(가린것), 표, 보류 }
}

/**
 * 돌아온 글의 자리표를 원래 이름으로 되돌린다.
 * @returns {{글: string, 실패: boolean}}  실패면 그 결과를 쓰면 안 된다.
 */
function 글되돌리기(글, 표) {
  let out = String(글 ?? '')
  // **긴 자리표부터 바꾼다.** `사람1` 을 먼저 바꾸면 `사람10` 의 앞 세 글자를 먹는다.
  const 표지들 = [...표.keys()].sort((a, b) => b.length - a.length)
  for (const 표지 of 표지들) out = out.split(표지).join(표.get(표지))
  return { 글: out, 실패: 남은자리표.test(out) }
}

/**
 * 응답 본문의 자리표를 되돌린 **새 응답**을 돌려준다.
 *
 * 가린 것이 없으면 원래 응답을 그대로 준다 — 가짜 응답을 쓰는 시험들이 있어서,
 * 읽을 수 없는 모양이면 손대지 않는다.
 *
 * @throws 자리표가 망가져 돌아왔을 때. 부르는 쪽 다섯이 전부 try/catch 안이라
 *         사람에게는 「AI 를 못 썼다」는 안내로 나가고 원문·규칙 결과가 쓰인다.
 */
async function 응답되돌리기(res, 표) {
  if (!표 || 표.size === 0) return res
  if (!res || typeof res.text !== 'function') return res

  const 글 = await res.text()
  const { 글: 되돌린, 실패 } = 글되돌리기(글, 표)
  if (실패) {
    throw new Error('AI 가 이름 자리표를 되돌릴 수 없게 바꿔 놨습니다. 그 결과는 쓰지 않았습니다.')
  }

  // 길이·압축 정보는 버린다 — 이미 푼 글이라 원래 값과 안 맞는다.
  const 머리 = new Headers(res.headers)
  머리.delete('content-length')
  머리.delete('content-encoding')
  return new Response(되돌린, { status: res.status, statusText: res.statusText, headers: 머리 })
}

module.exports = { 가리기, 응답되돌리기, 글가리기, 글되돌리기, 자리표, 남은자리표, 번호자리, 번호가리기, 번호같은덩어리가있나 }
