//
// **유령을 빼고 센다(2026-09-02, td09 §9의 미룬 갈래).** H15에서 배웠듯 프록시가 SSE
// close를 안 전달하면 죽은 창이 연결 목록에 남는다 — 그 유령을 "재생 창 있음"으로 세면
// 무음 방송이 성공으로 적히는 원래 구멍이 유령 경로로 되살아난다. localAliveCount는
// 생존 신호가 유효한 연결만 세고, **신호를 한 번도 못 받은 서버(옛 화면만)는 전원 생존
// 취급**이라(sse.살아있나) 예전 판정과 동일하게 떨어진다 — 멀쩡한 방송을 실패로 적는
// 쪽으로는 안 기운다.
//
// **부를 때 require 한다.** 테스트가 `require.cache` 로 sse 를 갈아끼우는 경로가 여럿이라,
// 로드 시점에 당기면 그 스텁을 못 본다.
'use strict'

function hasSitePlayer() {
  try { return require('./sse').localAliveCount() > 0 } catch { return true }
}

/**
 * **지금 소리를 낼 수 있는 창이 있는가** (현장 사고 2026-09-15).
 *
 * `hasSitePlayer()` 는 창이 **붙어 있나**만 답한다. 그런데 브라우저가 자동재생을 막으면
 * 창은 멀쩡히 붙어 있고 그림도 그리는데 **소리만 안 난다** — 오류도 안 난다.
 * 그날 07:50 아침 종합 방송이 그렇게 지나갔고 이력에는 **성공**으로 남았다.
 * 「무음인데 기록은 멀쩡」은 이 저장소가 가장 비싸게 데인 모양이다.
 *
 * 화면이 생존 신호에 실어 보낸 상태를 본다. **안 알려 준 창은 낼 수 있는 쪽으로 센다** —
 * 못 읽으면 true 를 내는 위 함수와 같은 결이다(자신 없을 때 멀쩡한 방송을 실패로
 * 적는 쪽이 더 나쁘다).
 */
function 소리낼수있나() {
  try { return require('./sse').소리낼수있는창수() > 0 } catch { return true }
}

/**
 * **창이 없던 것을 본 횟수** (V③ R8 지적, 2026-09-14).
 *
 * `hasSitePlayer()` 는 **그 순간**만 답한다. 방송이 도는 동안 창이 있었는지를 그것으로
 * 재면 **경계에서만 보게 되고**, 한 단계 안에서 닫혔다 돌아온 경우를 통째로 놓친다
 * (TTS 단계는 합성 대기 → 송출 → 종료 대기가 한 덩이다).
 *
 * 이 수는 **줄지 않는다.** 방송 시작과 끝의 값을 견주면 *"그동안 한 번이라도 0 이었나"* 가
 * 나온다 — 시각이 아니라 **사건**을 세므로 그 사이에 무슨 일이 있었는지 알 수 있다.
 * 못 읽으면 **0 으로 둔다** — 판정에 자신이 없을 때 멀쩡한 방송을 실패로 적는 쪽이 더 나쁘다
 * (`hasSitePlayer` 가 실패 시 true 를 내는 것과 같은 결).
 */
function 무창사건수() {
  try { return require('./sse').무창사건수() } catch { return 0 }
}

/**
 * **소리 담당이 바뀐 횟수** (V③ R10 지적, 2026-09-14).
 *
 * 창이 **둘** 있으면 소리를 내던 창이 닫혀도 `무창사건수` 는 안 오른다 — 남은 창이 있어
 * 「창 없음」이 아니기 때문이다. 그런데 **재생은 그 창에서 끊겼고**, 담당이 넘어가도
 * 진행 중인 소리는 안 이어받는다. 방송이 도는 동안 이 수가 달라졌다면 **그 방송은 끊겼다.**
 */
function 담당바뀜수() {
  try { return require('./sse').담당바뀜수() } catch { return 0 }
}

module.exports = { hasSitePlayer, 소리낼수있나, 무창사건수, 담당바뀜수 }
