// 보장되지는 않는다(탭이 여러 개면 leader 하나만 재생한다). 지금은 지배적 실패인 "창이
// 통째로 닫힘"만 잡는다. 조회가 실패하면 true로 둔다 — 판정에 자신이 없을 때 멀쩡한 방송을
