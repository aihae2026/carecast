// 머리줄 날짜 옆에 붙는 **작은 날씨 칩**의 값과 「언제 다시 받을지」를 정한다.
//
// ── 왜 반나절인가 (사용자 지시 2026-09-15) ─────────────────────────────────
// *"그냥 오전 오후 한번씩만 불러와서 그걸로 쓰면 되잖아"*
//
// 맞는 말이다. 이 칩이 말하는 것은 **오늘의 최고·최저·습도·자외선**이고, 그것들은
// 하루 사이에 거의 안 바뀐다. 30초마다 받아 봐야 같은 값을 다시 받는 것이고,
// 공공데이터 개발 계정은 **하루 1만 건** 한도가 있다.
//
// 그래서 하루를 **오전·오후 두 칸**으로 나누고, 한 칸에 **한 번만** 받는다.
// 그 칸에서 두 번째 요청부터는 먼저 받아 둔 값을 그대로 준다.
//
// ── 여기에 fetch 를 들이지 않는다 ──────────────────────────────────────────
// 이 파일은 **순수 함수만** 둔다(`domain/weatherCodes.js` 와 같은 규칙). 그래야
// 시계를 넣어 가며 시험할 수 있다. 실제로 받아오는 일은 라우트가 한다.
'use strict'

// 오전·오후를 가르는 시각. **12시다** — 최고기온이 대개 오후에 갱신되므로, 오후 칸을
// 12시에 열면 그날의 최고값이 들어간 뒤가 된다.
const 오후시작 = 12

function 두자리(n) { return String(n).padStart(2, '0') }

/**
 * 지금이 어느 칸인지. 칸이 바뀌면 다시 받는다.
 * @returns {string} 예: `2026-09-15/오전`
 */
function 반나절칸(지금 = new Date()) {
  const d = 지금 instanceof Date ? 지금 : new Date(지금)
  const 날 = `${d.getFullYear()}-${두자리(d.getMonth() + 1)}-${두자리(d.getDate())}`
  return `${날}/${d.getHours() < 오후시작 ? '오전' : '오후'}`
}

/**
 * 날씨 묶음(`services/weather.fetchWeather`)에서 칩이 쓸 것만 뽑는다.
 *
 * **없는 값은 지어내지 않고 `null` 로 둔다.** 화면은 null 인 칸을 아예 안 그린다 —
 * 「-」나 「0」으로 채우면 사람이 그것을 값으로 읽는다.
 */
function 칩만들기(묶음, 지금 = new Date()) {
  if (!묶음 || typeof 묶음 !== 'object') return null

  const 숫자 = (v) => (typeof v === 'number' && Number.isFinite(v) ? Math.round(v) : null)

  const 칩 = {
    최고:   숫자(묶음.maxTemp),
    최저:   숫자(묶음.minTemp),
    지금기온: 숫자(묶음.temperature),
    습도:   숫자(묶음.humidity),
    // 자외선은 **말이 숫자보다 쓸모 있다** — 「3」보다 「낮음」이 바로 읽힌다.
    // 둘 다 실어 보내고 화면이 고른다.
    자외선:     묶음.uv?.level ?? null,
    자외선수치: 숫자(묶음.uv?.value),
    하늘:   묶음.sky ?? null,
    잰때:   묶음.fetchedAt ?? null,
    칸:     반나절칸(지금),
  }

  // ── Open-Meteo 값이 칩에 보이나 (사용자 지시 2026-10-07) ─────────────────────────
  // Open-Meteo(CC BY 4.0)는 「데이터를 보여 주는 자리 옆에」 출처 링크를 요구한다. 칩이 **실제로 그리는 칸**의
  // 출처만 본다 — `dataSources.minmax` 는 값이 없어도 기본 'open-meteo' 라서, 칸이 비었으면 세지 않는다.
  칩.오픈메테오 = ((칩.최고 !== null || 칩.최저 !== null) && 묶음.dataSources?.minmax === 'open-meteo')
    || (칩.습도 !== null && 묶음.humiditySource === 'open-meteo')

  // **하나도 없으면 칩 자체를 안 만든다.** 빈 껍데기를 주면 화면이 빈 칸을 그린다.
  const 값들 = [칩.최고, 칩.최저, 칩.지금기온, 칩.습도, 칩.자외선]
  if (값들.every(v => v === null)) return null
  return 칩
}

/**
 * 받아 둔 칩을 그대로 써도 되는가.
 * 같은 반나절 칸이면 쓴다 — 그것이 「오전 오후 한 번씩」의 전부다.
 */
function 아직쓸만한가(받아둔것, 지금 = new Date()) {
  return !!받아둔것 && 받아둔것.칸 === 반나절칸(지금)
}

module.exports = { 반나절칸, 칩만들기, 아직쓸만한가, 오후시작 }
