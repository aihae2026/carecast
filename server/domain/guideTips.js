// 첫 화면이 **말을 거는 규칙** — 매뉴얼에서 읽고, 상황을 보고, 한 줄을 고른다.
//
// ── 무엇을 푸는가 (사용자 지시 2026-09-15) ─────────────────────────────────────
// *"기능 메뉴얼 논리 구조와 문구 규칙이 연결 파싱 되어서 **AI 개입 없어도** 자동으로
//   기능 안내 등등이 나갈 수 있도록."*
//
// 지금 첫 화면에는 「무엇을 방송할까요?」 **한 문장이 고정**으로 박혀 있다. 그래서
// 이 시스템이 무엇을 할 수 있는지는 **매뉴얼을 열어야만** 안다 — 요양원 직원이 매뉴얼을
// 열 이유가 없다. 쓸 줄 아는 기능만 쓰고 나머지는 없는 것이 된다.
//
// ── 왜 AI 를 안 쓰나 ────────────────────────────────────────────────────────
// 셋 다 이 저장소의 기존 규칙이다.
//  · **돈과 인터넷이 든다.** 첫 화면은 하루 종일 떠 있는 화면이라 그 비용이 상시로 붙는다.
//  · **인터넷이 끊기면 말을 못 하게 된다.** 그때야말로 안내가 필요한 순간이다.
//  · **AI 가 지은 문장은 확인을 거쳐야 나간다**(CLAUDE.md 검토 게이트). 화면에 뜨는 글도
//    사람이 못 본 문장이면 같은 문제다 — 매뉴얼에 있는 말만 쓰면 그 문제가 아예 없다.
//
// ── 단일 출처는 **매뉴얼**이다 ──────────────────────────────────────────────
// 기능 이름을 여기 따로 적지 않는다. `docs/MANUAL-USER.md` 의 **제목 구조**를 읽는다 —
//   · `### 2-N. …`  → **사람이 하는 일**(지금 방송·예약·마이크·차임·배경음악)
//   · `## 6` 표      → **증상 → 조치**
// 매뉴얼을 고치면 안내도 따라 바뀐다. 따로 적으면 언젠가 갈리고, 갈린 쪽이 화면이다.
'use strict'

// 주격 조사(이/가)는 **이미 있는 것을 쓴다** — `weatherCodes.subjectParticle`.
// 여기 다시 적으면 같은 규칙이 두 벌이 되고, 한쪽만 고치는 날 한쪽 화면만 틀린 말을 한다.
// (처음에 조사를 `이` 로 박아 뒀더니 *"국민체조**이** 안 나갔습니다"* 가 나왔다.)
const { subjectParticle: 조사 } = require('./weatherCodes')

// ── 문구 규칙 ────────────────────────────────────────────────────────────────
//
// 이 화면을 보는 사람은 요양보호사·사회복지사다. `feedback_carecast_plain_language` 의
// 규칙 그대로 **항상 존댓말**이고 **개발 용어를 안 쓴다.**
//
// ── **해요체로, 짧게** (사용자 지적 2026-09-15) ──────────────────────────────────
// 첫 판은 *"지금 바로 안내하기, 여기서 하실 수 있습니다."*(26자) 였다.
// 사용자 지적: *"말 걸듯이인데 너무 기능설명에 가까운 거 아니야? 문장 호흡도 길어지면
// 불편해."* — 맞다. 그건 **설명문**이지 말을 거는 것이 아니고, 한 줄로도 길다.
//
// 그래서 둘을 바꿨다:
//  · **합니다체 → 해요체.** 둘 다 존댓말인데 해요체가 **짧고 부드럽다**
//    (「나갑니다」 4자 → 「나가요」 3자). 말 거는 쪽은 이쪽이다.
//  · **상한을 40 → 28자로 내렸다.** 상한이 느슨하면 문장이 거기까지 자란다 —
//    실제로 28자짜리가 나왔다. 짧게 쓰라고 강제하는 것이 이 숫자의 일이다.
const 최대글자 = 28
// 화면에 뜨면 안 되는 말. 매뉴얼이 이미 안 쓰지만, 안내를 손으로 더할 때를 대비해 둔다.
const 금지낱말 = ['API', 'SSE', 'DB', '엔드포인트', '파싱', '캐시', '토큰', '쿼리', '로그인']

/**
 * 존댓말로 끝나는가. 물음표·느낌표는 붙어도 된다.
 *
 * **해요체를 함께 받는다**(`나가요`·`돼요`·`어때요`). 합니다체만 받으면 말이 딱딱해지고
 * 길어진다 — 이 줄은 **말을 거는 자리**라 해요체가 맞다. 반말은 여전히 안 받는다.
 */
function 존댓말인가(t) {
  // **어미를 일일이 나열하지 않는다.** 처음엔 `어요|아요|예요|…` 로 적었는데
  // *"저녁 방송이 **나가요**"* 가 걸러졌다 — 「가요」가 목록에 없었다.
  // 한국어 해요체는 **「요」로 끝난다**는 것 하나면 된다. 나열은 언젠가 빠뜨린다.
  return /(니다|십시오|요)[.?!]?$/.test(String(t || '').trim())
}

/** 화면에 내도 되는 문장인가. 규칙을 어기면 **그 줄을 안 쓴다**(고장난 안내보다 없는 편이 낫다). */
function 쓸수있나(t) {
  const s = String(t || '').trim()
  if (!s || s.length > 최대글자) return false
  if (!존댓말인가(s)) return false
  if (금지낱말.some(w => s.includes(w))) return false
  // 줄바꿈이 들어오면 한 줄이 아니다.
  return !/[\r\n]/.test(s)
}

// ── 매뉴얼 읽기 ──────────────────────────────────────────────────────────────

/**
 * 매뉴얼에서 **사람이 하는 일**을 뽑는다 — `### 2-N. 제목` 이 그 목록이다.
 *
 * 제목에서 군더더기를 걷는다: `2-3. 급할 때 — 마이크로 말하기` → `마이크로 말하기`.
 * 대시 뒤를 쓰는 이유는 앞이 **상황**이고 뒤가 **하는 일**이라서다.
 */
function 기능읽기(마크다운) {
  const 줄들 = String(마크다운 || '').split(/\r?\n/)
  const out = []
  for (const l of 줄들) {
    const m = /^###\s+(\d+)-(\d+)\.\s+(.+?)\s*$/.exec(l)
    if (!m || m[1] !== '2') continue          // 「2. 자주 하는 일」 아래만 본다
    let 제목 = m[3].replace(/\*\*/g, '').trim()
    const 대시 = 제목.split(/\s+—\s+/)
    if (대시.length > 1) 제목 = 대시[대시.length - 1].trim()
    if (제목) out.push({ 번호: `${m[1]}-${m[2]}`, 제목 })
  }
  return out
}

/**
 * 「이럴 때는 이렇게」 표를 뽑는다 — `| 증상 | 조치 |`.
 *
 * 지금은 **화면에 직접 쓰지 않는다.** 조치 문장이 길고 굵은 글씨·주소가 섞여 있어
 * 한 줄 안내로는 안 맞는다. 그래도 읽어 두는 이유는 **매뉴얼에 그 표가 살아 있는지**를
 * 시험이 확인하기 위해서다 — 표가 사라지면 §6 을 가리키는 안내도 거짓이 된다.
 */
function 해결읽기(마크다운) {
  const out = []
  let 표안 = false
  for (const l of String(마크다운 || '').split(/\r?\n/)) {
    if (/^##\s+6\./.test(l)) { 표안 = true; continue }
    if (표안 && /^##\s/.test(l)) break
    if (!표안 || !l.trim().startsWith('|')) continue
    const 칸 = l.split('|').map(c => c.trim()).filter((_, i, a) => i > 0 && i < a.length - 1)
    if (칸.length < 2 || /^-+$/.test(칸[0]) || 칸[0] === '이런 일이') continue
    out.push({ 증상: 칸[0].replace(/\*\*/g, ''), 조치: 칸[1].replace(/\*\*/g, '') })
  }
  return out
}

// ── 상황 → 한 줄 ─────────────────────────────────────────────────────────────
//
// **급한 것이 먼저다.** 기능 안내는 할 일이 없을 때만 한다 — 안 나간 방송이 있는데
// *"차임만 울릴 수도 있어요"* 라고 말하면 그건 잔소리다.

/** 지금부터 `안에분` 안에 나갈 것 하나. 없으면 null. */
function 곧나갈것(오늘, 지금분, 안에분 = 30) {
  let 골라진 = null
  for (const i of 오늘 || []) {
    if (!i || i.status !== 'pending' || !i.time) continue
    const [h, m] = String(i.time).split(':').map(Number)
    if (!Number.isFinite(h) || !Number.isFinite(m)) continue
    const 남음 = h * 60 + m - 지금분
    if (남음 < 0 || 남음 > 안에분) continue
    if (!골라진 || 남음 < 골라진.남음) 골라진 = { 항목: i, 남음 }
  }
  return 골라진
}

/**
 * 지금 화면에 띄울 한 줄을 고른다. **AI 를 안 쓴다 — 표와 조건뿐이다.**
 *
 * @param {object[]} 기능들  `기능읽기` 결과
 * @param {object[]} 오늘    `/api/schedules/today` 의 items
 * @param {Date}     지금
 * @param {number}   회전    기능 안내를 돌리는 번호(같은 문장만 계속 뜨지 않게)
 * @returns {{text:string, kind:string}|null} 규칙을 어기는 문장은 **안 내보낸다**
 */
function 한줄고르기({ 기능들 = [], 오늘 = [], 지금 = new Date(), 회전 = 0 } = {}) {
  const 지금분 = 지금.getHours() * 60 + 지금.getMinutes()

  // ── **안 나간 방송은 이 자리에서 말하지 않는다** (사용자 결정 2026-09-15) ──────────
  //
  // 처음엔 이 자리의 첫째 갈래가 「국민체조가 안 나갔어요.」였다. 급한 것이 먼저라는
  // 생각이었는데, 실제로 띄워 놓고 보니 **그 말이 오래 떠 있었다.** 아침에 하나 놓친 날은
  // 하루 종일 같은 문장이고, 그러면 안내가 아니라 **꾸지람**이 된다.
  //
  // 사용자 결정: *"안 나갔다라는 내용이 오래 떠있으니까 부정적인 느낌이 들어. 그냥
  // 부정적인 것들은 빼버리자, 어차피 상태로 확인 가능하니까."* — 맞다. 안 나간 방송은
  // **오늘 일과방송 목록의 「안 나감」**이 이미 보여 주고, 그쪽이 원래 그 사실을 보는
  // 자리다(경보 배너도 따로 있다). 같은 말을 큰 제목이 하루 종일 되풀이할 이유가 없다.
  //
  // **정보가 사라지는 것이 아니다** — 보는 자리를 하나로 모은 것이다.
  // **찾는 함수도 같이 지웠다** — 안 쓰는 코드를 「나중에 쓸지도」로 남기면
  // 다음 사람이 그게 살아 있는 규칙인 줄 안다.

  // ① 곧 나갈 방송 — 알아 두면 좋은 것. 5분 안이면 분까지, 아니면 시각으로 말한다.
  const 곧 = 곧나갈것(오늘, 지금분)
  if (곧?.항목?.label) {
    const 이름 = 곧.항목.label
    const t = 곧.남음 <= 5
      ? `곧 ${이름}${조사(이름)} 나가요.`
      : `${곧.항목.time}에 ${이름}${조사(이름)} 나가요.`
    if (쓸수있나(t)) return { text: t, kind: 'soon' }
  }

  // ② **할 일이 없으면 안심시킨다** (사용자 지시 2026-09-15).
  //
  // *"지금의 「무엇을 방송할까요」는 아 뭔가 친근하고 따뜻하다. 검색창에서는 아 이런
  //   정보도 입력해볼 수 있네? 이렇게."* — 두 자리의 일이 갈렸다:
  //   · **이 줄**은 따뜻한 쪽이다. 지금 어떤지 알려 주고 안심시킨다.
  //   · **「이런 것도 되는구나」는 검색창 예시가 맡는다**(`QuickSchedulePhrase` 의 EXAMPLES).
  //
  // 그래서 기능 나열을 이 자리의 **맨 뒤로** 미뤘다. 오늘 목록이 있으면 그 얘기를 하고,
  // 아무것도 모를 때만 기능을 든다.
  const 끝난것 = (오늘 || []).filter(i => i?.status === 'done').length
  const 남은것 = (오늘 || []).filter(i => i?.status === 'pending').length
  if (끝난것 > 0) {
    // 「다 나갔다」와 「여기까지 나갔다」를 가른다 — 남은 게 있는데 「다」라고 하면 거짓이다.
    const t = 남은것 === 0
      ? '오늘 방송, 다 잘 나갔어요.'
      : `지금까지 ${끝난것}건 잘 나갔어요.`
    if (쓸수있나(t)) return { text: t, kind: 'calm' }
  }

  // ③ 오늘 것을 아직 모를 때만 **기능을 하나씩** 든다. 매뉴얼 §2 의 차례 그대로 돈다.
  //
  // **이 갈래만 회전이 뜻이 있다.** 위 둘(①②)은 지금 상태가 정하므로 회전과 무관하다 —
  // 안 나간 방송이 있으면 12초 뒤에도 그 얘기다. 그래서 화면은 **회전 때문에 서버를
  // 다시 부를 필요가 없다**(`기능문구들` 로 목록을 한 번에 받아 그 자리에서 돌린다).
  if (기능들.length) {
    const f = 기능들[((회전 % 기능들.length) + 기능들.length) % 기능들.length]
    // 매뉴얼 제목은 *"…하기"* 꼴이라 **틀이 그 꼴에 맞아야** 말이 된다.
    //
    // 두 번 고쳤다. *"…도 할 수 있습니다"* → *"…, 여기서 하실 수 있습니다."* →
    // 지금은 **`…도 돼요.`** 다. 앞의 둘은 **설명문**이었고 길었다(26~28자).
    // *"차임만 울리기도 돼요."*(12자) 는 **곁에서 알려 주는 말**에 가깝다 —
    // 「…해도 된다」는 허락이 아니라 **권유**로 읽힌다.
    const t = `${f.제목}도 돼요.`
    if (쓸수있나(t)) return { text: t, kind: 'feature', 번호: f.번호 }
  }
  return null
}

/**
 * 기능 안내 문구를 **한꺼번에** 만든다. 화면이 회전할 때마다 서버를 부르지 않게 하려는 것.
 *
 * ── 왜 필요했나 (2026-09-15, 내가 낸 결함) ──────────────────────────────────
 * 처음엔 화면이 **회전 번호를 서버에 보내** 한 줄씩 받아 왔다. 그런데 회전이 12초마다
 * 도는 바람에 **12초마다 서버를 두 번씩**(오늘 목록 + 안내) 불렀다 — 분당 10회다.
 * 게다가 그 효과가 회전에 매여 있어서 **60초 폴링은 한 번도 안 돌았다**(12 < 60 이라
 * 매번 지워졌다). 상수만 60초라고 적혀 있고 실제로는 12초였던 것이다.
 *
 * 상태로 정해지는 문구(①②③)는 **회전과 무관**하다. 회전이 뜻을 갖는 것은 기능 안내뿐이라,
 * 그 목록만 통째로 주면 **화면이 제자리에서 돌릴 수 있다.**
 */
function 기능문구들(기능들 = []) {
  return 기능들
    .map(f => ({ text: `${f.제목}도 돼요.`, kind: 'feature', 번호: f.번호 }))
    .filter(x => 쓸수있나(x.text))
}

// ── 차례표 — 무엇이 얼마나 자주, 얼마나 오래 (사용자 지시 2026-09-15) ──────────────
//
// *"「무엇을 방송할까요?」 빈도수가 조금 많게 해주고 나머지는 적절한 시간과 분배에 따라
//   나오게 규칙 짜줘."*
//
// 그전까지 「무엇을 방송할까요?」는 **큰 제목에 고정**이고 안내는 그 아래 작은 줄이었다.
// 사용자 결정(2026-09-15)으로 **둘을 큰 제목 하나로 합쳤다** — 그러면 이 문구도 도는
// 것들 중 하나가 되므로, 얼마나 자주 돌아오는지를 정해야 한다.
//
// ── 규칙 셋 ─────────────────────────────────────────────────────────────────
//
// **① 안 나간 방송은 안 돈다.** 12초 뒤에도 그 방송은 여전히 안 나간 채다. 그 자리에서
//    「무엇을 방송할까요?」로 넘어가면 방금 본 경고가 없던 일이 된다.
//
// **② 한 칸 걸러 닻이다.** `[닻, 곁말, 닻, 곁말, …]` — 「무엇을 방송할까요?」가 **차례의
//    절반**을 갖는다. 이게 "조금 많게"의 뜻이다. 곁말을 연달아 두면 화면이 계속 새로운
//    말을 하는 것처럼 보여 오히려 시끄럽다. 닻으로 돌아올 때마다 **한 박자 쉰다.**
//
// **③ 곁말 차례는 급한 순이다.** 곧 나갈 방송 → 안심 → 인사 → 기능 안내.
//    앞의 둘은 `한줄고르기` 가 이미 정하므로 **여기서 다시 정하지 않는다** — 규칙이 두
//    벌이면 큰 제목과 오늘 목록이 언젠가 다른 말을 한다.
const 닻문구 = '무엇을 방송할까요?'
// ── 머무는 시간 — **초가 아니라 분이다** (사용자 지적 2026-09-15) ────────────────
// *"자주 바뀌니까 정신없어, 한 10분마다 바뀌면 좋을 것 같긴 해."*
//
// 처음엔 12초 : 9초였다. **읽는 속도로만 정한 값**이라 틀렸다 — 이 제목은 한 번 읽고
// 마는 글이 아니라 **하루 종일 떠 있는 화면의 얼굴**이다. 눈길이 안 가 있는 동안에도
// 계속 바뀌니, 고개를 들 때마다 다른 말이 있어서 산만했다.
//
// 그래서 **분 단위로 옮겼다.** 닻이 더 오래 머무는 비율(4:3)은 그대로 둔다 —
// 화면에 떠 있는 시간의 약 57% 가 닻이고, 한 번 바뀌는 데 평균 10.5분이다.
//
// **3분으로 줄였다** (사용자 지시 2026-09-17 *"3분마다 바뀌는 건 어때?"*). 10분이면 하루에 본 사람이 거의
// 안 바뀌는 줄 안다. 곁말은 3분, 닻은 앞선 결정(「닻이 조금 더 오래」)을 지켜 4분 — 비율 4:3 은 그대로다.
const 닻머무는초 = 4 * 60
const 곁말머무는초 = 3 * 60

/**
 * 시간대 인사. **오늘 목록이 비어 있어도 따뜻한 말이 돌게** 하는 자리다.
 * 새로 깐 PC 나 예약이 하나도 없는 날엔 ①②③ 이 전부 비는데, 그때 기능 안내만 돌면
 * 이 화면이 설명서가 된다.
 */
function 인사(지금) {
  const h = 지금.getHours()
  if (h >= 5  && h < 9)  return '오늘도 좋은 아침이에요.'
  if (h >= 9  && h < 12) return '오전 잘 보내고 계신가요?'
  if (h >= 12 && h < 14) return '점심시간이에요.'
  if (h >= 14 && h < 18) return '오후도 편안하게 보내세요.'
  if (h >= 18 && h < 22) return '오늘 하루도 수고하셨어요.'
  return '늦게까지 고생 많으세요.'
}

/**
 * 요일이 주는 말. **시계만 보고 지을 수 있는 것**이라 오늘 목록이 비어도 나온다.
 * 없으면 null — 화·수·목은 특별히 할 말이 없다. 억지로 채우면 그게 군더더기다.
 */
function 요일말(지금) {
  const d = 지금.getDay()
  if (d === 1) return '한 주가 시작됐어요.'
  if (d === 5) return '한 주 마무리하는 날이에요.'
  if (d === 0 || d === 6) return '주말이에요. 푹 쉬세요.'
  return null
}

/**
 * 오늘 목록이 말해 주는 것들. **여러 개를 한꺼번에** 돌려준다 — 하나만 고르면
 * 차례가 금방 바닥난다(사용자 지적: *"몇 가지밖에 없는데?"*).
 *
 * **세지 못하는 것은 말하지 않는다.** 남은 것이 0인데 「곧 나가요」라고 하거나,
 * 끝난 것이 없는데 「잘 나갔어요」라고 하면 그건 지어낸 말이다.
 */
function 오늘말들(오늘 = [], 지금 = new Date()) {
  const 목록 = 오늘 || []
  const 끝난것 = 목록.filter(i => i?.status === 'done').length
  const 남은것 = 목록.filter(i => i?.status === 'pending').length
  const out = []

  if (!목록.length) {
    // 예약이 하나도 없는 날. **새로 깐 PC 에서도 여기로 온다.**
    out.push({ text: '오늘은 잡힌 방송이 없어요.', kind: 'calm' })
    return out
  }
  if (끝난것 > 0 && 남은것 === 0) out.push({ text: '오늘 방송, 다 잘 나갔어요.', kind: 'calm' })
  if (끝난것 > 0 && 남은것 > 0)   out.push({ text: `지금까지 ${끝난것}건 잘 나갔어요.`, kind: 'calm' })
  if (남은것 > 0)                 out.push({ text: `오늘 ${남은것}건 더 남았어요.`, kind: 'calm' })
  if (끝난것 === 0 && 남은것 > 0 && 지금.getHours() < 12) {
    out.push({ text: '오늘 방송은 이제 시작이에요.', kind: 'calm' })
  }
  return out
}

/**
 * 큰 제목이 돌 차례를 짠다.
 *
 * @returns {{붙잡는말: object|null, 차례: object[]}}
 *   · `붙잡는말` 이 있으면 **그것만 띄우고 안 돈다**(안 나간 방송).
 *   · 없으면 `차례` 를 순서대로 돌린다. 각 칸에 `머무는초` 가 붙어 있다.
 */
function 차례짜기({ 기능들 = [], 오늘 = [], 지금 = new Date() } = {}) {
  const 닻 = { text: 닻문구, kind: 'anchor', 머무는초: 닻머무는초 }

  // ① 상태가 정하는 한 줄은 `한줄고르기` 한 곳에서 나온다. **기능은 빼고 부른다** —
  //    기능 안내는 아래에서 목록째로 붙이므로, 여기서 한 줄을 더 받으면 두 번 나온다.
  const 상태 = 한줄고르기({ 기능들: [], 오늘, 지금 })

  // **`붙잡는말` 은 이제 늘 비어 있다** (사용자 결정 2026-09-15).
  // 붙잡던 것은 「안 나갔어요」 하나였는데 그 문구를 뺐다 — 오래 떠 있으면 꾸지람이 되고,
  // 안 나간 사실은 오늘 일과방송 목록이 이미 보여 준다.
  // **자리는 남겨 둔다.** 나중에 정말 붙잡아야 할 말(예: 지금 방송 중)이 생기면 여기다.

  // ② 곁말 — **여러 갈래를 다 붙인다** (사용자 지적 2026-09-15:
  //    *"몇 가지밖에 없는데? 더 기능별, 상황별로 대폭 늘릴 수 없나?"*).
  //
  //    앞 판은 상태 한 줄 + 인사 한 줄 + 기능 다섯이라 **일곱이 전부**였다. 10분씩 머물게
  //    바꾸고 나니 그 일곱으로는 한 바퀴가 너무 빨리 돈다.
  //    지금은 **곧 나갈 방송 + 오늘 상태 여럿 + 요일 + 인사 + 기능 열넷**이다.
  //
  //    차례는 **급한 순**이다: 곧 나갈 방송 → 오늘 상태 → 요일 → 인사 → 기능 안내.
  //    지금 알아야 할 것이 앞이고, 알아 두면 좋은 것이 뒤다.
  const 곁말 = []
  if (상태?.kind === 'soon') 곁말.push(상태)      // 곧 나갈 방송 — 가장 앞
  곁말.push(...오늘말들(오늘, 지금))
  const 요일 = 요일말(지금)
  if (요일) 곁말.push({ text: 요일, kind: 'greet' })
  곁말.push({ text: 인사(지금), kind: 'greet' })
  곁말.push(...기능문구들(기능들))

  // **같은 말을 두 번 넣지 않는다.** `한줄고르기` 의 안심 문구와 `오늘말들` 이 같은 문장을
  // 낼 수 있다 — 한 바퀴에 같은 말이 두 번 나오면 차례가 고장 난 것처럼 보인다.
  {
    const 본것 = new Set()
    for (let i = 곁말.length - 1; i >= 0; i--) {
      if (본것.has(곁말[i]?.text)) 곁말.splice(i, 1)
      else 본것.add(곁말[i]?.text)
    }
  }

  const 쓸것 = 곁말.filter(x => 쓸수있나(x?.text))
  if (!쓸것.length) return { 붙잡는말: null, 차례: [닻] }

  // ③ 한 칸 걸러 닻.
  const 차례 = []
  for (const x of 쓸것) {
    차례.push(닻)
    차례.push({ text: x.text, kind: x.kind, 머무는초: 곁말머무는초 })
  }
  return { 붙잡는말: null, 차례 }
}

module.exports = {
  기능읽기, 해결읽기, 한줄고르기, 기능문구들, 차례짜기, 인사, 요일말, 오늘말들,
  쓸수있나, 존댓말인가, 최대글자, 금지낱말, 닻문구, 닻머무는초, 곁말머무는초,
}
