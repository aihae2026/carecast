'use strict'
// **방송 화면 글자 크기 — 고를 수 있는 값의 단일 출처** (사용자 지시 2026-09-16).
//
// *"그 방송화면에 자막 크기 설정할 수 있게 끔 하게 해줘, 설정에서 크게, 중간, 작게"*
//
// 여기는 **이름(id)** 만 정한다. 각 이름이 몇 배인지는 화면이 정한다
// (`src/lib/broadcastTextSize.js`) — 서버는 크기를 그리지 않기 때문이다.
// 두 목록이 갈리면 저장은 되는데 화면이 모르는 값이 생긴다 —
// `server/test/broadcast-text-size.test.js` 가 둘을 대조한다.
//
// **기본은 「크게」다.** 2026-09-15 에 사용자가 방송 글자를 1.5 배로 키워 달라고 했고
// 지금 화면이 그 크기다. 이 설정을 넣는다고 이미 쓰던 화면이 작아지면 안 된다.

const 크기들 = ['large', 'medium', 'small']
const 기본 = 'large'
const 설정키 = 'broadcast_text_size'

/** 모르는 값·빈 값은 기본(크게)으로 읽는다 — 읽는 쪽은 절대 던지지 않는다. */
function 정리(v) {
  return 크기들.includes(v) ? v : 기본
}

module.exports = { 크기들, 기본, 설정키, 정리 }
