'use strict'
// 올린 파일의 **보이는 이름**을 정하는 단일 출처 (UX-29).
//
// 왜 필요했나: 같은 이름을 두 번 올려도 아무 검사가 없었다. 디스크 파일명은
// 타임스탬프+랜덤이라 부딪히지 않지만, **사람이 보는 이름이 똑같아진다.**
// 그러면 목록에서 어느 것이 어느 것인지 알 방법이 없고, 녹음 음원 자리처럼 카테고리로
// 고르는 단계에서는 "먼저 올린 것만 나가는" 상태가 된다(그 자리에 `make-primary` 를
// 따로 만든 이유가 그것이다).
//
// **막지 않고 이름을 바꿔 준다.** 올리는 것을 거절하면 사람이 파일을 다시 만들어야 하고,
// 현장에서 그건 그냥 포기로 이어진다. 드라이브·탐색기가 하는 방식(`(2)`)을 따른다.

/** `가을 아침.mp3` → `{ 몸통: '가을 아침', 확장자: '.mp3' }` (확장자가 없으면 빈 문자열) */
function 이름가르기(name) {
  const s = String(name || '')
  const i = s.lastIndexOf('.')
  // 앞에 아무것도 없는 `.env` 같은 이름은 통째로 몸통이다 — 확장자로 보면 이름이 사라진다.
  if (i <= 0) return { 몸통: s, 확장자: '' }
  return { 몸통: s.slice(0, i), 확장자: s.slice(i) }
}

/** 이미 `이름 (2).mp3` 꼴이면 그 번호를 떼어 낸다 — 안 그러면 `이름 (2) (2).mp3` 가 된다. */
function 번호떼기(몸통) {
  const m = /^(.*?)\s*\((\d+)\)$/.exec(몸통)
  return m ? m[1] : 몸통
}

/**
 * 같은 자리에 이미 있는 이름들과 부딪히지 않는 이름을 만든다.
 *
 * @param {string} 원래이름  사람이 올린 그대로의 이름
 * @param {Iterable<string>} 쓰는이름들  같은 카테고리·폴더에 이미 있는 `original_name` 들
 * @returns {{이름: string, 바뀜: boolean}} 안 부딪히면 원래 이름 그대로(`바뀜: false`)
 */
function 안겹치는이름(원래이름, 쓰는이름들) {
  const 있음 = new Set()
  for (const n of 쓰는이름들 || []) 있음.add(String(n))
  if (!있음.has(원래이름)) return { 이름: 원래이름, 바뀜: false }

  const { 몸통, 확장자 } = 이름가르기(원래이름)
  const 밑동 = 번호떼기(몸통)
  // 2부터 올린다 — 원본이 (1) 이 아니라 이름 그대로이기 때문이다.
  for (let n = 2; n < 10000; n++) {
    const 후보 = `${밑동} (${n})${확장자}`
    if (!있음.has(후보)) return { 이름: 후보, 바뀜: true }
  }
  // 만 개가 같은 이름인 경우 — 실제로는 안 오지만 **조용히 부딪히게 두지 않는다.**
  return { 이름: `${밑동} (${Date.now()})${확장자}`, 바뀜: true }
}

// 디스크가 꽉 찼을 때의 안내. **원문을 그대로 내보내지 않는다** —
// `ENOSPC: no space left on device, write` 는 현장 직원에게 아무 뜻이 없다.
// 무엇이 문제이고 다음에 뭘 하면 되는지로 바꾼다(UX-10 의 연동 오류 규약과 같은 규칙).
const 저장공간코드 = new Set(['ENOSPC', 'EDQUOT', 'EFBIG'])
function 업로드오류문구(err) {
  const code = err && (err.code || err.errno)
  if (저장공간코드.has(code)) {
    return '방송 PC 의 저장 공간이 부족해 파일을 저장하지 못했습니다. '
      + '음원 및 동영상 관리에서 쓰지 않는 파일을 지운 뒤 다시 올려 주세요.'
  }
  if (code === 'EACCES' || code === 'EPERM') {
    return '저장 폴더에 쓸 권한이 없어 파일을 저장하지 못했습니다. 관리자에게 알려 주세요.'
  }
  return null   // 모르는 것은 지어내지 않는다 — 부르는 쪽이 원문을 쓴다
}

module.exports = { 안겹치는이름, 이름가르기, 번호떼기, 업로드오류문구 }
