'use strict'
// **받아쓰기가 알아야 할 낱말 — 단일 출처** (사용자 신고 2026-09-16).
//
// ── 무엇이 잘못됐나 ────────────────────────────────────────────────────────
// 녹음 문안 속 낱말을 받아쓰기가 더 흔한 비슷한 소리의 낱말로 틀리게 적었고(예: 드문 고유 낱말이
// 흔한 낱말로 바뀌거나, 아예 영문자 두 글자로 잡힘), AI 다듬기도 그것을 못 고쳤다.
//
// 두 자리가 **똑같이** 어휘를 모르고 있었다:
//
//   · `scripts/caption_stt.py` — `model.transcribe(...)` 에 **`initial_prompt` 가 없었다.**
//     whisper 는 그저 한국어 음성으로 듣는다. 무슨 방송인지 모르니 드문 낱말은 흔한 쪽으로 간다.
//   · `routes/audio.js` 의 `POLISH_PROMPT` — 「고유 어휘와 높임말이 많다」고 **말만 하고
//     낱말을 하나도 안 줬다.** 고칠 근거가 없으니 AI 도 틀린 낱말을 그냥 둔다.
//
// ── 왜 한 곳인가 ──────────────────────────────────────────────────────────
// 두 자리에 각각 적으면 갈린다. 받아쓰기가 아는 낱말과 다듬기가 아는 낱말이 다르면,
// **받아쓰기가 새로 틀리는 낱말을 다듬기가 못 고친다.** 이 저장소가 「같은 것이 두 벌」로
// 여러 번 데인 자리다(볼륨 이름 3개, 배포 게이트 시각 7곳).
//
// ── 두 쓰임새의 모양이 다르다 ──────────────────────────────────────────────
// whisper 의 `initial_prompt` 는 **앞말**이다 — 목록이 아니라 그 앞에 오는 자연스러운
// 문장이어야 하고, 길면 잘린다(대략 224 토큰). 그래서 `앞말()` 은 문장으로 낸다.
// AI 다듬기는 **대조표**가 있어야 판단하므로 `낱말들` 을 그대로 준다.
//
// ── 기관마다 다른 어휘는 설정 파일로 (2026-10-17) ──────────────────────────
// 시설 고유 낱말은 시설마다(종교·전례·지역) 다르다. 한 시설의 종교 어휘를 코드에 박아 두면 그 시설이
// 드러나고 다른 시설에는 맞지도 않는다. 그래서 **코드에는 어느 요양원에나 나오는 낱말만** 두고,
// 시설 고유 어휘는 저장소 밖 설정 파일에서 더한다:
//
//   server/config/stt-vocabulary.local.json   (git 에 안 올라간다 — `.gitignore`)
//   또는 환경변수 CARECAST_STT_VOCAB_FILE 이 가리키는 파일
//
//   { "설명": "요양원의 안내 방송입니다.",             ← 앞말의 첫 문장(선택)
//     "낱말들": ["…", "…"],                          ← 더할 낱말
//     "자주틀리는짝": [["틀린 쪽", "맞는 쪽"]] }       ← 실제로 틀렸던 짝
//
// 모양은 `server/config/stt-vocabulary.example.json` 에 있다. 파일이 없거나 깨졌으면 기본 낱말만
// 쓴다 — 받아쓰기는 앞말이 없어도 돌아가므로, 설정 실수로 자막 만들기를 멈추지 않는다.
const fs = require('node:fs')
const path = require('node:path')

// 어느 요양원 방송에나 나오는 낱말 — **실제로 쓰는 것만 적는다.** 짐작으로 늘리지 않는다.
// 기본 방송 문안이 종교 중립이 되면서(2026-10-17) 시설 고유 낱말도 기본에서 뺐다 — 「기도·묵상 시간(선택)」 단계를 켠
// 종교 시설은 그 낱말을 설정 파일에 더한다(아래 예시 파일 참고).
const 기본낱말 = [
  '식사 안내', '아침 방송', '마음 안정', '문안인사',
  '어르신', '국민체조', '투약', '환기', '식당', '프로그램', '요양보호사',
]
const 기본설명 = '요양원의 안내 방송입니다.'

const 기본파일 = path.join(__dirname, '..', 'config', 'stt-vocabulary.local.json')

/** 설정 파일을 읽는다. 없거나 깨졌으면 null — 기본 낱말만 쓴다. */
function 설정읽기(파일 = process.env.CARECAST_STT_VOCAB_FILE || 기본파일) {
  let raw
  try { raw = fs.readFileSync(파일, 'utf8') } catch { return null }   // 없음 — 정상 경로
  try {
    const j = JSON.parse(raw.charCodeAt(0) === 0xFEFF ? raw.slice(1) : raw)   // 메모장이 붙인 BOM 을 뗀다
    return j && typeof j === 'object' ? j : null
  } catch (e) {
    console.warn(`[받아쓰기 어휘] ${파일} 을 읽지 못했습니다(기본 낱말만 씁니다): ${e.message}`)
    return null
  }
}

/** 기본 낱말에 설정을 합친다. 순수 함수 — 시험이 파일 없이 부른다. */
function 합치기(설정) {
  const 글자만 = (xs) => (Array.isArray(xs) ? xs : []).filter((x) => typeof x === 'string' && x.trim()).map((x) => x.trim())
  const 낱말들 = [...new Set([...기본낱말, ...글자만(설정?.낱말들)])]
  const 자주틀리는짝 = (Array.isArray(설정?.자주틀리는짝) ? 설정.자주틀리는짝 : [])
    .filter((p) => Array.isArray(p) && p.length === 2 && p.every((x) => typeof x === 'string' && x.trim()))
    .map(([틀린, 맞는]) => [틀린.trim(), 맞는.trim()])
  const 설명 = typeof 설정?.설명 === 'string' && 설정.설명.trim() ? 설정.설명.trim() : 기본설명
  return { 낱말들, 자주틀리는짝, 설명 }
}

const 지금 = 합치기(설정읽기())

/**
 * whisper 의 `initial_prompt` 로 줄 앞말.
 *
 * 목록이 아니라 **문장**이다 — `initial_prompt` 는 "이 음성 앞에 이런 말이 있었다"로
 * 쓰이므로, 낱말을 쉼표로 늘어놓기만 해도 되지만 문장이 자연스러울수록 잘 끌린다.
 * **틀린 낱말은 절대 안 넣는다** — 넣으면 그쪽으로 끌려간다.
 */
function 앞말(어휘 = 지금) {
  const 틀린것 = new Set(어휘.자주틀리는짝.map(([틀린]) => 틀린))
  const 낱말 = 어휘.낱말들.filter((x) => !틀린것.has(x))
  return `${어휘.설명} ${낱말.join(', ')} 같은 말이 나옵니다.`
}

/**
 * AI 다듬기 프롬프트에 붙일 어휘 안내.
 * 낱말 목록과 「이렇게 틀린다」 짝을 함께 준다. 짝이 없으면 그 줄은 뺀다.
 */
function 다듬기안내(어휘 = 지금) {
  const 줄 = [`자주 나오는 낱말: ${어휘.낱말들.join(', ')}`]
  if (어휘.자주틀리는짝.length) {
    const 짝 = 어휘.자주틀리는짝.map(([틀린, 맞는]) => `"${틀린}" → "${맞는}"`).join(', ')
    줄.push(`받아쓰기가 이렇게 틀린 적이 있다: ${짝}. 같은 갈래의 잘못도 같이 고친다.`)
  }
  return 줄.join('\n')
}

module.exports = {
  낱말들: 지금.낱말들, 자주틀리는짝: 지금.자주틀리는짝,
  기본낱말, 합치기, 설정읽기, 앞말, 다듬기안내,
}
