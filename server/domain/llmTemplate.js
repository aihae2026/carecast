// 3차 폴백 — LLM 이 하나도 안 될 때 쓰는 규칙 템플릿.
//
// 언제 도나: 로컬 모델도 없고 외부 API 도 안 되는 날. **가장 나쁜 날에만** 돈다.
// 그래서 여기서 하는 일은 최소한이어야 하고, 무엇보다 **지어내지 않아야** 한다.
//
// 왜 "지어내지 않는다"가 핵심인가: 이 결과는 요양원에서 어르신께 나가는 방송문이 된다.
// LLM 이 없다고 그럴듯한 문장을 만들어 내면, 사람이 안 쓴 사실(시각·이유·대상)이
// 방송으로 나갈 수 있다. 그건 도움이 아니라 사고다.
// 그래서 **틀은 고정하고 내용은 입력에서만** 가져온다.
//
// 말투는 현장 문안을 따른다 — `favorites` 의 빠른 방송 문구가
// "어르신 여러분, … 바랍니다." 모양이다(2026-09-06 현장 사본 확인).
// 낯선 말투가 튀면 그 방송만 이상하게 들린다.
'use strict'

/** 이 결과가 템플릿에서 나왔음을 화면·로그가 표시할 때 쓰는 말. */
const TEMPLATE_MARK = '템플릿'

// 방송 하나가 이보다 길 이유가 없다. 넘으면 자른다 — TTS 가 몇 분을 읽는다.
const MAX_BODY = 200

function 정리(s) {
  return String(s ?? '')
    .replace(/\s+/g, ' ')      // 줄바꿈·연속 공백 → 한 칸 (TTS 가 이상하게 끊어 읽는다)
    .trim()
}

/**
 * 상황 한 줄을 방송문 초안으로 만든다.
 *
 * 하는 일은 셋뿐이다: 다듬고, 자르고, 정해진 틀에 끼운다.
 * **입력에 없는 것은 아무것도 더하지 않는다.**
 *
 * @param {string} 상황  사람이 쓴 상황 한 줄 ("점심 배식 안내")
 * @returns {string} 방송문 초안. 빈 입력이어도 **빈 문자열을 돌려주지 않는다** —
 *                   사람이 무엇을 채워야 하는지 보이는 초안을 준다.
 */
function buildAnnouncement(상황) {
  let 본문 = 정리(상황)
  if (본문.length > MAX_BODY) 본문 = `${본문.slice(0, MAX_BODY)}…`

  if (!본문) {
    return '어르신 여러분, 안내 말씀드립니다. (내용을 입력해 주세요) 감사합니다.'
  }
  // 끝에 마침표가 없으면 붙인다. 있으면 두 번 찍지 않는다.
  const 끝 = /[.!?。]$/.test(본문) ? '' : '.'
  return `어르신 여러분, 안내 말씀드립니다. ${본문}${끝} 감사합니다.`
}

module.exports = { buildAnnouncement, TEMPLATE_MARK, MAX_BODY }
