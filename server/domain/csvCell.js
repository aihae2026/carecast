// CSV 한 칸을 만든다 — 엑셀이 **수식으로 읽지 않게**(전문가 1차 검토 1-4).
//
// 큰따옴표로 감싸는 것은 쉼표·줄바꿈만 지킨다. 엑셀은 따옴표 안이라도 `=`·`+`·`-`·`@` 로
// 시작하는 칸을 수식으로 읽는다. 방송 문안·담당자 칸에 `=HYPERLINK(...)` 같은 글이 들어가면
// 이력 파일을 연 직원의 PC 에서 링크나 계산이 된다.
//
// 그래서 **글자 칸**이 그런 문자로 시작하면 앞에 작은따옴표(')를 붙인다 — 엑셀은 이것을
// "글자로 보라"는 표시로 쓰고 화면에는 안 보인다. 앞 공백·탭·제어문자 뒤에 숨긴 경우도
// 같이 본다(엑셀이 앞 공백을 걷고 수식으로 읽는다).
//
// **진짜 숫자(number)는 그대로 둔다** — 「준비(초)」 같은 칸은 엑셀에서 숫자로 더할 수 있어야 한다.
'use strict'

// 앞 공백·제어문자(코드 0x20 이하)를 건너뛴 첫 글자를 본다. 탭·줄바꿈으로 시작하는 칸도 막는다.
function 위험한가(s) {
  let i = 0
  while (i < s.length && s.charCodeAt(i) <= 0x20) i++
  return '=+-@'.includes(s[i] ?? 'x') || /^[\t\r\n]/.test(s)
}

function csvCell(v) {
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : '""'
  let s = String(v ?? '')
  if (위험한가(s)) s = `'${s}`
  return `"${s.replace(/"/g, '""')}"`
}

module.exports = { csvCell }
