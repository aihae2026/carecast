// 합성 직전 **읽기 다듬기** — 기호·단위를 한국어 말로 바꾼다 (사용자 청취 2026-09-21).
//
// *"23.5 로보씨? 이렇게 들리고 미세먼지는 32 미러ㅔㄹ뤠 이렇게 들리는데? 23.5도 … 라고 읽어야지"*
// 기본 엔진(Supertonic 3)은 ℃·㎍/㎥ 같은 기호를 말로 풀지 못한다. 방송 문안을 짓는 코드(morning.js)는
// 이미 「도」「마이크로그램」으로 적지만, 직원이 즉시 방송 칸에 직접 쓰는 글은 기호가 섞인다.
//
// **소리에만 쓴다.** 자막·기록·캐시 열쇠는 원문 그대로다(열쇠는 엔진 소금의 「읽기@판」 으로 갈린다).
// 규칙을 바꾸면 READING_REV 를 올린다 — 합성 결과가 바뀌므로 옛 소리가 캐시에서 밀려나야 한다.
// 단어를 건드리지 않도록 **숫자 바로 뒤의 단위**만 바꾼다(「mm」가 들어간 영어 낱말 등을 지키려고).
'use strict'

const READING_REV = 2   // 2: %p·°C 뒤 영문·헥토파스칼 조사 (Codex ④-d 3회차)

const 숫자 = String.raw`(\d+(?:[.,]\d+)?)`
const 규칙 = [
  // 온도
  // 뒤에 영문 글자가 붙은 표기(「90°CCW」「10°Celsius」)는 건드리지 않는다 — 부분만 바뀌면 표기가 망가진다.
  [new RegExp(`${숫자}\\s*(?:℃|°\\s*C|°)(?![A-Za-z])`, 'g'), '$1도'],
  // 미세먼지 농도(마이크로그램 퍼 세제곱미터) — 방송 문안의 말투(「… 마이크로그램」)에 맞춘다
  [new RegExp(`${숫자}\\s*(?:㎍\\s*/\\s*㎥|[µμu]g\\s*/\\s*m(?:3|³))`, 'g'), '$1마이크로그램'],
  [new RegExp(`${숫자}\\s*㎍`, 'g'), '$1마이크로그램'],
  [new RegExp(`${숫자}\\s*㎛`, 'g'), '$1마이크로미터'],
  // 비·거리·바람·기압·비율
  [new RegExp(`${숫자}\\s*(?:㎜|mm)(?![a-z])`, 'gi'), '$1밀리미터'],
  [new RegExp(`${숫자}\\s*(?:㎞|km)(?![a-z])`, 'gi'), '$1킬로미터'],
  [new RegExp(`${숫자}\\s*(?:㎧|m\\s*/\\s*s)(?![a-z])`, 'gi'), '$1미터'],
  [new RegExp(`${숫자}\\s*hPa(?![a-z])`, 'g'), '$1헥토파스칼'],
  // 「5%p」(퍼센트포인트)를 먼저 — 「%」 만 바꾸면 「5퍼센트p」 가 된다.
  [new RegExp(`${숫자}\\s*%\\s*p(?![A-Za-z])`, 'g'), '$1퍼센트포인트'],
  [new RegExp(`${숫자}\\s*%(?![A-Za-z])`, 'g'), '$1퍼센트'],
  // 범위 「10~20」 → 「10에서 20」
  [new RegExp(`${숫자}\\s*[~∼〜]\\s*(?=\\d)`, 'g'), '$1에서 '],
  // 받침으로 끝나는 단위 말 뒤 조사를 맞춘다 — 「35㎍/㎥로」 가 「35마이크로그램로」, 「1013hPa가」 가
  // 「1013헥토파스칼가」 가 되지 않게. 「마이크로그램」(ㅁ 받침)은 로→으로, 「헥토파스칼」(ㄹ 받침)은 로 그대로.
  // (다른 단위 말은 모음으로 끝나 기호 뒤의 조사가 그대로 맞다.)
  [/(마이크로그램|헥토파스칼)(로|가|는|를|와)(?![가-힣])/g,
    (_, 말, 조사) => 말 + ({ 로: 말.endsWith('칼') ? '로' : '으로', 가: '이', 는: '은', 를: '을', 와: '과' }[조사])],
  [/마이크로그램로(?=[가-힣])/g, '마이크로그램으로'],
]

/** 합성 엔진에 넘기기 직전의 문장. 원문을 바꾸지 않는다(새 문자열을 돌려준다). */
function 읽기다듬기(text) {
  let s = String(text ?? '')
  for (const [re, 새] of 규칙) s = s.replace(re, 새)
  return s
}

module.exports = { 읽기다듬기, READING_REV }
