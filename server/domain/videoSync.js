'use strict'
// **TV 싱크 보정 — 단일 출처** (사용자 지시 2026-09-16).
//
// ── 무엇을 바꿨나 ──────────────────────────────────────────────────────────
// *"이거 영상 하나로 통일해줘, 어차피 동일하게 TV에서 수신받아서 약간씩 늦는거잖아"*
//
// 그전에는 보정값이 **둘**이었다 — 국민체조 영상(`video_audio_delay_exercise_ms`)과
// 식사전 체조 영상(`video_audio_delay_meal_ms`). 갈래를 고르려고 `delayProfile`(A/B)
// 이라는 개념이 서버 → 화면 → 재생기로 흘렀고, 그 사슬이 끊겨 조용히 틀린 값이 걸린
// 사고가 두 번 있었다(V③ R18·R23, 2026-09-14).
//
// **그런데 두 값은 같은 것을 재고 있었다.** 지연은 「어느 영상이냐」가 아니라
// **「PC 오디오 → 방송설비」와 「캡처카드 → TV 채널」의 경로 차이**에서 온다. 그 경로는
// 영상이 무엇이든 같다. 실제로 현장 값도 둘 다 400 이었다(2026-09-16 사본 확인).
// 그래서 **값 하나**로 줄이고, 갈래 개념을 걷었다. 고를 것이 없으면 틀리게 고를 수도 없다.
//
// ── 자막은 왜 따로인가 ────────────────────────────────────────────────────
// *"자막도 속도도 물려서 자막은 조금 늦어, 그래서 조금 빠르게 설정할 수 있도록"*
//
// 자막은 지금까지 소리 보정을 **그대로** 따라갔다(`VideoPlayer` 의 `자막붙이기(v, delayMs)`).
// 소리를 늦추면 자막도 같이 늦는데, **사람 눈은 귀보다 자막을 먼저 찾는다** — 그래서
// 소리에 맞춘 자막은 늦게 느껴진다. 이제 **그 위에 더하는 오프셋**을 따로 둔다.
//
//   자막이 뜨는 시각 = 영상 보정 + 자막 오프셋
//
// 오프셋은 **음수가 된다**(자막을 먼저 띄운다). 영상 보정은 0 밑으로 못 가지만
// (소리를 미리 낼 수는 없다) 자막은 당길 수 있다 — 그래서 읽는 규칙이 둘로 갈린다.
//
// ── 배포 기본값은 0 이다 ──────────────────────────────────────────────────
// *"설치 배포할때는 그냥 기본값, 모니터에서 나오는 그대로 0 설정해놓고"*
//
// 앞 판 기본값은 450 이었다. 그것은 **처음 운영한 시설의 캡처카드·TV 조합에서 잰 값**이지
// 어느 시설에나 맞는 값이 아니다. 새로 설치한 PC 는 대개 TV 로 안 보내고 **모니터로
// 그냥 본다** — 거기서 450 은 소리가 근거 없이 0.45초 늦는다는 뜻이다.
// 그래서 **0 에서 시작하고, 필요한 시설이 올린다.**
// 이미 값이 있는 PC 는 안 건드린다(`config/siteBaseline.js` 와 같은 규칙).

/** 하나뿐인 영상 보정 설정 키. */
const 딜레이키 = 'video_audio_delay_ms'

/** 자막을 얼마나 당기거나 미룰지(ms). 음수면 자막이 먼저 뜬다. */
const 자막오프셋키 = 'caption_offset_ms'

/** 배포 기본값 — 0. 이유는 머리말 「배포 기본값은 0 이다」. */
const 딜레이기본 = 0
const 자막오프셋기본 = 0

/** 영상 보정 범위 — 소리를 **미리** 낼 수는 없으므로 0 밑으로 안 간다. */
const 딜레이최소 = 0
const 딜레이최대 = 2000

/** 자막 오프셋 범위 — **음수가 된다.** 자막을 당기는 것이 이 값의 존재 이유다. */
const 자막최소 = -2000
const 자막최대 = 2000

/**
 * 보낸 값이 **진짜 숫자인가.** 아니면 왜 아닌지 한 문장으로.
 *
 * 옛 검사는 `isNaN(Number(delayMs))` 였다. 그런데 **`Number(null)` 도 `Number('')` 도
 * `Number('   ')` 도 전부 0 이다.** 그래서 빈 값이 검사를 통과해 **현장에서 맞춰 둔
 * 보정을 0 으로 덮어썼다** — 200 을 돌려주므로 화면은 "저장됐다"고 말하고, 그 뒤로
 * 소리와 자막이 어긋난다. 오류가 안 난다(V③ R19 지적 4, 2026-09-14).
 *
 * **명시적인 숫자 0 은 그대로 받는다** — 보정을 끄는 것은 정당한 조작이다.
 * 막는 것은 «값을 안 준 것»이지 «0 을 준 것»이 아니다.
 *
 * @returns {{ok:true, 값:number}|{ok:false, 사유:string}}
 */
function 숫자읽기(값, { 최소, 최대, 이름 = 'delayMs' }) {
  if (값 === undefined || 값 === null) return { ok: false, 사유: `${이름} 값이 필요합니다.` }
  if (typeof 값 === 'string' && 값.trim() === '') {
    return { ok: false, 사유: `${이름} 가 비어 있습니다. 끄려면 0 을 보내 주세요.` }
  }
  if (typeof 값 === 'boolean') return { ok: false, 사유: `${이름} 는 숫자여야 합니다.` }
  const n = Number(값)
  if (!Number.isFinite(n)) return { ok: false, 사유: `${이름} 는 숫자여야 합니다.` }
  return { ok: true, 값: Math.max(최소, Math.min(최대, Math.round(n))) }
}

/** 영상 보정값 읽기 — 0~2000. */
const 보정값읽기 = (v) => 숫자읽기(v, { 최소: 딜레이최소, 최대: 딜레이최대, 이름: 'delayMs' })

/** 자막 오프셋 읽기 — **-2000~2000**(음수 허용). */
const 자막오프셋읽기 = (v) => 숫자읽기(v, { 최소: 자막최소, 최대: 자막최대, 이름: 'offsetMs' })

module.exports = {
  딜레이키, 자막오프셋키,
  딜레이기본, 자막오프셋기본,
  딜레이최소, 딜레이최대, 자막최소, 자막최대,
  보정값읽기, 자막오프셋읽기,
}
