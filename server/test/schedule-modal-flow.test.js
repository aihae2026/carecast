// **「대상」을 걷고, 흐름을 그 자리에서 고르고 보게 한다** (사용자 지시 2026-09-15).
//
// ── ① 「대상」은 소리를 안 가른다 ────────────────────────────────────────────
// *"대상이 나오는데 대상은 없어, 필요없는 기능이야."* — 재 보니 맞다.
// `['전체','1층','2층','3층']` 은 **모달 파일에만** 있던 목록이고, 재생 경로 어디도
// 그 값을 안 읽었다(SSE·오디오 큐·오디오 백엔드·화면 재생 훅 전부 0건).
// 고를 수 있는데 아무 일도 안 일어나는 칸은 **「골랐으니 거기로 나가겠지」** 라고 믿게
// 만든다. 이 저장소가 가장 경계하는 조용한 오독이다.
//
// **값 자체는 안 없앴다** — `form.target` 은 기본값 「전체」로 그대로 흐르고, 이력
// (`broadcasts.target`)과 겹침 판정 열쇠는 예전 그대로다. 지운 것은 **고르는 칸**이다.
//
// ── ② 흐름은 고른 자리에서 보인다 ──────────────────────────────────────────
// *"사용할 흐름 넣어놓고 선택하면 밑에 방송 플로우가 보였으면."*
// 그전에는 고르고 나서 무엇이 나가는지 보려면 **자동순서 화면까지 다녀와야** 했다.
'use strict'

const test   = require('node:test')
const assert = require('node:assert/strict')
const fs     = require('node:fs')
const path   = require('node:path')

const ROOT = path.join(__dirname, '..', '..')
const 읽기 = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8')
const 모달 = 읽기('src/components/shared/ScheduleModal.jsx')
const 코드만 = 모달.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')

test('긍정 앵커 — 이 모달이 흐름 유형을 다룬다', () => {
  assert.match(코드만, /const isFlow\s*=/, '흐름 판정이 없다 — 이 시험의 전제다')
  assert.match(코드만, /<FlowPicker\s/, '흐름 고르개를 안 쓴다')
})

test('**「대상」 고르는 칸이 없다** — 고를 수 있는데 아무 일도 안 일어나면 안 된다', () => {
  assert.doesNotMatch(코드만, /TARGET_OPTIONS/,
    '층 목록이 아직 있다 — 소리는 층별로 안 갈린다')
  assert.doesNotMatch(코드만, /'1층'|"1층"/, '층 값이 아직 화면에 있다')
  // 「대상」이라는 **라벨**도 없어야 한다 — 값만 지우고 글자를 남기면 더 헷갈린다.
  assert.doesNotMatch(코드만, />\s*대상\s*</, '「대상」 라벨이 아직 있다')
})

test('**값은 그대로 흐른다** — 칸만 지웠지 값을 없앤 것이 아니다', () => {
  // `form.target` 이 사라지면 이력의 `target` 칸과 겹침 열쇠가 조용히 바뀐다.
  const 유틸 = 읽기('src/lib/scheduleUtils.js')
  assert.match(유틸, /target:/, '기본값에서 target 이 사라졌다 — 이력·겹침 판정이 바뀐다')
})

test('**흐름을 고르면 단계가 그 자리에 보인다**', () => {
  assert.match(코드만, /getFlow\(/,
    '고른 흐름의 단계를 안 받아 온다 — 목록에는 이름과 개수뿐이다')
  // 단계 종류를 **사람 말로** 바꾼다. 모르는 것은 그 이름 그대로 — 지어내지 않는다.
  assert.match(코드만, /단계라벨/, '단계 종류를 사람 말로 바꾸는 자리가 없다')
  for (const t of ['tts', 'chime', 'audio', 'bgm']) {
    assert.ok(코드만.includes(`${t}:`) || 코드만.includes(`'${t}'`),
      `단계 종류 「${t}」 의 이름이 없다`)
  }
})

test('**미리보기가 고르기를 막지 않는다** — 못 받아도 고를 수 있어야 한다', () => {
  // 곁가지(미리보기)가 본 일(고르기)을 막으면 안 된다. 실패해도 빈 목록으로 끝낸다.
  assert.match(코드만, /\.catch\(\(\)\s*=>/, '단계 받기 실패를 안 흡수한다')
})

test('**「새 순서 만들기」가 눈에 띈다** — 흐름이 없을 때 유일한 길이다', () => {
  const i = 코드만.indexOf('새 순서 만들기')
  assert.ok(i > 0, '「새 순서 만들기」 단추가 없다')
  const 조각 = 코드만.slice(Math.max(0, i - 500), i)
  // 앞 판은 밑줄 없는 작은 글씨였다. 테두리·바탕이 있어야 단추로 읽힌다.
  assert.match(조각, /border/, '테두리가 없다 — 글씨로만 보인다')
  assert.match(조각, /bg-/, '바탕이 없다 — 글씨로만 보인다')
  // G-15 — 손으로 누르는 것은 충분히 커야 한다.
  assert.match(조각, /min-h-\[\d\d/, '높이를 안 정했다 — 손가락이 닿는 크기가 아니다')
})
