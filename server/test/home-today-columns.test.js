// 오늘 일과방송 — **열 정렬과 꼬리표** (사용자 지시 2026-09-14).
//
// ── 무엇이 문제였나 (PC 사진) ────────────────────────────────────────────────
// ① 「자동」·「안내방송」 꼬리표가 이름 칸을 갉아먹었다.
// ② 차수 단추(1차·2차)가 **상태 칸 안**에 있어서 그 줄만 「완료」가 왼쪽으로 밀렸다 —
//    상태 글자의 x 좌표가 줄마다 달랐다(실측 1001·930·986·942).
// ③ 지나간 줄이 다른 줄과 구별되지 않았다.
//
// ── 고친 방향 ────────────────────────────────────────────────────────────────
// · 꼬리표는 **안 그린다**(표시만 빠진다 — 유형·예약 데이터는 그대로).
// · 수동 조작은 **한 칸에 모은다** — ▶ 와 차수 단추는 하는 일이 같다.
// · 상태·수동 칸을 **고정 폭**으로 둔다. `auto` 면 내용에 따라 칸이 흔들려 정렬이 깨진다.
// · 지나간 줄은 **바탕만** 눕힌다 — 글자 투명도를 낮추면 읽기가 어려워진다.
//   **시간이 지났다고 「완료」로 바꾸지 않는다**(안 나간 방송이 나간 것으로 읽힌다).
'use strict'

const test   = require('node:test')
const assert = require('node:assert/strict')
const fs     = require('node:fs')
const path   = require('node:path')

const ROOT = path.join(__dirname, '..', '..')
const SRC  = fs.readFileSync(path.join(ROOT, 'src/components/home/HomeToday.jsx'), 'utf8')
const 코드 = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

test('유형 꼬리표를 안 그린다 — 규칙 모듈은 살아 있다', () => {
  assert.doesNotMatch(코드, /tagOfRow\(/, '아직 꼬리표를 만든다')
  assert.doesNotMatch(코드, /KIND_CLASS\[/, '아직 꼬리표 색을 칠한다')
  // 규칙 자체는 지우지 않는다 — 초안 카드가 계속 쓴다
  const 규칙 = fs.readFileSync(path.join(ROOT, 'src/lib/broadcastKind.js'), 'utf8')
  assert.match(규칙, /tagOfRow/, '규칙 모듈까지 지웠다 — 초안 카드가 그것을 쓴다')
})

test('상태·수동 칸이 **고정 폭**이다 — auto 면 줄마다 정렬이 달라진다', () => {
  const m = 코드.match(/tablet:grid-cols-\[([^\]]+)\]/g) || []
  assert.ok(m.length >= 2, `격자 정의를 ${m.length}개만 찾았다 — 머리글과 줄 둘 다 있어야 한다`)
  for (const g of m) {
    assert.doesNotMatch(g, /_auto_auto\]/,
      `상태·수동이 auto 다 — 차수 단추가 있는 줄만 칸이 넓어져 상태가 밀린다: ${g}`)
    assert.match(g, /_\d+px_\d+px\]/, `상태·수동 폭이 안 정해졌다: ${g}`)
  }
  // 머리글과 줄의 격자가 **같아야** 이름표와 칸이 맞는다
  const 폭 = m.map(g => (g.match(/\[(.+)\]/) || [])[1])
  assert.equal(new Set(폭).size, 1, `머리글과 줄의 격자가 다르다: ${JSON.stringify(폭)}`)
})

test('차수 단추가 **수동 칸 안**에 있다 — 상태 칸을 안 밀어낸다', () => {
  const i = 코드.indexOf('_isGroup && r._items.map')
  assert.ok(i > 0, '차수 단추를 그리는 자리를 못 찾았다')
  // 그 앞의 여는 span 이 **제 칸**이어야 한다.
  //
  // 2026-09-15: 앞 판은 `col-start-3` 을 **글자로** 박았다. 좁은 화면 격자가 세 칸에서
  // 두 칸으로 바뀌면서(시각을 윗줄로 올렸다) 그 번호가 3→2 가 됐고, **지키려던 사실은
  // 그대로인데** 빨간불이 났다. 열 번호는 배치를 고칠 때마다 바뀌는 값이다.
  // **사실은 「제 칸에 있고, 두 줄에 걸쳐, 오른쪽에 붙는다」** — 그것만 본다.
  const 앞 = 코드.slice(Math.max(0, i - 700), i)
  assert.match(앞, /col-start-\d/, '차수 단추가 격자 칸을 안 지정한다 — 상태 칸 안으로 흘러든다')
  assert.match(앞, /row-span-2/, '차수 단추 칸이 두 줄에 안 걸친다 — 이름이 접히면 단추가 어긋난다')
  assert.match(앞, /justify-end/, '차수 단추가 오른쪽에 안 붙는다 — 줄마다 자리가 달라진다')
})

// ── 2026-09-14: 「지나간 줄 회색 바탕」이 **철회됐다**(사용자 지시) ──────────────
// *"이전에 요청한 '지나간 행에 진한 회색 배경'은 철회한다. 기본 행은 페이지 배경이
//   비치는 투명한 느낌으로 복원한다."*
// 그래서 이 자리의 시험도 뜻이 뒤집힌다 — **바탕을 눕혔는지**가 아니라
// **아무 바탕도 안 깔았는지**를 본다. 지나갔다는 사실은 「상태」 칸이 말한다.
test('기본 줄에는 **바탕을 안 깐다** — 페이지 배경이 그대로 비친다', () => {
  // 긍정 앵커 — 볼 대상(줄을 그리는 자리)이 이 파일에 있다
  assert.match(코드, /rows\.map\(r => \{/, '오늘 목록을 그리는 자리가 없다')
  assert.doesNotMatch(코드, /bg-ds-v3-surface-2/,
    '지나간 줄에 회색 바탕이 되살아났다 — 목록이 계단처럼 보이고 배경이 끊긴다')
  assert.doesNotMatch(코드, /function 지나간줄/,
    '철회된 판정이 코드에 남아 있다 — 다음 사람이 "왜 안 쓰지"를 다시 판다')
})

test('**시간이 지났다고 상태를 바꾸지 않는다** — 안 나간 방송이 나간 것으로 읽히면 안 된다', () => {
  // 판정을 화면이 하지 않는다는 것이 요지다. 회색 바탕이 빠지면서 시각을 보는 자리 자체가
  // 없어졌으므로, **시계를 다시 들이지 않았는지**로 본다.
  assert.doesNotMatch(코드, /getHours\(\)/,
    '화면이 다시 시각을 재고 있다 — 상태를 스스로 정하기 시작하는 첫 걸음이다')
  // 상태 글자는 서버가 준 status 로만 고른다
  assert.match(코드, /STATUS\[r\.status\]/, '상태를 서버 값으로 안 고른다')
})

test('**「다음」 줄만** 눈에 띈다 — 나머지는 아무 바탕도 없다', () => {
  const i = 코드.indexOf('isNext ?')
  assert.ok(i > 0, '「다음」 줄을 가르는 자리가 없다')
  const 줄 = 코드.slice(i, i + 260)
  assert.match(줄, /bg-white/, '「다음」 줄이 흰 바탕이 아니다')
  assert.match(줄, /rounded-\[10px\]/, '「다음」 줄의 모서리가 안 둥글다 — 물감이 네모로 보인다')
  assert.match(줄, /overflow-hidden/,
    '물감이 모서리 밖으로 샌다 — 그릇이 안 막혀 있으면 사각 경계가 드러난다')
  // 「안 나감」은 상태 글자 색으로 말한다(회색 바탕이 없어졌으므로 묻힐 바탕도 없다)
  assert.match(코드, /missed:\s*\{[^}]*text-ds-v3-bgm/, '「안 나감」이 눈에 띄는 색이 아니다')
})

// ── 2026-09-15: 좁은 화면은 **두 줄로 세운다** (사용자 지시) ──────────────────────
// *"모바일 ui에서는 시간 밑에 제목이랑 다음 이런거 집어넣어서 한줄에 보일 수 있게"*.
// 앞 판은 390px 에서 이름 칸이 152px 뿐이라 「아침 종합 방송」이 접혔고, 그러면 옆의
// 차수 단추와 줄이 어긋나 목록이 들쭉날쭉해 보였다(*"재생 카드들도 두줄 막 줄 어긋난거"*).
test('좁은 화면 격자는 **두 칸**이고, 넓은 화면은 네 칸 그대로다', () => {
  const m = 코드.match(/grid-cols-\[minmax\(0,1fr\)_94px\][\s\S]{0,120}?tablet:grid-cols-\[140px_minmax\(0,1fr\)_96px_100px\]/)
  assert.ok(m,
    '좁은 화면이 두 칸(이름+수동)이 아니거나, 넓은 화면 네 칸이 바뀌었다 — '
    + '좁은 쪽만 고치기로 한 변경이다')
})

test('**이름과 상태가 한 그릇**에 담긴다 — 좁을 때 한 줄에 나란히 선다', () => {
  // `tablet:contents` 가 넓은 화면에서 그릇을 레이아웃에서 지운다 — 그래야 넓은 화면
  // 배치가 한 글자도 안 바뀐다. 이것이 빠지면 넓은 화면에서 둘이 한 칸에 뭉친다.
  const i = 코드.indexOf('tablet:contents')
  assert.ok(i > 0, '이름·상태를 담는 그릇이 없다 — 좁은 화면에서 둘이 따로 줄을 먹는다')
  const 그릇 = 코드.slice(i - 200, i + 40)
  assert.match(그릇, /row-start-2/, '그릇이 둘째 줄에 안 선다 — 시각과 같은 줄에 겹친다')
  assert.match(그릇, /min-w-0/, '그릇이 안 줄어든다 — 긴 이름이 칸 밖으로 삐져나온다')
})
