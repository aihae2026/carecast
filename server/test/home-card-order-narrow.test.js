// 카드가 열려도 **좁은 화면에서 순서가 안 뒤집힌다** (사용자 신고 2026-09-14).
//
// ── 증상 ─────────────────────────────────────────────────────────────────────
// 휴대폰에서 「지금 말하기」를 누르면 입력 카드 대신 **오늘 일과방송**이 보였다.
// 카드가 안 열린 것이 아니라 **화면 밖으로 밀린 것**이다 — 실측 `top: 1090px`(화면 844px).
//
// ── 원인 ─────────────────────────────────────────────────────────────────────
// 카드가 열리면(`초안열림`) 배치가 `flex` → `grid` 로 바뀌는데, 그때의 순서 지정이
// **`wide:` 접두사뿐**이었다. 좁은 화면에서는 그 규칙이 하나도 안 걸려 **DOM 순서**가
// 그대로 나온다 — DOM 은 `HomeToday`(목록)가 먼저다. 그래서 목록이 맨 위로 올라갔다.
//
// CSS 투명도도, 스크롤도, 조건부 렌더링도 아니었다. **순서 규칙이 좁은 화면에 없던 것**이다.
//
// ── 이 시험이 보는 것 ────────────────────────────────────────────────────────
// 세 칸 모두 **접두사 없는 기본 순서**를 갖는지. 하나라도 `wide:` 에만 있으면 같은 일이
// 다시 난다. 브라우저 실측은 따로 하고(이 저장소는 렌더러를 시험에 안 들인다),
// 여기서는 **규칙이 빠지지 않았는지**를 고정한다.
'use strict'

const test   = require('node:test')
const assert = require('node:assert/strict')
const fs     = require('node:fs')
const path   = require('node:path')

const ROOT = path.join(__dirname, '..', '..')
const SRC  = fs.readFileSync(path.join(ROOT, 'src/pages/HomeMode.jsx'), 'utf8')
const 코드 = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

/** `초안열림 ? '…' : '…'` 의 **참 쪽** 문자열들. */
function 열렸을때클래스() {
  const out = []
  const re = /초안열림\s*\n?\s*\?\s*'([^']*)'/g
  let m
  while ((m = re.exec(코드))) out.push(m[1])
  return out
}

test('긍정 앵커 — 카드가 열렸을 때의 배치 규칙이 세 칸에 있다', () => {
  const 열림 = 열렸을때클래스()
  assert.ok(열림.length >= 3,
    `열렸을 때의 클래스를 ${열림.length}개만 찾았다 — 이 시험의 전제가 깨졌다`)
  // 2026-09-17 부터 두 칸은 `wide:` 가 아니라 `두칸`(창 폭 ÷ 배율) 조건 뒤에만 선다.
  assert.match(코드, /두칸\s*\?\s*'grid-cols-\[/, '넓은 화면의 두 칸 배치가 사라졌다')
})

test('열렸을 때도 **접두사 없는 order** 를 갖는다 — 좁은 화면에 규칙이 있어야 한다', () => {
  for (const c of 열렸을때클래스()) {
    if (!/order-/.test(c)) continue               // 순서를 안 정하는 칸은 건너뛴다
    assert.match(c, /(^|\s)order-\d/,
      `좁은 화면에 순서 규칙이 없다 — DOM 순서대로 목록이 맨 위로 올라간다: "${c}"`)
  }
})

test('닫혔을 때의 순서와 **같은 순서**다 — 열고 닫을 때 자리가 안 뛴다', () => {
  // 목록 order-3 · 입력 order-1 · 누르고말하기 order-2 — 열림/닫힘이 같아야 한다.
  const 쌍 = [...코드.matchAll(/초안열림\s*\n?\s*\?\s*'([^']*)'\s*\n?\s*:\s*'([^']*)'/g)]
  assert.ok(쌍.length >= 3, `열림/닫힘 쌍을 ${쌍.length}개만 찾았다`)
  for (const [, 열림, 닫힘] of 쌍) {
    const a = (열림.match(/(?:^|\s)(order-\d)/) || [])[1]
    const b = (닫힘.match(/(?:^|\s)(order-\d)/) || [])[1]
    if (!a && !b) continue
    assert.equal(a, b, `열렸을 때(${a})와 닫혔을 때(${b})의 순서가 다르다 — 카드를 열면 자리가 뛴다`)
  }
})
