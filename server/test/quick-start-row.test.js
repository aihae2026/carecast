// 검색창 밑 **빠른 단추** — 문장을 안 쳐도 시작되지만, **확정은 안 건너뛴다** (2026-09-14).
//
// 사용자 지적: *"예전에는 tts 방송이라고 있어서 약간 직관적이었단말이야? … 저 검색창이
// 생기면서 뭔가 좀 애매해지긴 했어, 직관적으로 즉시방송하고 싶기도 한데"*
//
// **이 시험이 지키는 두 가지**
//  ① 단추가 여는 초안이 맞다 — 유형·즉시 여부·제목.
//  ② **단추가 소리를 내지 않는다.** 초안만 만들고, 「지금 방송」을 사람이 눌러야 나간다.
//     전관 스피커로 나가는 것이라 되돌릴 수 없다(G-42). 이 줄이 무너지면 **잘못 누른 손가락
//     하나가 곧 방송**이 된다 — 야간 요양보호사 페르소나(P1)가 정확히 그 자리다.
//
// 판단을 `src/lib/quickStart.js` 로 내렸기 때문에 이 시험은 **진짜로 부른다.**
// 소스를 글자로 읽는 검사는 이 저장소에서 이미 여러 번 헛통과했다(V③ R23·R24).
'use strict'

const fs   = require('fs')
const path = require('path')
const test = require('node:test')
const assert = require('node:assert/strict')

const ROOT = path.join(__dirname, '..', '..')
const ASK  = path.join(ROOT, 'src', 'components', 'shared', 'QuickSchedulePhrase.jsx')

let Q
test.before(async () => {
  Q = await import('file:///' + path.join(ROOT, 'src', 'lib', 'quickStart.js').replace(/\\/g, '/'))
})

// 밑바탕은 `emptySchedule()` 자리다. 그 모듈은 아이콘을 들고 있어 노드에서 못 부르므로
// **넣어 준다** — 이 시험이 보는 것은 "밑바탕 위에 무엇을 덮는가"다.
const 밑바탕 = () => ({
  title: '', content: '', target: '전체', scheduled_time: '09:30', active: 1,
  broadcast_type: 'text', repeat_broadcast: 0, main_volume: null, bgm_volume: null,
})

test('단추 넷이 각각 제 유형으로 연다', () => {
  const 기대 = { tts: 'text', chime: 'chime', bgm: 'bgm', flow: 'flow' }
  for (const [id, 유형] of Object.entries(기대)) {
    const d = Q.빠른초안(id, 밑바탕())
    assert.ok(d, `${id} 단추가 초안을 안 만든다`)
    assert.equal(d.broadcast_type, 유형, `${id} 가 엉뚱한 유형을 연다`)
  }
})

// ── 2026-09-14: 줄에 **「예약 방송」이 들어왔다**(사용자 지시) ─────────────────
// 앞 판은 *"전부 지금 바로다"* 라고 못 박았다. 그때는 그게 사실이었다 — 줄의 목적이
// 「즉시 방송을 쉽게」 하나였다. 지금 줄은 `[지금 방송][예약 방송][배경음악][순서]` 라
// **둘을 갈라서** 봐야 한다. 하나로 뭉뚱그리면 예약이 즉시로 열려도 초록이 된다.
test('즉시 단추는 **지금 바로**, 예약 단추는 **예약으로** 연다', () => {
  for (const b of Q.빠른시작) {
    const 열림 = Q.빠른초안(b.id, 밑바탕())
    assert.equal(열림.immediate, b.id !== 'schedule',
      `${b.id} 가 반대로 열린다(immediate=${열림.immediate}) — 즉시와 예약은 뜻이 정반대다`)
  }
})

test('「예약 방송」은 **밑바탕 기본값을 지킨다** — 안 그러면 영영 안 울린다', () => {
  // 즉시 방송은 시각·반복·활성을 덮는다(다시 안 쏘게). 예약이 그 길을 지나면
  // **오늘 지금 시각 · 반복 없음 · 꺼짐**으로 저장돼 한 번도 안 나간다.
  const d = Q.빠른초안('schedule', 밑바탕(), new Date(2026, 8, 14, 13, 1))
  assert.equal(d.scheduled_time, '09:30', '예약의 시각이 「지금」으로 덮였다 — 즉시 방송의 규칙이 샜다')
  assert.equal(d.active, 1, '예약이 꺼진 채로 만들어진다 — 스케줄러가 영영 안 본다')
  assert.equal(d.broadcast_type, 'text', '예약 방송의 기본 유형이 안내 음성이 아니다')
})

// ── 차임벨은 **단추에서 빠졌지만 여는 법은 남는다** (사용자 지시 2026-09-14) ────
// *"차임벨을 다섯 번째 방송 카드나 독립 실행 모드로 만들지 마라"* 와
// *"기존 차임 예약·저장된 순서·API 기능은 삭제하지 않는다"* 는 같은 지시의 두 면이다.
test('차임벨은 줄에 안 서지만 `빠른초안` 은 여전히 연다', () => {
  assert.equal(Q.빠른시작.some(b => b.id === 'chime'), false,
    '차임벨이 아직 방송 카드 단추로 서 있다 — 설정 패널로 옮기라는 지시다')
  const d = Q.빠른초안('chime', 밑바탕())
  assert.ok(d, '차임 초안을 여는 길이 사라졌다 — 예약·흐름·API 가 쓰던 길이다')
  assert.equal(d.broadcast_type, 'chime', '차임 초안이 엉뚱한 유형으로 열린다')
})

test('제목이 비어 있지 않다 — 비면 확정이 막혀 또 막다른 길이 된다', () => {
  for (const b of Q.빠른시작) {
    const t = Q.빠른초안(b.id, 밑바탕()).title
    assert.match(t || '', /\S/, `${b.id} 의 제목이 비었다`)
  }
})

// ── 2026-09-14: 이 단언이 **결함을 사실로 적고 있었다** ─────────────────────────
// 예전 판은 `scheduled_time` 이 밑바탕(`09:30`) 그대로여야 한다고 못 박았다. 그런데 밑바탕은
// `emptySchedule()` 이고 그 기본값은 **새 예약을 만들 때의 것**이다 — 다음 5분 자리·매일 반복·
// 활성. 즉시 방송이 그것을 물려받는 바람에 **한 번 누른 방송이 몇 분 뒤 다시 나가고 내일도
// 나갔다**(사용자 신고). 그러므로 "덮어쓰지 않는다"는 규칙이 통째로 옳았던 것이 아니다.
//
// 사실을 다시 적는다: **실행을 정하는 값(시각·반복·활성)은 덮는다. 나머지는 안 건드린다.**
test('즉시 방송은 **실행값만** 덮는다 — 나머지 기본값은 밑바탕이 단일 출처다', () => {
  // **시계를 고정해서 묻는다**(V③ REPLAY-R2 지적, 2026-09-14). 앞 판은 *"밑바탕의 09:30 과
  // 달라야 한다"* 고 적었는데, 그것은 요구사항이 아니다 — **매일 09:30 에는 정상 구현도
  // 빨간불**이 된다(검수관이 09:30 을 주입해 재현했다). 요구사항은 하나다:
  // **즉시 방송의 예약 시각은 「지금」이다.** 그 값이 우연히 밑바탕과 같아도 옳다.
  const 지금 = new Date(2026, 8, 14, 13, 1)   // 09:30 이 아닌 시각
  const d = Q.빠른초안('tts', 밑바탕(), 지금)
  // 덮어야 하는 것 — 이걸 안 덮으면 예약으로 남아 다시 나간다
  assert.equal(d.scheduled_time, '13:01',
    '즉시 방송의 예약 시각이 「지금」이 아니다 — 미래 시각이면 그때 한 번 더 나간다')

  // 밑바탕 시각과 **같은 분**에 눌러도 규칙은 그대로다 — 시계가 아니라 규칙을 본다.
  const 같은분 = Q.빠른초안('tts', 밑바탕(), new Date(2026, 8, 14, 9, 30))
  assert.equal(같은분.scheduled_time, '09:30', '같은 분에 눌렀을 때 시각이 어긋난다')
  assert.deepEqual(같은분.repeat_weekdays, [], '같은 분이라고 반복 규칙이 달라진다')
  assert.equal(!!같은분.active, false, '같은 분이라고 활성 규칙이 달라진다')
  assert.deepEqual(d.repeat_weekdays, [],
    '즉시 방송이 반복 요일을 들고 있다 — 매일 같은 시각에 나간다')
  assert.equal(!!d.active, false,
    '즉시 방송이 활성 예약으로 남는다 — 스케줄러가 그 시각에 다시 쏜다')
  // 건드리면 안 되는 것 — 범위를 넘어 기본값을 흔들지 않는다
  assert.equal(d.main_volume, null, '볼륨 기본값을 건드렸다')
  assert.equal(d.target, '전체', '대상 기본값을 건드렸다')
})

test('모르는 단추는 지어내지 않는다', () => {
  for (const 없는 of ['', null, undefined, 'video', 'no-such']) {
    assert.equal(Q.빠른초안(없는, 밑바탕()), null, `${없는} 에 초안이 만들어졌다`)
    assert.equal(Q.빠른단추(없는), null)
  }
})

test('내용은 비워 둔다 — 사람이 안 적은 문구가 나가면 안 된다', () => {
  assert.equal(Q.빠른초안('tts', 밑바탕()).content, '', 'TTS 내용이 미리 채워져 있다')
})

// ── ② 단추가 소리를 내지 않는다 ──────────────────────────────────────────────
//
// 이 부분만 소스 대조다. 「누르면 발사한다」가 **없다**를 보는 것이라 실행으로는 못 본다
// (없는 것을 부를 수는 없다). 그래서 **긍정 앵커를 먼저 세운다** — 감시할 대상이
// 이 파일에 실제로 있는지부터 확인한다(`CLAUDE.md` 「파일을 가를 때」 ②).
test('빠른 단추는 초안만 연다 — 그 자리에서 발사하지 않는다', () => {
  const 글 = fs.readFileSync(ASK, 'utf8')

  // 긍정 앵커 — 빠른 단추 줄이 이 파일에 있다.
  assert.match(글, /빠른초안\(/, '빠른 단추가 이 화면에 없다 — 시험이 감시할 대상이 없다')
  // **`빠른시작` 을 직접 돌지 않는다**(2026-09-15) — `단추묶음()` 이 「지금/나중에」로
  // 갈라 주고, 그것이 `빠른시작` 에서 나온다. 화면이 제 목록을 적지 않는 것은 그대로다.
  assert.match(글, /단추묶음\(\)|빠른시작/, '단추 목록을 공용 규칙에서 안 가져온다')

  // 단추를 누르는 자리에서 발사 API 로 바로 가면 안 된다.
  const i = 글.indexOf('빠른초안(')
  const 앞뒤 = 글.slice(Math.max(0, i - 600), i + 600)
  assert.ok(!/triggerSchedule\s*\(/.test(앞뒤),
    '빠른 단추가 그 자리에서 방송을 발사한다 — 확인 한 단계가 사라졌다(G-42)')
  assert.ok(!/createSchedule\s*\(/.test(앞뒤),
    '빠른 단추가 그 자리에서 예약을 저장한다 — 초안 게이트를 건너뛴다')
})
