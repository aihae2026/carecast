'use strict'
// **캘린더가 읽히게 하는 네 가지** (사용자 지시 2026-09-16, 사진 8장).
//
// 넷 다 «색과 크기가 뜻을 못 하고 있다» 는 한 가지 문제의 다른 얼굴이다. 고친 뒤
// 시험이 없으면 다음 사람이 「보기 좋게」 되돌리기 쉬워서, 각각을 사실로 박는다.
//
// ── 1. 칩이 넓은 화면일수록 작아지고 있었다 ────────────────────────────────
// *"캘린더 밑에 자동방송이랑 매일방송 건 야 저건 인간적으로 너무 작지 않냐"*
//
// 원인은 **뒤집힌 중단점**이다. `tablet:` 은 `min-width: 834px`(이상)이라
// `text-[14px] tablet:text-[11px]` 은 **폰에 14px, PC 에 11px** 을 먹인다. 화면이
// 넓어질수록 글씨가 작아지는 셈이고, 사진을 찍은 PC 가 딱 그 11px 이었다.
//
// 그냥 키울 수는 없다 — 월 달력 한 칸은 `min-h-[104px]` 안에 칩 여럿을 담아야 한다.
// 그래서 **자리가 크기를 정한다**(`큼`).
//
// ── 2. 주 보기가 일곱 칸으로 쪼개져 있었다 ──────────────────────────────────
// 1400px 화면에서도 하루가 190px 이라, 칩이 그 폭에 맞춰 작아져야 했다. 위 11px 의
// 진짜 뿌리다. 세로 목록으로 바꾸면서 칸을 가로로 쪼개는 일을 그만뒀다.
// (그 사실은 `narrow-screen-tables.test.js` 의 「사실3」이 지킨다 — 여기서 겹쳐 세지 않는다)
//
// ── 3. 목록에 무늬가 둘 겹쳐 있었다 ─────────────────────────────────────────
// *"목록은 왜 이렇게 얼룩덜룩하게 보여 … 아예 저렇게 넣지말고 반투명(너무 반투명말고 살짝)"*
//
// 홀짝 줄무늬(`idx % 2`)와 자동방송 파랑(`/40`)이 엇갈렸다. 줄무늬는 눈이 줄을
// 놓치지 말라고 쓰는 것인데 이 표는 줄 사이에 선이 이미 있어 **일을 두 번** 하고 있었다.
//
// ── 4. 색이 정반대로 쓰이고 있었다 ──────────────────────────────────────────
// *"활성 표시 저렇게 회색하니까 좀 그래 차라리 시간을 검은색 및 회색으로 하고
//   상태를 파란색을 넣던지"*
//
// 시각이 파랑이고 「활성」이 회색이었다. **모든 줄의 시각이 똑같이 파래서** 파랑이
// 아무것도 안 가리키고, 정작 살았나 멈췄나는 회색이라 꺼진 것처럼 보였다.
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const SRC = path.join(__dirname, '..', '..', 'src', 'components', 'admin', 'sections')
const 읽기 = (f) => fs.readFileSync(path.join(SRC, f), 'utf8')

// **주석을 먼저 걷는다.** 이 저장소의 주석은 «무엇을 왜 고쳤나» 를 적으므로 고친 옛
// 코드를 그대로 인용한다 — 걷지 않으면 «`idx % 2` 가 없어야 한다» 가 **그 사실을 적은
// 주석 때문에** 빨간불이 난다(2026-09-16 실제로 그랬다).
const 주석없이 = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

const WEEK = 주석없이(읽기('WeeklySchedule.jsx'))
const LIST = 주석없이(읽기('ScheduledBroadcast.jsx'))

test('**칩 크기를 한 곳에서 정한다** — 세 칩이 따로 놀면 한 칩만 커진다', () => {
  assert.match(WEEK, /const 칩크기 = \(큼\) =>/, '칩 크기 단일 출처가 없다')

  // 세 칩이 모두 그 한 곳을 쓴다. **개수를 센다** — 하나라도 옛 글자를 들고 있으면
  // 그 칩만 안 커지고, 그건 화면에서 「왜 얘만 작지」로 나타난다.
  const 쓴횟수 = (WEEK.match(/\+ 칩크기\(큼\)/g) || []).length
  assert.equal(쓴횟수, 3,
    `칩 셋 중 ${쓴횟수}개만 공용 크기를 쓴다 — BroadcastChip·DailyChip·AutoChip 전부여야 한다`)

  // 옛 모양이 되살아나지 않았는지도 본다. 되살아나면 그 칩만 다시 11px 이 된다.
  assert.doesNotMatch(WEEK, /tablet:min-h-\[24px\] tablet:text-\[11px\][\s\S]{0,40}hover:brightness/,
    '칩 클래스에 옛 크기 글자가 다시 박혔다')
})

test('**넓은 자리에서는 칩이 커진다** — 고른 날 목록과 주 보기', () => {
  // 크기를 「자리가 정한다」는 말은, **실제로 큰 자리가 큼을 넘겨야** 뜻이 있다.
  // 안 넘기면 `칩크기` 는 있는데 아무도 안 써서 화면은 그대로다.
  const 큼넘김 = (WEEK.match(/v3=\{v3\} 큼/g) || []).length
  assert.ok(큼넘김 >= 6,
    `큰 칩을 쓰는 자리가 ${큼넘김}곳뿐이다 — 주 보기 셋 + 고른 날 목록 셋이어야 한다`)

  // **달력 칸은 그대로 촘촘해야 한다.** 여기까지 키우면 한 칸에 칩이 안 들어간다.
  const 달력칸 = WEEK.slice(WEEK.indexOf('function MonthDayCell'), WEEK.indexOf('function DayCard'))
  assert.ok(달력칸.length > 200, '월 달력 칸을 못 찾았다 — 이 시험이 헛돌고 있다')
  assert.doesNotMatch(달력칸, /큼/,
    '월 달력 칸까지 칩을 키웠다 — 한 칸(min-h-104px)에 칩 여럿이 안 들어간다')
})

test('**목록에 홀짝 줄무늬가 없다** — 선이 이미 줄을 가른다', () => {
  assert.doesNotMatch(LIST, /idx % 2/,
    '홀짝 줄무늬가 살아 있다 — 자동방송 색과 엇갈려 얼룩이 된다')
  // 긍정 앵커 — 줄 바탕을 칠하는 자리가 이 파일에 실제로 있다.
  assert.match(LIST, /border-b border-ds-v3-line transition-colors/,
    '표 줄을 그리는 자리를 못 찾았다 — 이 시험이 헛돌고 있다')
  // 자동방송은 **살짝만** 비친다. `/40` 이던 것을 `/20` 으로 내렸다.
  assert.match(LIST, /bg-ds-v3-tts-bg\/20/,
    '자동방송 줄이 옅게 비치지 않는다')
})

test('**시각은 잉크, 상태는 파랑** — 색을 정반대로 쓰지 않는다', () => {
  // 시각 칸: 파랑이면 안 된다(줄마다 다른 값이라 색이 가리킬 것이 없다).
  const 시각칸 = /<td className="px-3 md:px-5 py-3\.5 nums font-semibold (text-[a-z0-9-]+)"/.exec(LIST)
  assert.ok(시각칸, '시각 칸을 못 찾았다 — 이 시험이 헛돌고 있다')
  assert.equal(시각칸[1], 'text-ds-v3-ink',
    `시각이 ${시각칸[1]} 이다 — 모든 줄이 같은 색이면 그 색은 아무것도 안 가리킨다`)

  // 「활성」은 파랑이어야 한다.
  const 상태 = LIST.slice(LIST.indexOf('export function ScheduleStatus'),
    LIST.indexOf('// ── 즐겨찾기 버튼 편집기'))
  assert.ok(상태.length > 100, '상태 부품을 못 찾았다 — 이 시험이 헛돌고 있다')
  assert.match(상태, /text-ds-v3-tts[\s\S]{0,120}활성/,
    '「활성」이 파랑이 아니다 — 살아 있는지가 안 읽힌다')

  // **같은 마크업을 두 벌 두지 않는다.** 예전엔 자동방송 줄에 한 벌이 더 박혀 있어
  // 색을 고칠 때 한쪽만 바뀌었다.
  const 활성마크업 = (LIST.match(/rounded-full bg-ds-v3-[a-z0-9-]+ inline-block" \/> 활성/g) || []).length
  assert.equal(활성마크업, 1,
    `「활성」 마크업이 ${활성마크업}벌이다 — 한 벌이어야 색을 한 번에 고칠 수 있다`)
})
