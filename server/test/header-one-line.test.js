'use strict'
// **머리줄은 한 줄이다** (사용자 신고 2026-09-16).
//
// *"이거 왜 토글 간편-캘린더 이거 토글 위치 왜 바뀌었냐? 일부러 바꿨어?"*
// *"이렇게 겹쳐지잖아."*
//
// ── 무엇이 일어났나 ────────────────────────────────────────────────────────
// 머리줄이 `flex-wrap` 이었다. 그래서 안에 든 것이 조금만 넓어져도 — 「크게 보기」
// 단추를 더한 것, 날씨 칩을 더한 것, 배율을 올린 것 — **탭 줄이 둘째 줄로 떨어졌다.**
//
// 그러면 두 가지가 한꺼번에 나빠진다:
//   ① 탭이 **오른쪽 끝에서 왼쪽 끝으로** 자리를 옮긴다. 어제 눈으로 찾던 자리에 없다.
//   ② 머리줄이 두 배로 높아져 **밑의 글과 겹쳐 보인다.**
//
// **접히게 두는 것이 애초에 틀린 선택이었다.** 머리줄은 자리가 고정돼야 사람이 눈으로
// 찾는다. 좁아지면 탭 줄이 **제 안에서** 밀리는 것이 맞다.
//
// ── 이 시험이 지키는 것 ────────────────────────────────────────────────────
// 머리줄에 무엇을 더할 때마다 같은 일이 반복됐다(메뉴 단추 → 날씨 칩 → 크게 보기).
// 다음에 무엇을 더하더라도 **줄이 접히면 빨간불**이 나게 한다.
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const ROOT = path.join(__dirname, '..', '..')
const SRC = fs.readFileSync(path.join(ROOT, 'src/components/home/HomeShell.jsx'), 'utf8')
const 코드만 = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

// 머리줄의 **줄 상자** 하나만 잘라 본다. 파일 전체를 보면 서랍·본문의 `flex-wrap` 까지
// 걸려서 엉뚱한 빨간불이 난다.
function 머리줄상자() {
  const i = 코드만.indexOf('max-w-[1280px]')
  assert.ok(i > 0, '머리줄 줄 상자를 못 찾았다 — 이 시험의 전제가 무너졌다')
  const 시작 = 코드만.lastIndexOf('<div', i)
  const 끝 = 코드만.indexOf('>', i)
  return 코드만.slice(시작, 끝 + 1)
}

test('긍정 앵커 — 머리줄 줄 상자가 있다', () => {
  const 상자 = 머리줄상자()
  assert.match(상자, /flex/, '머리줄이 flex 가 아니다')
  assert.ok(상자.length < 600, `줄 상자만 잘라야 한다 — ${상자.length}자를 읽었다`)
})

test('**머리줄이 안 접힌다** — 접히면 탭이 딴 데로 가고 밑의 글과 겹친다', () => {
  const 상자 = 머리줄상자()
  assert.ok(!/flex-wrap/.test(상자),
    '머리줄이 접힌다 — 무언가를 더하는 순간 탭 줄이 둘째 줄로 떨어진다')
  assert.match(상자, /flex-nowrap/, '안 접는다고 명시하지 않았다')
})

test('**탭 줄이 제 안에서 밀린다** — 안 그러면 머리줄이 통째로 넘친다', () => {
  const i = 코드만.indexOf('<nav')
  assert.ok(i > 0, '탭 줄을 못 찾았다')
  const nav = 코드만.slice(i, 코드만.indexOf('>', 코드만.indexOf('aria-label="화면"')) + 1)

  assert.match(nav, /min-w-0/,
    '탭 줄이 안 줄어든다 — 제 내용만큼 버텨서 머리줄 전체를 넘치게 만든다')
  assert.match(nav, /overflow-x-auto/, '넘칠 때 밀리지 않는다')
  // **`shrink-0` 과 같이 쓰면 안 된다** — 서로 반대말이라 하나가 죽는다.
  assert.ok(!/\bshrink-0\b/.test(nav),
    '안 줄어든다(shrink-0)와 줄어든다(min-w-0)가 같이 있다 — 뜻이 반대다')
})

test('**머리줄 높이가 정해져 있다** — 내용에 따라 늘었다 줄었다 하면 밑이 흔들린다', () => {
  const 상자 = 머리줄상자()
  assert.match(상자, /h-1[46]/, '머리줄 높이가 고정이 아니다')
})

test('**높이를 재서 밑에 알려 준다** — 그 값으로 본문이 자리를 비운다', () => {
  // 머리줄은 `sticky` 라 본문 위에 뜬다. 높이를 안 알려 주면 본문 첫 줄이 가려진다.
  assert.match(코드만, /--cc-header-h/, '머리줄 높이를 안 내보낸다')
  assert.match(코드만, /offsetHeight/, '높이를 재지 않는다 — 박아 두면 내용이 바뀔 때 어긋난다')
})

// ── **시계가 탭 위에 겹치지 않는다** (사용자 신고 2026-09-16, 두 번째) ────────────
//
// *"저기 창 줄이니까 시간 쪽 겹쳐지는거 버그 보이지?"*
//
// 시계를 **화면 한가운데**에 세우려고 자리에서 빼냈다(`absolute left-1/2`). 그 말은
// **아무도 그 자리를 비켜 주지 않는다**는 뜻이다 — 탭이 늘어나면 그대로 시계 밑을
// 파고든다. 접힘(위 시험)과는 다른 고장이라 따로 본다.
//
// 막는 장치가 둘이고 **둘의 기준 폭이 같아야 한다**:
//   ① `HomeClock` 이 그려지기 시작하는 폭
//   ② `HomeShell` 의 탭 줄이 가운데로 못 오게 막히는 폭
// 하나만 옮기면 그 사이 구간에서 다시 겹친다. 그래서 **둘을 맞춰 본다.**
const CLOCK = fs.readFileSync(path.join(ROOT, 'src/components/home/HomeClock.jsx'), 'utf8')
const 시계코드만 = CLOCK.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

test('**시계는 자리에서 빠져 화면 한가운데에 선다** — 이 시험들의 전제다', () => {
  assert.match(코드만, /absolute left-1\/2 -translate-x-1\/2/,
    '시계를 가운데 세우는 자리를 못 찾았다 — 아래 두 시험의 전제가 무너졌다')
})

// 탭 줄(`<nav>`)의 **여는 태그**만 잘라 본다. 머리줄 줄 상자는 바깥 `<div>` 라
// 그 안의 탭 줄이 안 들어간다(위 `머리줄상자` 는 여는 태그 하나만 돌려준다).
function 탭줄() {
  const i = 코드만.indexOf('<nav')
  assert.ok(i > 0, '탭 줄을 못 찾았다 — 이 시험의 전제가 무너졌다')
  return 코드만.slice(i, 코드만.indexOf('>', i) + 1)
}

test('**탭 줄이 가운데로 넘어오지 못한다** — 시계가 비켜 줄 수 없기 때문이다', () => {
  const 상자 = 탭줄()
  assert.match(상자, /max-w-\[calc\(50%-\d+px\)\]/,
    '탭 줄에 가운데를 막는 max-w 가 없다 — 탭이 늘면 시계 밑으로 파고든다')
})

test('**시계가 보이는 폭과 탭을 막는 폭이 같다** — 어긋나면 그 사이에서 겹친다', () => {
  const 시계폭 = 시계코드만.match(/hidden\s+([a-z]+):flex/)
  assert.ok(시계폭, 'HomeClock 이 어느 폭부터 보이는지 못 찾았다')

  const 탭폭 = 탭줄().match(/([a-z]+):max-w-\[calc\(50%-\d+px\)\]/)
  assert.ok(탭폭, '탭 줄의 max-w 가 어느 폭부터인지 못 찾았다')

  assert.equal(탭폭[1], 시계폭[1],
    `시계는 ${시계폭[1]} 부터 보이는데 탭은 ${탭폭[1]} 부터 막힌다 — 그 사이 폭에서 겹친다`)
})
