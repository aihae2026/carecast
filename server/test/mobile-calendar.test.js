// 휴대폰 달력 — **위에는 점, 누르면 아래에 그날 목록** (사용자 지시 2026-09-15).
//
// ── 무엇이 문제였나 ──────────────────────────────────────────────────────────
// *"핸드폰에서 캘린더 화면을 ui를 모바일 전용으로 하나 만들까봐 저렇게 애플에 위에
//   일정 떠주고 누르면 나오게끔 그대로 웹 들어오니까 꾸져보이잖아."*
//
// 휴대폰에서 한 칸이 약 51px 인데 칸마다 제목·시각 칩을 쌓고 있었다(`min-h-[104px]`).
// 글자가 뭉개지고 한 화면에 두 주도 안 들어왔다.
//
// ── 고친 방향 ────────────────────────────────────────────────────────────────
// 좁은 화면에서는 칸에 **날짜와 점만** 찍고, 고른 날의 목록을 달력 **아래**에 편다.
//
// ── 이 시험이 **꼭** 보는 것 ─────────────────────────────────────────────────
// **아래 목록이 새로 만든 목록이 아니어야 한다.** 이 저장소는 같은 것을 두 벌로 만들었다가
// 한쪽만 고쳐지는 실패를 여러 번 겪었다(`UX-21` 이 목록 탭을 옮길 때의 판단과 같다).
// 위 격자가 쓰는 **같은 칩 부품**을 써야 상세 팝업·일시정지·묶음 접기를 안 잃는다.
'use strict'

const test   = require('node:test')
const assert = require('node:assert/strict')
const fs     = require('node:fs')
const path   = require('node:path')

const ROOT = path.join(__dirname, '..', '..')
const 읽기 = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8')
const 코드만 = (s) => s
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\s*\/\/.*$/gm, '')
  .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')

const SRC = 읽기('src/components/admin/sections/WeeklySchedule.jsx')
const 코드 = 코드만(SRC)

test('긍정 앵커 — 달력과 날짜 칸이 이 파일에 있다', () => {
  assert.match(코드, /function MonthDayCell/, '날짜 칸을 못 찾았다 — 옮겼으면 이 시험도 같이 옮긴다')
  assert.match(코드, /grid-cols-7/, '달력 격자가 없다')
})

test('**폭 판정을 여기서 새로 만들지 않는다** — 기준이 갈리면 반쪽만 바뀐다', () => {
  assert.match(코드, /useWideScreen/, '공용 폭 판정을 안 쓴다')
  assert.doesNotMatch(코드, /matchMedia/,
    '이 파일이 제 손으로 폭을 잰다 — 기준 폭이 CSS 의 `tablet:` 과 갈리면 그 사이 폭에서 화면 반쪽만 바뀐다')
  // 공용 훅의 기본값이 CSS 의 `tablet` 과 같아야 한다.
  const 훅 = 읽기('src/hooks/useWideScreen.js')
  const m = 훅.match(/기준폭 = (\d+)/)
  assert.ok(m, '공용 훅에 기본 기준폭이 없다')
  const cfg = 읽기('tailwind.config.js')
  assert.match(cfg, new RegExp(`tablet:\\s*'${m[1]}px'`),
    `훅의 기준폭 ${m[1]}px 가 tailwind 의 tablet 과 다르다 — CSS 와 JS 가 다른 폭에서 갈린다`)
})

test('좁은 화면 칸은 **점만** 찍고, 넓은 화면은 칩 그대로다', () => {
  assert.match(코드, /점만/, '좁은 화면 전용 칸이 없다')
  assert.match(코드, /function 점요약/, '점 요약 부품이 없다')
  // 점 색은 이 화면의 **색 표 하나**에서 온다 — 손으로 적으면 칩과 색이 갈린다.
  const i = 코드.indexOf('function 점요약')
  assert.match(코드.slice(i, i + 700), /KIND_STYLE/,
    '점 색을 손으로 적었다 — 칩과 색이 갈리면 같은 방송이 자리마다 달라 보인다')
  // 넓은 화면 칸의 높이는 그대로여야 한다(칩을 쌓을 자리가 필요하다).
  assert.match(코드, /min-h-\[104px\]/, '넓은 화면 칸 높이가 바뀌었다 — 칩이 잘린다')
})

test('**손가락이 닿는다** — 좁은 칸도 44px 이상이다', () => {
  const i = 코드.indexOf('if (점만) {')
  assert.ok(i > 0, '좁은 화면 칸을 못 찾았다')
  const 몸통 = 코드.slice(i, i + 1400)
  const m = 몸통.match(/min-h-\[(\d+)px\]/)
  assert.ok(m, '좁은 화면 칸에 최소 높이가 없다')
  assert.ok(Number(m[1]) >= 44,
    `좁은 화면 칸이 ${m[1]}px 다 — 7칸이 390px 에 들어가느라 가로가 좁으니 세로로 44px 이상을 줘야 한다(G-15)`)
})

test('**아래 목록이 새 목록이 아니다** — 위 격자와 같은 칩을 쓴다', () => {
  // **앵커가 `좁은화면` 에서 `접어보기` 로 옮겨졌다**(2026-09-15). 넓은 화면에서도
  // 카드가 열리면 같은 모습으로 접으므로 판정 이름이 바뀌었다 — 이 시험이 지키는 것은
  // 그대로다(고른 날 목록이 **새 목록이 아니라 같은 칩을 쓴다**).
  const i = 코드.indexOf('접어보기 && (')
  assert.ok(i > 0, '고른 날 목록을 못 찾았다')
  const 목록 = 코드.slice(i, i + 2600)
  // 같은 부품 셋을 그대로 쓴다 — 새로 그리면 상세 팝업·일시정지·묶음 접기를 잃는다.
  for (const 부품 of ['AutoChip', 'DailyChip', 'BroadcastChip']) {
    assert.ok(목록.includes(부품),
      `고른 날 목록이 ${부품} 을 안 쓴다 — 목록을 새로 그리면 그 부품의 기능(상세 팝업·일시정지·묶음)을 잃는다`)
  }
  // 같은 묶음 규칙을 쓴다 — 안 쓰면 환기방송이 낱개로 풀려 목록이 길어진다.
  assert.match(목록, /batchSchedules/, '고른 날 목록이 묶음 규칙을 안 쓴다')
  // 누르면 **같은 상세 팝업**이 뜬다.
  assert.match(목록, /openDetail\(/, '고른 날 목록의 칩이 상세 팝업을 안 연다')
})

test('**지난 날에는 예약 추가를 안 내놓는다** — 넣어도 영영 안 나간다', () => {
  // **앵커가 `좁은화면` 에서 `접어보기` 로 옮겨졌다**(2026-09-15). 넓은 화면에서도
  // 카드가 열리면 같은 모습으로 접으므로 판정 이름이 바뀌었다 — 이 시험이 지키는 것은
  // 그대로다(고른 날 목록이 **새 목록이 아니라 같은 칩을 쓴다**).
  const i = 코드.indexOf('접어보기 && (')
  const 목록 = 코드.slice(i, i + 2600)
  const j = 목록.indexOf('이 날 예약')
  assert.ok(j > 0, '고른 날에 예약을 넣는 단추가 없다 — 달력에서 예약을 못 만든다')
  // 그 단추가 지난 날 조건 안에 있어야 한다.
  assert.match(목록.slice(Math.max(0, j - 400), j), /!지난날\(그날\)/,
    '지난 날에도 예약 추가가 뜬다 — 1회성 예약은 시작일 당일에만 발동해서 저장돼도 영영 안 울린다')
})

test('같은 날을 **다시 누르면 접힌다** — 달력을 다 보고 싶을 때가 있다', () => {
  assert.match(코드, /set고른날\(v => \(v === key \? null : key\)\)/,
    '같은 날을 다시 눌러도 안 접힌다 — 목록이 화면을 계속 차지한다')
})
