// 「AI 도움받기」 — **그 칸에 바로 덮어쓴다.** 그리고 눈에 보인다 (2026-09-14).
//
// ── 사용자가 물은 것 ─────────────────────────────────────────────────────────
//   *"그리고 AI 도움받기는 왜 없어졌냐?"*
//   *"지금 aI방송문 예전에도 밑에 막 또 나와서 지저분하기도 했어, 아예 그냥 그 창 하나에
//     ai가 고쳐서 채워넣는건 어때?"*
//
// **둘 다 이미 그렇게 돼 있었다.** 없어진 적이 없고, 후보 목록을 아래에 뿌리지도 않는다 —
// 결과가 곧 그 칸에 들어간다. 문제는 **작은 글자 링크**라 바로 아래 체크박스 줄과
// 생김새가 같았다는 것이다. 눈이 그것을 체크박스로 읽고 지나쳤다.
//
// 그래서 이 시험이 지키는 것은 셋이다:
//  ① 덮어쓰기다 — 후보 목록을 따로 뿌리지 않는다
//  ② 되돌릴 수 있다 — 덮기 전 원문을 쥔다
//  ③ **단추다** — 링크로 되돌아가지 않는다. 그리고 주황은 **이 한 자리뿐**이다
'use strict'

const fs   = require('fs')
const path = require('path')
const test = require('node:test')
const assert = require('node:assert/strict')

const ROOT = path.join(__dirname, '..', '..')
const ASK  = path.join(ROOT, 'src', 'components', 'shared', 'QuickSchedulePhrase.jsx')
const 글 = fs.readFileSync(ASK, 'utf8')

/**
 * 「AI 도움받기」 **단추**가 있는 구간만 잘라 본다.
 *
 * 앵커를 낱말로 잡았다가 한 번 틀렸다 — 바로 위 **주석**에도 그 낱말이 있어서
 * 엉뚱한 단추를 집었다. 그래서 화면에 실제로 그려지는 **JSX 문자열**을 앵커로 쓴다.
 */
function AI구간() {
  const 앵커 = "'AI 도움받기'"
  const i = 글.indexOf(앵커)
  assert.ok(i > 0, '긍정 앵커 — 화면에 그려지는 「AI 도움받기」 글자가 이 파일에 있다')
  const 시작 = 글.lastIndexOf('<button', i)
  assert.ok(시작 > 0, '긍정 앵커 — 그 글자 앞에 단추가 있다')
  return 글.slice(시작, i + 앵커.length)
}

test('AI 는 **그 칸에 바로 덮어쓴다** — 후보를 아래에 뿌리지 않는다', () => {
  // 2026-09-14: 700자로 잘라 보다가 **늦은 응답 가드가 끼어들면서 창 밖으로 밀렸다.**
  // 글자 위치로 자르는 창은 그 사이에 코드가 늘면 조용히 빗나간다 — 넉넉히 잡는다.
  const 구간 = 글.slice(글.indexOf('방송문구짓기('), 글.indexOf('방송문구짓기(') + 2000)
  assert.match(구간, /setDraft\(d => \(\{ \.\.\.d, content: r\.text \}\)\)/,
    'AI 결과가 내용 칸으로 안 들어간다 — 따로 뿌리면 화면이 지저분해진다')
  // 후보를 여러 개 받아 목록으로 그리는 자리가 없어야 한다.
  assert.ok(!/후보|suggestions|candidates/.test(구간),
    'AI 후보 목록이 돌아왔다 — 사용자가 "밑에 막 또 나와서 지저분하다"고 짚은 그 모양이다')
})

test('덮기 전 원문을 쥔다 — 「원래대로」가 살아 있다', () => {
  // **`draft.content` 가 아니라 `보낸글` 이다**(2026-09-14). 비동기 콜백의 `draft` 는
  // 누른 순간 값으로 굳어 있어 그것을 그대로 쓰면 「지금」과 「그때」가 뒤섞인다.
  // 보낼 때 적어 둔 `보낸글` 이 곧 **덮기 직전의 원문**이다.
  assert.match(글, /const 보낸글 = draft\.content \|\| ''/, '보낼 때의 원문을 안 적어 둔다')
  assert.match(글, /set이전문구\(보낸글\)/, '덮기 전 원문을 안 쥔다')
  assert.match(글, /원래대로/, '되돌리는 단추가 없다 — 덮어쓰기만 있고 무를 수 없다')
})

test('링크가 아니라 **단추**다 — 체크박스 줄에 섞이지 않는다', () => {
  const 구간 = AI구간()
  assert.match(구간, /rounded-full/, 'AI 도움받기가 알약 단추가 아니다')
  // **앵커가 옮겨졌다**(2026-09-16): 옛 주황 `cc-orange` 는 이 제품의 색 언어에 없는
  // 색이라 무채색(`ds-v3-ink-2`)으로 갔다. 이 시험이 막으려는 것은 **「채운 단추냐
  // 글자 링크냐」**이지 색이 아니다 — 그래서 **채워졌는지**를 본다.
  assert.match(구간, /bg-ds-v3-[a-z0-9-]+/, '채움색이 없다 — 다시 글자 링크로 돌아갔다')
  // G-15 — 손으로 누르는 것은 44px 이상이다. 36px 를 허용했다가 `home-layering` 가 잡았다.
  assert.match(구간, /min-h-\[4[4-9]px\]|min-h-\[[5-9]\dpx\]/, '누를 자리가 44px 미만이다(G-15)')
})

test('주황이 **하나도 없다** — 넷째 색을 아예 안 쓴다', () => {
  // ── **시험이 뒤집혔다**(2026-09-16). 앞 판은 *"주황은 이 한 자리뿐"* 이라 **하나는
  // 있어야** 통과했다. 그때는 AI 단추만 예외로 두는 절충이었다.
  //
  // 이제 절충이 없다 — 옛 이름표와 원색을 전부 걷어내면서 **주황이 0건**이 됐다
  // (사용자 지시: *"브랜드 디자인할 때 통일감 있어야 하잖아"*). 그러니 검사도
  // *"하나뿐이다"* 가 아니라 *"하나도 없다"* 여야 한다.
  //
  // **약해진 것이 아니라 세졌다.** 허용치가 2 에서 0 으로 내려갔다.
  const 주황 = (글.match(/cc-orange|orange-\d00|amber-\d00|yellow-\d00/g) || []).length
  assert.equal(주황, 0,
    `주황 계열이 ${주황}군데다 — 이 제품의 색은 셋(말·음악·순서)과 경고뿐이다(G-1·G-6). `
    + '넷째 색이 번지면 "이 색이 무슨 뜻이냐"를 사람이 더는 못 외운다')

  // **긍정 앵커는 「단추가 아직 있다」로 옮긴다** — 없을 것만 보는 검사는 파일이
  // 통째로 사라져도 통과한다(「파일을 가를 때」 규칙 ②).
  assert.match(글, /AI 도움받기/, '긍정 앵커 — AI 단추가 이 파일에 있다')
})

test('AI 가 실패하면 말해 준다 — 조용히 아무 일도 안 하지 않는다', () => {
  assert.match(글, /setAi오류\(e\.message \|\| 'AI 가 문구를 못 만들었습니다\.'\)/,
    'AI 실패가 화면에 안 뜬다')
  assert.match(글, /무엇을 방송할지 먼저 적어 주세요/,
    '빈 칸에서 눌렀을 때 아무 일도 안 일어난다 — 사람은 고장으로 읽는다')
})
