// ── **안 나간 방송은 이 자리에서 말하지 않는다** (사용자 결정 2026-09-15) ────────────
// 앞 판은 이 자리의 첫째 갈래가 「국민체조가 안 나갔어요.」였고, 이 시험이 그것을
// *"급한 것이 먼저다"* 로 고정하고 있었다. **띄워 놓고 보니 그 말이 오래 떠 있었다** —
// 아침에 하나 놓친 날은 하루 종일 같은 문장이라, 안내가 아니라 꾸지람이 된다.
//
// 사용자 결정: *"안 나갔다라는 내용이 오래 떠있으니까 부정적인 느낌이 들어. 그냥
// 부정적인 것들은 빼버리자, 어차피 상태로 확인 가능하니까."*
//
// **시험을 지우지 않고 뒤집는다.** 지우면 「다시 들어와도 아무도 모르는」 자리가 된다.
test('**안 나간 방송을 이 자리에서 말하지 않는다** — 오래 떠 있으면 꾸지람이 된다', () => {
  const 지금 = new Date(2026, 8, 15, 11, 12)
  const 오늘 = [
    { status: 'missed',  label: '국민체조',          time: '09:00' },
    { status: 'pending', label: '점심 식사 전 방송', time: '11:15' },
  ]
  const a = G.한줄고르기({ 기능들, 오늘, 지금 })
  assert.notEqual(a?.kind, 'missed', `안 나갔다는 말이 돌아왔다: ${a?.text}`)
  assert.equal(a.kind, 'soon', `안 나간 것을 건너뛰고 곧 나갈 것을 말해야 한다: ${a.text}`)

  // **어느 갈래에서도 그 말이 안 나온다.** 차례 전체를 훑는다 — 한 갈래만 막으면
  // 다른 갈래로 돌아 나온다.
  const 차례 = G.차례짜기({ 기능들, 오늘, 지금 })
  assert.equal(차례.붙잡는말, null, '붙잡는 말이 살아 있다')
  for (const x of 차례.차례) {
    assert.doesNotMatch(x.text, /안 나갔|못 나갔|누락/, `부정 문구가 차례에 있다: ${x.text}`)
    assert.notEqual(x.kind, 'missed', `missed 갈래가 차례에 있다: ${x.text}`)
  }

  // 나머지 차례는 그대로다 — 곧 나갈 것 > 안심 > 기능 안내.
  const b = G.한줄고르기({ 기능들, 오늘: [오늘[1]], 지금 })
  assert.equal(b.kind, 'soon')
  const c = G.한줄고르기({ 기능들, 오늘: [], 지금 })
  assert.equal(c.kind, 'feature')
})

