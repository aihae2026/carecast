  const 부름 = /getHomeTip\((.*)$/m.exec(화면)
  assert.ok(부름, 'getHomeTip 호출을 못 찾았다')
  assert.doesNotMatch(부름[1], /칸|회전/,
    `차례 번호를 서버로 보낸다: getHomeTip(${부름[1]}`)

  // ③ 못 받았을 때 돌아갈 문장이 **서버의 닻 문구와 같아야** 한다. 갈리면 평소 제목과
  //    서버가 고른 제목이 다른 말이 된다 — 사람은 깜빡였다고 느낀다.
  assert.ok(화면.includes(`'${G.닻문구}'`),
    `화면의 기본 제목이 서버의 닻 문구(${G.닻문구})와 다르다`)
