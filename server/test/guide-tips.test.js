test('**세지 못하는 것은 말하지 않는다** — 오늘 목록이 근거다', () => {
  // 예약이 없는 날에 「다 잘 나갔어요」라고 하면 그건 지어낸 말이다.
  const 빈날 = G.오늘말들([], new Date(2026, 8, 15, 14, 0)).map(x => x.text)
  assert.deepEqual(빈날, ['오늘은 잡힌 방송이 없어요.'], `빈 날에 딴말을 한다: ${빈날.join(' / ')}`)

  // 끝난 것이 없으면 「잘 나갔어요」가 없어야 한다.
  const 아직 = G.오늘말들([{ status: 'pending', label: '저녁 마무리', time: '18:00' }],
    new Date(2026, 8, 15, 9, 0)).map(x => x.text)
  assert.ok(!아직.some(t => /잘 나갔/.test(t)), `안 나갔는데 나갔다고 한다: ${아직.join(' / ')}`)
  assert.ok(아직.some(t => /1건 더 남았/.test(t)), `남은 건수를 안 말한다: ${아직.join(' / ')}`)

  // 남은 게 있는데 「다」라고 하지 않는다.
  const 섞임 = G.오늘말들(
    [{ status: 'done', label: '아침', time: '07:50' }, { status: 'pending', label: '저녁', time: '18:00' }],
    new Date(2026, 8, 15, 14, 0)).map(x => x.text)
  assert.ok(!섞임.some(t => /다 잘 나갔/.test(t)), `남았는데 「다」라고 한다: ${섞임.join(' / ')}`)

  // **여러 개를 한꺼번에 낸다.** 하나만 내면 차례가 금방 바닥나고, 그게 원래 문제였다
  // (*"몇 가지밖에 없는데?"*). 총 개수만 재면 기능 열넷이 메워서 안 잡힌다 —
  // **이 함수가 내는 개수**를 직접 잰다(변이로 확인했다).
  assert.ok(섞임.length >= 2,
    `끝난 것도 남은 것도 있는데 ${섞임.length}가지만 말한다: ${섞임.join(' / ')}`)
  assert.ok(아직.length >= 2,
    `아직 안 나간 아침인데 ${아직.length}가지만 말한다: ${아직.join(' / ')}`)

  for (const t of [...빈날, ...아직, ...섞임]) {
    assert.ok(G.쓸수있나(t), `오늘 말이 문구 규칙을 어긴다: ${t}`)
  }
})

