// **카드가 열리면 달력이 옆으로 가고, 취소하면 원위치** (사용자 정정 2026-09-15).
//
// ── 두 번 고쳤다 ───────────────────────────────────────────────────────────
// ① 처음엔 카드가 열리면 달력이 **아래로 밀려 내려갔다.** 초안 카드가 세로로 400px 넘게
//    자라는데 그 위에 검색창이 있어서, 방금 누른 것과 달력 사이가 한 화면 넘게 벌어졌다.
// ② 그래서 **감췄다.** 그런데 감추니 카드 오른쪽 900px 이 통째로 비었고, *"예약을
//    만드는 중에 달력을 못 본다"* 는 원래 문제는 그대로 남았다(밀려난 것이 사라진 것이
//    될 뿐이다). 사용자 정정: *"내가 이 텅 빈 이곳에 오른쪽 모바일처럼 만들라고 했잖아."*
//
// ③ 지금은 **옆으로 옮기고 휴대폰과 같은 모습으로 접는다** — 칸에 점만, 누르면 그 아래 목록.
//
// ── 이 시험이 지키는 것 ────────────────────────────────────────────────────
//  · 접는 모습을 **두 벌로 만들지 않는다** — 휴대폰이 쓰던 길을 그대로 켠다
//  · **분기점이 1440 이 아니다** — 처음에 `wide` 로 걸었더니 1280·1413 화면에서
//    아무 일도 안 일어났다(사용자 사진이 그 폭이다)
//  · 달력을 **지우지 않는다** — 부품이 살아 있어야 취소했을 때 보던 달이 돌아온다
'use strict'

const test   = require('node:test')
const assert = require('node:assert/strict')
const fs     = require('node:fs')
const path   = require('node:path')

const ROOT = path.join(__dirname, '..', '..')
const 화면 = fs.readFileSync(
  path.join(ROOT, 'src/components/admin/sections/WeeklySchedule.jsx'), 'utf8')
const 코드만 = 화면.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')

test('긍정 앵커 — 카드가 열렸는지를 화면이 안다', () => {
  assert.match(코드만, /onDraftChange=\{set초안열림\}/,
    '검색창이 카드 열림을 안 알린다 — 이 시험의 전제다')
  assert.match(코드만, /const \[초안열림, set초안열림\] = useState\(false\)/, '상태가 없다')
})

test('**접는 모습을 두 벌로 만들지 않는다** — 휴대폰이 쓰던 길을 켠다', () => {
  assert.match(코드만, /const 접어보기 = 좁은화면 \|\| 초안열림/,
    '접어보기 판정이 없다 — 넓은 화면에서 휴대폰 모습을 못 켠다')
  // 점 찍기와 「고른 날 목록」이 **같은 판정**을 본다. 하나만 켜지면 점은 찍히는데
  // 누를 데가 없거나, 목록은 있는데 달력이 안 접힌다.
  assert.match(코드만, /점만=\{접어보기\}/, '칸이 접어보기를 안 본다')
  assert.match(코드만, /\{접어보기 && \(/, '고른 날 목록이 접어보기를 안 본다')
  assert.doesNotMatch(코드만, /점만=\{좁은화면\}/, '아직 좁은화면만 보고 있다')
})

test('**분기점이 laptop 이다** — wide(1440)로 걸면 1280·1413 에서 안 먹는다', () => {
  const m = /(\w+):grid-cols-\[minmax\(0,560px\)_minmax\(0,1fr\)\]/.exec(코드만)
  assert.ok(m, '두 칸 격자를 못 찾았다 — 카드 옆에 달력을 두는 자리다')
  assert.equal(m[1], 'laptop',
    `분기점이 ${m[1]} 다 — 사용자 화면(1280·1413)이 wide(1440) 아래라 아무 일도 안 일어난다`)
})

test('**달력을 감추지도 지우지도 않는다** — 취소하면 보던 달이 돌아와야 한다', () => {
  // `hidden` 으로 감추면 오른쪽이 비고, 걷어내면 이번 달로 튕긴다.
  assert.doesNotMatch(코드만, /초안열림 \? 'hidden'/,
    '달력을 다시 감추고 있다 — 감추면 카드 오른쪽이 통째로 빈다')
  assert.doesNotMatch(코드만, /초안열림 &&[\s\S]{0,40}viewMode/,
    '달력을 조건부로 걷어내고 있다 — 취소하면 이번 달로 튕긴다')
})

test('**조종간도 남는다** — 감추던 때 같이 감췄던 줄이다', () => {
  // 달력이 옆에 남으므로 「월·주·목록」·「이전/다음」도 남아야 한다.
  assert.doesNotMatch(코드만, /flex items-center gap-2 flex-wrap ' \+ \(초안열림 \? 'hidden'/,
    '보기 전환 줄이 아직 감춰진다 — 옆에 있는 달력을 못 넘긴다')
})
