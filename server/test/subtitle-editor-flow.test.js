'use strict'
// **자막 편집기의 흐름과 무게** (사용자 지시 2026-09-16).
//
// *"지금 작업 형태가 복잡해, 딱 자막 초안생성 - AI 고치기 - 확인 및 저장 이런 플로우로
//   설계할수 있도록 해줘"*
// *"저장화면도 연하게 나오니까 헷갈리잖아"*
// *"반응형으로 자막 고치면 옆으로 좀 늘어나서 편집하기 좀 쉬운 환경으로"*
//
// ── 이 시험이 지키는 것 ────────────────────────────────────────────────────
// 화면은 고치기 쉽고, 고치다 보면 **이유가 먼저 사라진다.** 여기 적는 것은 모양이 아니라
// **왜 그 모양이어야 하는가**다:
//   · 단계가 셋이고 **막지 않는다** — 막으면 한 줄 고치러 온 사람이 처음부터 해야 한다.
//   · 마무리 단추가 **가장 진하다** — 이 단추를 눌러야 홀 화면에 나간다.
//   · 이미 있는 자막은 **확인 단계**에서 연다 — 만들 것이 없는데 「초안 만들기」를 띄우면
//     *"처음부터 다시 만들라"* 로 읽힌다(이 화면이 예전에 그래서 지적을 받았다).
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const ROOT = path.join(__dirname, '..', '..')
const SRC = fs.readFileSync(
  path.join(ROOT, 'src/components/admin/sections/subtitleEditorModal.jsx'), 'utf8')
const 코드만 = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

test('**단계가 셋이고 사용자가 말한 순서 그대로다**', () => {
  const m = /const 단계표 = \[([\s\S]*?)\n\]/.exec(코드만)
  assert.ok(m, '단계표를 못 찾았다 — 이 시험의 전제가 무너졌다')
  const 표 = m[1]

  // 순서가 뜻이다. 「AI 고치기」가 「초안 만들기」보다 앞서면 고칠 것이 없다.
  const 자리 = (t) => 표.indexOf(t)
  assert.ok(자리('초안 만들기') >= 0, '① 초안 만들기가 없다')
  assert.ok(자리('AI 로 고치기') >= 0, '② AI 로 고치기가 없다')
  assert.ok(자리('확인하고 저장') >= 0, '③ 확인하고 저장이 없다')
  assert.ok(자리('초안 만들기') < 자리('AI 로 고치기'), '초안보다 AI 고치기가 먼저다')
  assert.ok(자리('AI 로 고치기') < 자리('확인하고 저장'), 'AI 고치기보다 확인이 먼저다')

  assert.equal((표.match(/번호:/g) || []).length, 3, '단계가 셋이 아니다')
})

test('**단계를 막지 않는다** — 아무 단계나 눌러 옮길 수 있다', () => {
  // 막으면 「이미 다 된 자막의 한 줄만 고치려는 사람」이 길을 잃는다.
  assert.match(코드만, /단계표\.map\(\(칸\)[\s\S]{0,400}?onClick=\{\(\) => \{ set단계\(칸\.번호\)/,
    '단계 머리줄의 칸이 눌리지 않는다 — 앞뒤로 못 간다')
  assert.ok(!/disabled=\{단계 [<>]/.test(코드만),
    '단계를 순서대로만 가게 막았다 — 한 줄 고치러 온 사람이 처음부터 해야 한다')
})

test('**마무리 단추가 가장 진하다** — 연하면 무엇이 끝인지 안 보인다', () => {
  // **단추 자체에 건다.** 글자 「방송에 쓰기」로 찾으면 안내문("…「방송에 쓰기」를
  // 누르세요")이 먼저 걸린다 — 실제로 그랬다. 단추는 `save(true)` 를 부르는 것 하나뿐이다.
  const i = 코드만.indexOf('onClick={() => save(true)}')
  assert.ok(i > 0, '마무리 단추(save(true))를 못 찾았다 — 이 시험의 전제가 무너졌다')
  const 단추 = 코드만.slice(i, i + 500)

  // 앞 판은 `bg-ds-v3-ink-3`(흐린 회색)이라 옆의 보조 단추와 같은 무게로 보였다.
  assert.ok(!/bg-ds-v3-ink-3[^-]/.test(단추),
    '마무리 단추가 흐린 회색이다 — 옆 단추들과 무게가 같아 보인다')
  assert.match(단추, /bg-ds-v3-tts/, '마무리 단추에 주 색이 없다')
})

test('**이미 있는 자막은 확인 단계에서 연다** — 처음부터 만들라고 하지 않는다', () => {
  // 저장된 자막을 불러온 직후 단계를 3으로 옮겨야 한다.
  const i = 코드만.indexOf('setSaved(true)')
  assert.ok(i > 0, '불러오기 자리를 못 찾았다')
  const 뒤 = 코드만.slice(i, i + 300)
  assert.match(뒤, /set단계\(3\)/,
    '저장된 자막을 열었는데 ①「초안 만들기」로 시작한다 — 만들 것이 없다')
})

test('**초안이 생기면 스스로 다음 단계로 간다** — 한 번 더 누르게 하지 않는다', () => {
  // 받아쓰기: 글자가 틀릴 수 있으니 ②로. 정본을 맞춰 왔으면 글자가 맞으니 ③으로.
  assert.match(코드만, /set단계\(r\.canonical \? 3 : 2\)/,
    '받아쓰기 뒤에 단계가 안 넘어간다')
  // 기본 문구는 정본이라 AI 로 고칠 것이 없다 — 바로 ③.
  const i = 코드만.indexOf("setSource('manual')")
  assert.ok(i > 0, '기본 문구 불러오기 자리를 못 찾았다')
  assert.match(코드만.slice(i, i + 200), /set단계\(3\)/,
    '기본 문구를 불러왔는데 AI 고치기 단계로 간다 — 정본이라 고칠 것이 없다')
})

test('**옆으로 넓게 열린다** — 자막 한 줄이 한 줄로 보여야 길이를 가늠한다', () => {
  // `max-w-5xl`(1024px)로는 글자 칸과 미리보기가 둘 다 좁아 한 줄이 접혔다.
  assert.match(코드만, /width="max-w-\[1[0-9]{3}px\]/, '모달이 아직 좁다')
  // 글자 칸이 미리보기보다 넓어야 한다 — 반반이면 긴 줄이 접힌다.
  assert.match(코드만, /laptop:grid-cols-\[minmax\(0,1\.\d+fr\)_minmax\(0,1fr\)\]/,
    '넓은 화면에서 글자 칸을 더 주지 않는다')
  // 좁은 화면에서는 위아래로 쌓인다(가로 스크롤이 생기면 안 된다).
  assert.match(코드만, /grid-cols-1 laptop:grid-cols-/, '좁은 화면에서 한 줄로 안 쌓인다')
})
