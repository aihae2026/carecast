  // 발표에서 가장 먼저 잘리는 장이다. 자르면 질문으로 나왔을 때 방어하는 모양이 된다.
  assert.match(슬라이드, /한계 — \*\*줄이지 않습니다\*\*/, '한계 장이 사라졌다')
