// 휴대폰의 간편화면 — **탭 숨김 · 여백 대칭 · 네 단추 균형** (사용자 지시 2026-09-14).
//
// ── 사진에서 드러난 것 ───────────────────────────────────────────────────────
// ① 탭 다섯이 좁은 화면에서 한 줄을 통째로 써서 머리줄이 두 줄이 됐다.
// ② 입력창·제목이 **왼쪽으로 치우쳐** 보였다.
// ③ 네 단추가 **셋 + 하나**로 갈라져 「순서」만 아래 줄에 덩그러니 남았다.
//
// ── 원인 ─────────────────────────────────────────────────────────────────────
// ②가 특히 엉뚱한 자리였다. `<main>` 이 서랍 손잡이 자리로 **`pr-8` 만** 줬는데, 안쪽은
// `mx-auto` 가운데 맞춤이라 **남은 폭의 가운데**에 선다 — 결과는 전체가 16px 왼쪽으로
// 밀린 화면이다(430px 실측: 제목 left 0 / right 32). 한 기종용 오프셋이 아니라 **대칭**으로
// 푼다 — 어느 폭에서도 가운데가 맞는다.
//
// ③은 라벨이 첫 줄을 갉아먹어 줄바꿈 자리가 폭에 따라 들쭉날쭉한 것이었다. 좁은 화면에서는
// **격자로 못 박아** 언제나 2+2 로 맞춘다.
//
// ── 권한을 막는 것이 아니다 ──────────────────────────────────────────────────
// 탭을 숨기는 것은 **입구 하나**를 빼는 것이다. PC 메뉴·상세 경로는 그대로이고 주소를 알면
// 휴대폰에서도 들어간다. 간편모음(서랍)은 그대로 있어 휴대폰에서도 쓸 수 있다.
'use strict'

const test   = require('node:test')
const assert = require('node:assert/strict')
const fs     = require('node:fs')
const path   = require('node:path')

const ROOT  = path.join(__dirname, '..', '..')
const 읽기  = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8')
const 코드만 = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

const SHELL = 코드만(읽기('src/components/home/HomeShell.jsx'))
const ASK   = 코드만(읽기('src/components/shared/QuickSchedulePhrase.jsx'))

test('손잡이 자리를 **양쪽에 같이** 준다 — 한쪽만 주면 내용이 치우친다', () => {
  const m = SHELL.match(/onToggleDrawer \? '([^']*)'/)
  assert.ok(m, '손잡이 자리를 주는 곳을 못 찾았다')
  assert.doesNotMatch(m[1], /(^|\s)pr-\d/,
    `오른쪽에만 자리를 준다 — mx-auto 가운데 맞춤이라 전체가 왼쪽으로 밀린다: "${m[1]}"`)
  assert.match(m[1], /(^|\s)px-\d/, `대칭 여백이 아니다: "${m[1]}"`)
})

// ── 2026-09-15: 이제 **휴대폰에도 탭 줄을 그린다** (사용자 결정, 앞 판 뒤집음) ───────
// 2026-09-14 에는 숨겼다. 이유는 *"탭 다섯이 좁은 화면에서 한 줄을 통째로 쓰면서
// 머리줄을 두 줄로 만든다"* 였다(실측: 다섯 칸 423px > 쓸 수 있는 358px).
// **그 이유가 없어졌다** — 탭이 둘이면 이름표 옆에 같은 줄로 앉는다.
//
// 대가로 치르던 것이 컸다: 탭 줄이 없어서 **휴대폰에는 캘린더로 갈 입구가 없었다.**
// 그래서 이 시험이 지키는 사실도 뒤집힌다 — 「숨겼는가」가 아니라
// **「머리줄이 한 줄로 유지되는가」**다. 그게 원래 지키려던 것이었다.
test('휴대폰에서도 탭 줄이 보이고, **머리줄은 한 줄**로 남는다', () => {
  const i = SHELL.indexOf('aria-label="화면"')
  assert.ok(i > 0, '긍정 앵커 — 탭 줄을 못 찾았다')
  const 앞 = SHELL.slice(Math.max(0, i - 400), i)
  assert.doesNotMatch(앞, /hidden tablet:flex/,
    '휴대폰에서 탭 줄을 다시 숨겼다 — 그러면 캘린더로 갈 입구가 없어진다(2026-09-15 결정)')
  // **제 줄을 통째로 쓰면 안 된다.** `w-full` 이면 이름표 아래로 내려가 머리줄이 두 줄이 된다.
  assert.doesNotMatch(앞, /w-full/,
    '탭 줄이 좁은 화면에서 제 줄을 통째로 쓴다 — 머리줄이 두 줄이 되고, 그게 처음에 숨긴 이유였다')

  // **좁은 화면에 나오는 탭이 둘일 때만** 같은 줄에 들어간다(다섯이면 423px 로 넘친다).
  //
  // 2026-09-15 오후 정정: 목록은 **다섯 그대로**이고 셋은 CSS 로 감춘다
  // (*"저건 모바일에서만 적용하라고"*). 그래서 세는 것은 **목록 길이가 아니라
  // 좁은 화면에 남는 개수**다 — `폰에도: true` 가 붙은 것만 센다.
  // 목록 길이로 세면 이 시험이 넓은 화면 사정 때문에 빨간불이 되어, 고치려다
  // 휴대폰 규칙을 망가뜨리게 된다.
  const 폰개수 = (SHELL.match(/폰에도: true/g) || []).length
  assert.equal(폰개수, 2,
    `좁은 화면에 남는 탭이 ${폰개수}개다 — 셋 이상이면 이름표 옆에 못 앉는다. `
    + '늘릴 거면 실제 폭을 다시 재고 이 시험을 같이 고칠 것')
  // 나머지는 **감춰야** 한다. 감추는 규칙이 없으면 다섯이 그대로 나온다.
  assert.match(SHELL, /hidden tablet:inline-flex/,
    '좁은 화면에서 나머지 탭을 감추는 규칙이 없다')

  // **경로까지 지우면 안 된다** — 줄인 것은 입구 개수이지 화면이 아니다
  assert.match(SHELL, /TABS\.map/, '탭 목록 자체를 지웠다 — PC 에서도 못 간다')
})

test('네 단추는 좁은 화면에서 **2×2 격자**다 — 하나만 떨어지지 않는다', () => {
  // **앵커가 옮겨졌다**(2026-09-15): 「지금/나중에」로 묶으면서 `묶음.단추.map` 이 됐다.
  const i = ASK.indexOf('묶음.단추.map')
  assert.ok(i > 0, '빠른 단추를 그리는 자리를 못 찾았다')
  const 앞 = ASK.slice(Math.max(0, i - 400), i)
  assert.match(앞, /grid-cols-2/, '좁은 화면에서 줄바꿈이 폭에 따라 들쭉날쭉해진다')
  assert.match(앞, /tablet:flex/, '넓은 화면에서도 격자로 굳었다 — 한 줄로 늘어놔야 한다')
})

test('라벨이 단추 줄을 갉아먹지 않는다 — 제 줄로 올린다', () => {
  // 라벨이 **둘로 갈렸다**(2026-09-15) — 「지금 바로」와 「나중에」. 앞의 것을 본다.
  const i = ASK.indexOf('{묶음.이름}</span>')
  assert.ok(i > 0, '라벨을 못 찾았다')
  // **창을 300 → 700 으로 넓혔다**(2026-09-15). 묶음 껍데기의 `className` 이 조건부로
  // 길어져서(`gi > 0` 일 때 선을 긋는다) `flex-col` 이 300자 밖으로 밀렸다.
  // **고정 창으로 소스를 자르는 것**은 이 저장소가 조심하는 모양이라
  // (`feedback_carecast_fake_oracle`), 넓힌 사실을 적어 둔다 — 이 시험이 지키려는 것은
  // 「라벨이 단추와 같은 줄에 있지 않다」이고 그것은 그대로다.
  const 앞 = ASK.slice(Math.max(0, i - 700), i)
  assert.match(앞, /flex-col/, '라벨이 단추와 같은 줄에 있다 — 첫 줄이 좁아져 배치가 갈린다')
})
