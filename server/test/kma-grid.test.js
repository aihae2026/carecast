'use strict'
// UX-08 — 위경도 ↔ 기상청 격자 (2026-09-11).
//
// **알려진 점으로 고정한다.** 도법 상수 하나를 잘못 건드리면 전국이 조용히 몇 칸씩
// 밀리고, 화면에는 그럴듯한 숫자가 나온다 — 날씨가 "틀린 줄 모르게" 틀리는 모양이다.
const test = require('node:test')
const assert = require('node:assert/strict')
const {
  격자로, 위경도로, 격자범위밖, 가까운자외선관측소, 거리km, 자외선관측소,
} = require('../../src/lib/kmaGrid.js')

// **널리 인용되는 쌍만 쓴다.** 처음에 부산·대구 값을 기억으로 적었다가 틀렸다 —
// 구현이 아니라 기대값이 틀린 것이었다(EV-004531·EV-004532). 오라클을 지어내면
// 구현을 되풀이하는 테스트가 되거나, 맞는 구현을 틀렸다고 하게 된다(헌장 §M8·§M9).
const 알려진점 = [
  { 이름: '서울(종로)', 위도: 37.5729, 경도: 126.9794, nx: 60, ny: 127 },
  { 이름: '서울(중구)', 위도: 37.5636, 경도: 126.9976, nx: 60, ny: 127 },
  { 이름: '제주(제주시)', 위도: 33.4996, 경도: 126.5312, nx: 53, ny: 38 },
]

test('널리 알려진 지점의 격자가 맞는다', () => {
  for (const p of 알려진점) {
    const g = 격자로(p.위도, p.경도)
    assert.deepEqual(g, { nx: p.nx, ny: p.ny }, `${p.이름} 격자가 어긋났다`)
  }
})

test('격자가 남쪽·동쪽으로 갈수록 제대로 움직인다', () => {
  // 절대값을 모르는 지점은 **관계**로 본다. 남쪽이면 ny 가 작고, 동쪽이면 nx 가 크다.
  const 서울 = 격자로(37.5729, 126.9794)
  const 부산 = 격자로(35.1028, 129.0403)
  const 강릉 = 격자로(37.7515, 128.8910)
  assert.ok(부산.ny < 서울.ny, '부산이 서울보다 북쪽으로 나온다')
  assert.ok(부산.nx > 서울.nx, '부산이 서울보다 서쪽으로 나온다')
  assert.ok(강릉.nx > 서울.nx && 강릉.ny > 서울.ny, '강릉이 서울 북동쪽이 아니다')
})

test('격자 → 위경도 → 격자 가 제자리로 돌아온다', () => {
  for (const p of 알려진점) {
    const { 위도, 경도 } = 위경도로(p.nx, p.ny)
    assert.deepEqual(격자로(위도, 경도), { nx: p.nx, ny: p.ny }, `${p.이름} 왕복이 안 맞는다`)
    // 격자 중심이라 원래 좌표와 조금 다르다. 5km 격자이므로 4km 안이면 같은 칸이다.
    assert.ok(거리km(위도, 경도, p.위도, p.경도) < 4, `${p.이름} 되돌린 좌표가 너무 멀다`)
  }
})

// ⚠ **격자 두 칸 차이는 10km 가까이 된다** — 2026-09-11 이 변환을 만들면서 드러났다.
//
// 예전 설정 화면은 격자 숫자를 사람이 외워 넣게 했고, 안내하던 숫자가 실제 시설 좌표의 격자와
// 두 칸(약 9km) 어긋나 있었다. 5km 격자라 예보 구역이 같을 때가 많아 아무도 눈치채지 못했다.
// 이 시험은 그 사실(작은 숫자 차이가 먼 거리)을 일반 좌표로 고정해, 격자를 손으로 적지 말고
// 좌표에서 계산해야 하는 이유를 남긴다. (공개판에서는 시설 위치를 일반 좌표로 바꿨다.)
test('격자 숫자가 두 칸만 달라도 5km 넘게 떨어진 곳이다 — 격자는 좌표에서 계산한다', () => {
  const 서울 = 격자로(37.5729, 126.9794)
  const 두칸옆 = 위경도로(서울.nx - 2, 서울.ny)
  assert.ok(거리km(두칸옆.위도, 두칸옆.경도, 37.5729, 126.9794) > 5,
    '두 칸 차이가 같은 격자 안이면 이 경고는 필요 없다')
})

test('범위 밖 격자는 범위 밖이라고 말한다', () => {
  assert.equal(격자범위밖(60, 127), null)
  assert.match(격자범위밖(0, 127), /범위/)
  assert.match(격자범위밖(60, 999), /범위/)
  // 빈 칸은 "범위를 벗어났다"가 아니라 "안 넣었다" 여야 한다 — 아직 아무것도 안 넣은
  // 사람에게 범위 얘기를 하면 무슨 뜻인지 모른다.
  assert.match(격자범위밖('', 127), /안 넣었/)
  assert.match(격자범위밖(60, '  '), /안 넣었/)
  assert.match(격자범위밖('가나다', 127), /숫자/)
  assert.match(격자범위밖(NaN, 1), /숫자/)
})

test('가까운 자외선 관측소를 고르고, 멀면 멀다고 말한다', () => {
  const 수원 = 가까운자외선관측소(37.2636, 127.0286)   // 수원시청 부근(일반 예시 좌표)
  assert.equal(수원.stn, '119', '수원시청 부근에서 가장 가까운 곳은 수원 관측소다')
  assert.equal(수원.멀다, false)

  const 광주 = 가까운자외선관측소(35.1595, 126.8526)
  assert.equal(광주.멀다, true, '목록이 넷뿐이라 광주는 멀다 — 그 사실을 숨기면 안 된다')
})

test('관측소 목록은 화면이 안내하던 넷 그대로다 — 확인 못 한 지점을 넣지 않았다', () => {
  assert.deepEqual(자외선관측소.map(s => s.stn).sort(), ['105', '108', '119', '159'])
})

// ── 화면: 남의 좌표를 기본값으로 두지 않는다 ────────────────────────────
const fs = require('node:fs')
const path = require('node:path')
const 날씨화면 = fs.readFileSync(
  path.join(__dirname, '..', '..', 'src/components/admin/sections/apiSettingsWeather.jsx'), 'utf8')

test('설정 칸이 어느 시설의 값으로도 미리 차 있지 않다 — 그대로 저장하면 남의 날씨를 방송한다', () => {
  // 긍정 앵커 — 감시할 상태 선언이 이 파일에 있다.
  assert.match(날씨화면, /const \[nx,\s*setNx\]\s*=\s*useState\(/, 'nx 상태를 못 찾았다 — 이 가드를 옮길 것')
  // 예전엔 처음 운영한 시설의 격자·관측소·법정동 코드가 초기값이었다. 특정 옛값을 나열하는 대신
  // **빈칸으로 시작하는지**를 본다 — 어느 시설 값이 새로 들어와도 잡힌다.
  for (const 이름 of ['nx', 'ny', 'uvStn', 'areaNo', 'uvAreaNo']) {
    const m = new RegExp(`set${이름[0].toUpperCase()}${이름.slice(1)}\\]\\s*=\\s*useState\\(([^)]*)\\)`).exec(날씨화면)
    assert.ok(m, `${이름} 상태 선언을 못 찾았다 — 이 가드를 옮길 것`)
    assert.equal(m[1].trim(), "''", `${이름} 초기값이 빈칸이 아니다(${m[1]}) — 남의 시설 값을 심지 않는다`)
  }
})

test('화면이 이 변환 모듈을 쓴다 — 사람이 격자 숫자를 직접 알아내지 않게', () => {
  assert.match(날씨화면, /from '\.\.\/\.\.\/\.\.\/lib\/kmaGrid'/, '변환 모듈을 안 쓴다')
  assert.match(날씨화면, /격자로\(/, '좌표로 격자를 계산하지 않는다')
  assert.match(날씨화면, /위경도로\(/, '넣은 격자가 어디인지 되짚어 볼 길이 없다')
  assert.match(날씨화면, /가까운자외선관측소\(/, '관측소 번호를 여전히 사람이 찾아야 한다')
})
