// ── 2026-09-15: **차임벨 단추가 진짜로 소리를 낸다** (사용자 결정) ─────────────────
// 09-14 지시는 *"차임벨을 독립 실행 모드로 만들지 마라 — 설정 패널만"* 이었고, 그때
// 패널은 *"지금 소리가 나지는 않습니다"* 라고 적었다. **09-15 에 뒤집혔다**:
// *"진짜 소리나는 시작차임, 종료차임 이걸로 소리나가는걸로 바꿨으면 좋겠고"*.
//
// 그러면 **문구가 정반대가 되어야 한다.** 이 자리는 전관 스피커로 나가는 단추라,
// 옛 문구("소리가 나지 않습니다")가 한 줄이라도 남으면 사람이 모르고 누른다.
// ── 2026-09-15(2차): **글자가 아니라 돌려서 본다** (V③ UI-0915-R1 지적) ──────────
// 앞 판은 `fireChime` 이라는 **이름이 파일에 있는지**만 봤다. 검수관이 실제 호출을
// `await Promise.resolve()` 로 바꿔치고도 8건이 전부 통과하는 것을 보였다 — 가짜 오라클이다.
// 이름은 `import` 줄에만 남아 있어도 충족된다.
//
// 그래서 **제품 핸들러를 떼어 실제로 돌린다.** 누르면 진짜로 창구를 부르는지,
// 도는 중에 또 눌러도 안 나가는지, 실패를 말하는지를 값으로 본다.
function 발사환경() {
  const 코드 = 카드.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
  const i = 코드.indexOf('const 차임내보내기 = async (종류) => {')
  assert.ok(i > 0, '긍정 앵커 — 차임 발사 핸들러를 못 찾았다')
  let 깊이 = 0, 끝 = -1
  const 여는곳 = 코드.indexOf('{', 코드.indexOf('=>', i))
  for (let k = 여는곳; k < 코드.length; k++) {
    if (코드[k] === '{') 깊이++
    else if (코드[k] === '}') { 깊이--; if (깊이 === 0) { 끝 = k; break } }
  }
  assert.ok(끝 > 여는곳, '핸들러의 끝을 못 찾았다')
  const 몸통 = 코드.slice(여는곳 + 1, 끝)

  const st = { 보내는중: null, 오류: '', 부른것: [] }
  let 풀기, 던지기
  const env = {
    set차임보내는중: (v) => { st.보내는중 = v },
    set차임오류: (v) => { st.오류 = v },
    fireChime: (종류) => {
      st.부른것.push(종류)
      return new Promise((res, rej) => { 풀기 = res; 던지기 = rej })
    },
  }
  // ── **리액트처럼 굳혀서 준다** (V③ UI-0915-R3 지적) ──────────────────────────
  // 앞 판은 `차임보내는중` 을 **살아 있는 getter** 로 줬다. 그래서 제품이 상태를 읽든
  // ref 를 읽든 시험은 초록이었다 — 그런데 **리액트에서 상태는 그 렌더의 값으로 굳는다.**
  // 손가락이 다시 그려지기 전에 두 번 닿으면 둘 다 `null` 을 읽고 **둘 다 나간다.**
  // 시험이 그것을 못 봤다(검수관이 짚었다).
  //
  // 그래서 **상태는 굳혀 주고 ref 만 살려 준다** — 리액트가 실제로 그렇게 준다.
  // 이제 제품이 상태로 막으면 이 시험이 **빨간불**을 낸다.
  // (이 저장소는 반대 방향으로도 한 번 데였다 — 살아 있는 값을 줘서 가드가 초록으로 보인 일.)
  const ref = { current: null }
  const 창 = {}
  for (const k of Object.keys(env)) Object.defineProperty(창, k, { get: () => env[k] })
  창.차임보내는중 = null                       // **굳은 값** — 누른 순간의 렌더 값이다
  Object.defineProperty(창, '차임보내는중Ref', { get: () => ref })
  const f = new Function('창', `with (창) { return (async (종류) => {${몸통}}) }`)(창)
  // 「다시 그려졌다」를 시험이 명시적으로 일으킨다 — 안 부르면 굳은 값 그대로다.
  const 다시그리기 = () => { 창.차임보내는중 = st.보내는중 }
  return { st, ref, 다시그리기, 누르기: f, 끝내기: () => 풀기?.(), 실패로: (e) => 던지기?.(e) }
}

