// ── 2026-09-15(3차): **빗장은 `ref` 여야 한다** (V③ UI-0915-R3) ─────────────────
// 위 두 행동 시험이 이것을 이미 값으로 잡는다. 이 시험은 **왜 그래야 하는지를 이름으로**
// 남긴다 — 다음 사람이 "상태로도 되는데 왜 ref 지" 하고 되돌리지 않게.
test('**빗장은 ref 다** — 상태는 그 렌더의 값으로 굳어 연타를 못 막는다', () => {
  const 코드 = 카드.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
  const i = 코드.indexOf('const 차임내보내기')
  assert.ok(i > 0, '긍정 앵커 — 차임 발사 핸들러가 있다')
  const 몸통 = 코드.slice(i, i + 900)
  assert.match(몸통, /if \(차임보내는중Ref\.current\) return/,
    '빗장이 ref 가 아니다 — 리액트 상태는 **그 렌더의 값으로 굳어서**, 다시 그리기 전에 '
    + '두 번 누르면 둘 다 통과한다(페르소나 P3「두 번 누르는 시설장」)')
  assert.match(몸통, /set차임오류/,
    '실패를 안 알린다 — 조용한 실패가 이 저장소에서 가장 비싼 실패다')
  // 끝나면 반드시 푼다 — 안 풀면 그 뒤로 차임 단추가 영영 안 먹는다.
  assert.match(코드.slice(i, i + 1400), /차임보내는중Ref\.current = null/,
    '끝난 뒤 빗장을 안 푼다 — 한 번 끼면 그 뒤로 차임을 못 보낸다')
})
